#!/usr/bin/env python3
"""Write a C source embedding compiled SPIR-V blobs and a name->blob table.

Usage: embed_shaders.py OUT_C SPV...

Each SPV path becomes a `static const unsigned char s_<sym>[]` array, 16
bytes per line, where <sym> is the file name with every character outside
[A-Za-z0-9_] replaced by '_' and a leading digit prefixed with '_' (CMake's
string(MAKE_C_IDENTIFIER)). The table `g_rhi_embedded_shaders` lists the
blobs in argument order with their file names and byte counts, and
`g_rhi_embedded_shader_count` its length; rhi_embedded_shaders.h declares
both.
"""

import os
import re
import sys

HEADER = ('/* AUTO-GENERATED by embed_shaders.py - do not edit. */\n'
          '#include "rhi_embedded_shaders.h"\n\n')
BYTES_PER_ROW = 16


def c_identifier(name):
    """Return `name` as a C identifier, by the rule of MAKE_C_IDENTIFIER."""
    sym = re.sub(r"[^A-Za-z0-9_]", "_", name)
    return "_" + sym if re.match(r"[0-9]", sym) else sym


def blob_rows(data):
    """Return `data` as initializer rows of BYTES_PER_ROW hex bytes."""
    return "".join(
        "    " + ",".join("0x%02x" % b for b in data[i:i + BYTES_PER_ROW]) + ",\n"
        for i in range(0, len(data), BYTES_PER_ROW))


def generate(spv_paths):
    """Return the generated C source for the SPIR-V files in `spv_paths`."""
    body = [HEADER]
    table = []
    for path in spv_paths:
        name = os.path.basename(path)
        sym = c_identifier(name)
        with open(path, "rb") as fh:
            data = fh.read()
        body.append("static const unsigned char s_%s[] = {\n%s};\n" % (sym, blob_rows(data)))
        table.append('    { "%s", s_%s, %du },\n' % (name, sym, len(data)))
    body.append("\nconst rhi_embedded_shader g_rhi_embedded_shaders[] = {\n%s};\n"
                % "".join(table))
    body.append("const unsigned g_rhi_embedded_shader_count =\n"
                "    (unsigned)(sizeof(g_rhi_embedded_shaders) / sizeof(g_rhi_embedded_shaders[0]));\n")
    return "".join(body).encode("ascii")


def main(argv):
    if len(argv) < 2:
        sys.stderr.write("usage: embed_shaders.py OUT_C SPV...\n")
        return 2
    out = argv[0]
    text = generate(argv[1:])
    tmp = out + ".tmp"
    with open(tmp, "wb") as fh:
        fh.write(text)
    os.replace(tmp, out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
