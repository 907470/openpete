/* The byte is clamped to 0..255. The small motor is on or off: the measured
 * intensity is 1.0 when bit 0 of the byte is set and 0.0 otherwise. The large
 * motor reads the measured intensity for the byte from a 256-entry table of
 * single-precision bit patterns. Documented in openpete_rumble.h. */
float openpete_rumble_response(int raw_byte, int is_small)
{
    int b = raw_byte < 0 ? 0 : (raw_byte > 255 ? 255 : raw_byte);
    if (is_small)
        return (b & 1) ? 1.0f : 0.0f;
    float v;
    memcpy(&v, &k_large_bits[b], sizeof v);
    return v;
}
