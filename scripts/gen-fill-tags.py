#!/usr/bin/env python3
"""Regenerate games/spyro-1/renderer/terrain_fill_tags.h from the frozen,
human-reviewed verdicts in tests/freecam/fill-tags.verdicts.

Only FILL rows are emitted — absence means "not a fill face". Run after any
verdict change and commit both files together:
    python3 scripts/gen-fill-tags.py
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERDICTS = f"{ROOT}/tests/freecam/fill-tags.verdicts"
OUT = f"{ROOT}/games/spyro-1/renderer/terrain_fill_tags.h"

# g_LevelId scheme: tens = homeworld, units = HOME(0)/levels(1-3)/boss(4)/flight(5)
LEVEL_ID = {
    "artisans": 10, "stone_hill": 11, "dark_hollow": 12, "town_square": 13,
    "toasty": 14, "sunny_flight": 15, "peace_keepers": 20, "dry_canyon": 21,
    "cliff_town": 22, "ice_cavern": 23, "doctor_shemp": 24, "night_flight": 25,
    "magic_crafters": 30, "alpine_ridge": 31, "high_caves": 32, "wizard_peak": 33,
    "blowhard": 34, "crystal_flight": 35, "beast_makers": 40, "terrace_village": 41,
    "misty_bog": 42, "tree_tops": 43, "metalhead": 44, "wild_flight": 45,
    "dream_weavers": 50, "dark_passage": 51, "lofty_castle": 52,
    "haunted_towers": 53, "jacques": 54, "icy_flight": 55, "gnorc_gnexus": 60,
    "gnorc_cove": 61, "twilight_harbor": 62, "gnasty_gnorc": 63, "gnastys_loot": 64,
}

rows = []
for line in open(VERDICTS):
    m = re.match(r"FILL\s+(\S+) (\d+) (\d+) (\d+)", line)
    if m:
        rows.append((LEVEL_ID[m.group(1)], int(m.group(2)), int(m.group(3)), m.group(1)))
rows.sort()

with open(OUT, "w") as f:
    f.write(f"""/* Generated by scripts/gen-fill-tags.py from tests/freecam/fill-tags.verdicts
 * — do not hand-edit; change the verdicts file and regenerate.
 *
 * The frozen LP fill-face list: faces whose authored LP covers sightlines no
 * authored HP covers (measured og-orig vs og-sat coverage, per-face strip
 * review). Keyed on (g_LevelId, sector index, LP face index); absence means
 * "not a fill face". */
#ifndef TERRAIN_FILL_TAGS_H
#define TERRAIN_FILL_TAGS_H

typedef struct {{ unsigned short level, sec, face; }} tft_entry_t;

static const tft_entry_t k_terrain_fill_tags[{len(rows)}] = {{
""")
    prev = None
    for lvl, sec, face, name in rows:
        if name != prev:                       # one banner per level, not per row
            f.write(f"{'' if prev is None else chr(10)}    /* {name} */\n")
            prev = name
        f.write(f"    {{ {lvl:2d}, {sec:3d}, {face:2d} }},\n")
    f.write("""};

#endif /* TERRAIN_FILL_TAGS_H */
""")
print(f"{len(rows)} FILL entries -> {os.path.relpath(OUT, ROOT)}")
