local ffi = require 'ffi'
local fp = io.open(CFG.csv_path, 'w')
fp:write('frame,engine,op,vidx,'
    ..'Vx,Vy,Vz,'
    ..'TRx,TRy,TRz,'
    ..'RT00,RT01,RT02,RT10,RT11,RT12,RT20,RT21,RT22,'
    ..'OFX,OFY,H,DQA,DQB,'
    ..'MAC0,MAC1,MAC2,MAC3,IR0,IR1,IR2,IR3,'
    ..'SZ0,SZ1,SZ2,SZ3,'
    ..'SXY0,SXY1,SXY2,'
    ..'RGB0,RGB1,RGB2,'
    ..'FLAG\n')
fp:flush()

local frame = 0
local press_release = {}  -- map frame -> button to release

local function lo16(w)
    local m = bit.band(w, 0xFFFF)
    return bit.band(m, 0x8000) ~= 0 and (m - 0x10000) or m
end
local function hi16(w)
    local m = bit.band(bit.rshift(w, 16), 0xFFFF)
    return bit.band(m, 0x8000) ~= 0 and (m - 0x10000) or m
end
local function s32(w)
    return bit.band(w, 0x80000000) ~= 0
       and (bit.tobit(w))
        or w
end

local function dump_post(op_label, vidx, V, regs)
    local cp2d, cp2c = regs.CP2D.r, regs.CP2C.r
    fp:write(string.format(
        '%d,pcsx,%s,%d,'
        ..'%d,%d,%d,'
        ..'%d,%d,%d,'
        ..'%d,%d,%d,%d,%d,%d,%d,%d,%d,'
        ..'%d,%d,%d,%d,%d,'
        ..'%d,%d,%d,%d,%d,%d,%d,%d,'
        ..'%u,%u,%u,%u,'
        ..'0x%08X,0x%08X,0x%08X,'
        ..'0x%08X,0x%08X,0x%08X,'
        ..'0x%08X\n',
        frame, op_label, vidx,
        V[1], V[2], V[3],
        s32(cp2c[5]), s32(cp2c[6]), s32(cp2c[7]),
        lo16(cp2c[0]), hi16(cp2c[0]), lo16(cp2c[1]),
        hi16(cp2c[1]), lo16(cp2c[2]), hi16(cp2c[2]),
        lo16(cp2c[3]), hi16(cp2c[3]), lo16(cp2c[4]),
        s32(cp2c[24]), s32(cp2c[25]), bit.band(cp2c[26], 0xFFFF),
        lo16(cp2c[27]), s32(cp2c[28]),
        s32(cp2d[24]), s32(cp2d[25]), s32(cp2d[26]), s32(cp2d[27]),
        lo16(cp2d[8]), lo16(cp2d[9]), lo16(cp2d[10]), lo16(cp2d[11]),
        bit.band(cp2d[16], 0xFFFF), bit.band(cp2d[17], 0xFFFF),
        bit.band(cp2d[18], 0xFFFF), bit.band(cp2d[19], 0xFFFF),
        cp2d[12], cp2d[13], cp2d[14],
        cp2d[20], cp2d[21], cp2d[22],
        cp2c[31]))
end

local function read_word(va)
    local mem = PCSX.getMemPtr()
    return ffi.cast('uint32_t*', mem + bit.band(va, 0x1FFFFFFF))[0]
end

local function snapshot_v(cp2d, idx)
    -- Return {Vx,Vy,Vz} as int16 for V0/V1/V2 (idx 0,1,2). For idx -1 returns 0,0,0.
    if idx < 0 or idx > 2 then return {0, 0, 0} end
    local i = idx * 2
    return {lo16(cp2d[i]), hi16(cp2d[i]), lo16(cp2d[i+1])}
end

local function emit_for_func(func, regs)
    local cp2d = regs.CP2D.r
    if func == 0x01 then
        dump_post('RTPS', 0, snapshot_v(cp2d, 0), regs)
    elseif func == 0x30 then
        dump_post('RTPT_v0', 0, snapshot_v(cp2d, 0), regs)
        dump_post('RTPT_v1', 1, snapshot_v(cp2d, 1), regs)
        dump_post('RTPT_v2', 2, snapshot_v(cp2d, 2), regs)
    elseif func == 0x06 then dump_post('NCLIP', -1, {0,0,0}, regs)
    elseif func == 0x2D then dump_post('AVSZ3', -1, {0,0,0}, regs)
    elseif func == 0x2E then dump_post('AVSZ4', -1, {0,0,0}, regs)
    end
end

-- Set breakpoints at PC+4 of every cop2 op in our range. Invoker fires AFTER
-- the cop2 has executed; registers contain the post-state.
--
-- Gotcha: the invoker MUST return true (not false): a BP that
-- returns false fires once and is never seen again. Returning true (or any
-- non-false) keeps it armed.
--
-- Gotcha: BPs only fire when the emulator is launched with --debugger.
for _, pc in ipairs(cop2_pcs) do
    PCSX.addBreakpoint(pc + 4, 'Exec', 4, 'gte-dump',
        function(addr)
            if frame >= CFG.frame_lo and frame < CFG.frame_hi then
                local cmd = read_word(addr - 4)
                local func = bit.band(cmd, 0x3F)
                local regs = PCSX.getRegisters()
                emit_for_func(func, regs)
            end
            return true  -- KEEP the breakpoint armed
        end,
        string.format('gte-dump-0x%08X', pc))
end

-- Frame counter via VSync event.
PCSX.Events.createEventListener('GPU::Vsync', function()
    frame = frame + 1

    -- Press handling.
    if CFG.presses[frame] then
        local btn = CFG.presses[frame]
        PCSX.SIO0.slots[1].pads[1].setOverride(btn)
        press_release[frame + CFG.press_dur] = btn
        print(string.format('[gte-dump] f%d press btn=%d', frame, btn))
    end
    if press_release[frame] then
        PCSX.SIO0.slots[1].pads[1].clearOverride(press_release[frame])
        press_release[frame] = nil
    end

    if frame >= CFG.frame_hi then
        fp:flush()
        fp:close()
        print(string.format('[gte-dump] done at frame %d, output: %s', frame, CFG.csv_path))
        PCSX.quit(0)
    end

    if frame % 60 == 0 then
        print(string.format('[gte-dump] frame=%d', frame))
    end
end)

print(string.format('[gte-dump] armed: %d cop2 PCs, frame range [%d,%d)',
                    #cop2_pcs, CFG.frame_lo, CFG.frame_hi))
