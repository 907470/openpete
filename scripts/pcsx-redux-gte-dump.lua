-- pcsx-redux GTE dumper for Spyro 1 titlescreen cutscene
--
-- Counts VSync events as frames, presses Start at scheduled frames to reach
-- the cutscene, then on each cop2 imm-25 instruction in r_pete + r_environment
-- (range 0x80023AC4..0x8002B9CC) emits one CSV row matching the openpete
-- trace logger's "psy" engine layout. After CFG.frame_hi we quit.

local CFG = {
    csv_path  = '/tmp/pcsx-redux-gte.csv',
    -- pcsx-redux frame numbers (no fast-boot, so later than openpete).
    -- Will tune empirically; for first run, dump everything in a wide window.
    frame_lo  = 0,
    frame_hi  = 4000,
    -- Pad presses (Start = button 3). frame -> {duration_frames, button}.
    -- Tuned for Spyro 1 NTSC: skip past boot splash, then through title.
    presses   = {
        [600]  = 3,  -- Start, after boot splash
        [800]  = 3,
        [1100] = 3,
        [1300] = 3,
        [1500] = 3,
    },
    press_dur = 6,
}

