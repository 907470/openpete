#!/usr/bin/env python3
"""gen-terrain-arena-caps.py - per-level terrain-arena capacities, generated.

The retained terrain cache allocates fifteen vertex arenas and eight
cell-record arenas per level. Sizing
them by guess costs device memory where the guess is high and sends sectors
back to the CPU walk where it is low, so the capacities come from the measured
high-water baseline under baselines/terrain-arena/ instead: per level, the
maximum `high` an arena reached over every pose and replay row of that level,
times a headroom factor, rounded up to a whole allocation step.

The table is keyed by the level id the game reports (game_layout.level_id),
read from the level table in games/spyro-1/features/levelwarp.c so the ids
cannot drift from the ones the baseline was measured against. A level id the
table does not name takes the union row, the per-arena maximum over every
level, which is also what the cache allocates at init, before any level has
loaded.

Run at configure time by core/CMakeLists.txt; the output is rewritten only
when its content changes, so a reconfigure does not rebuild the world.
"""
import argparse
import math
import os
import re
import sys

# core/include/openpete_terrain_cache.h, the OPTC_ARENA_* enum order.
ARENAS = [
    "OPAQUE", "ALPHA", "ADD", "SUB", "LP",
    "A_OPAQUE", "A_ALPHA", "A_ADD", "A_SUB", "A_LP",
    "N_OPAQUE", "N_ALPHA", "N_ADD", "N_SUB", "N_LP",
    "CN_OPAQUE", "CN_ALPHA", "CN_ADD", "CN_SUB",
    "CA_OPAQUE", "CA_ALPHA", "CA_ADD", "CA_SUB",
]

HEADROOM = 1.25      # the level's measured peak is not its bound
STEP = 16384         # allocation granularity, vertices
FLOOR = 16384        # smallest arena worth a buffer of its own
# The cell-record arenas (CN_*, CA_*) count records of 176-200 bytes, each
# standing in for 48-96 baked vertices, so their granularity and floor are
# record counts of about the same byte size as a few thousand vertices.
CELL_STEP = 256
CELL_FLOOR = 256

LEVEL_RE = re.compile(r'\{\s*"([a-z0-9_]+)"\s*,\s*"[^"]*"\s*,\s*(\d+)\s*\}')


def level_ids(levelwarp_c):
    """slug -> level id, from the k_levels table."""
    txt = open(levelwarp_c).read()
    start = txt.index("k_levels[] = {")
    end = txt.index("};", start)
    out = {}
    for m in LEVEL_RE.finditer(txt, start, end):
        out[m.group(1)] = int(m.group(2))
    return out


def read_rows(path):
    """arena -> maximum `high` over every pose row of one level file."""
    out = {}
    for line in open(path):
        if line.startswith("#") or line.startswith("pose\t"):
            continue
        f = line.rstrip("\n").split("\t")
        if len(f) < 3:
            continue
        out[f[1]] = max(out.get(f[1], 0), int(f[2]))
    return out


def cap_of(high, name):
    step, floor = (CELL_STEP, CELL_FLOOR) if name.startswith("C") else (STEP, FLOOR)
    n = int(math.ceil(high * HEADROOM / step)) * step
    return max(n, floor)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--baselines", required=True)
    ap.add_argument("--levelwarp", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    ids = level_ids(a.levelwarp)
    rows = []
    union = {n: 0 for n in ARENAS}
    for slug in sorted(ids):
        path = os.path.join(a.baselines, slug + ".tsv")
        if not os.path.exists(path):
            continue
        high = read_rows(path)
        rows.append((ids[slug], slug, [cap_of(high.get(n, 0), n) for n in ARENAS]))
        for n in ARENAS:
            union[n] = max(union[n], high.get(n, 0))
    rows.sort()
    ucaps = [cap_of(union[n], n) for n in ARENAS]

    o = []
    o.append("/* Generated by scripts/gen-terrain-arena-caps.py from")
    o.append(" * baselines/terrain-arena/. Per-arena vertex capacities: the level's")
    o.append(" * measured high-water mark over every baseline row, times %.2f, rounded" % HEADROOM)
    o.append(" * up to a multiple of %d and never below %d; the cell-record arenas" % (STEP, FLOOR))
    o.append(" * (CN_*, CA_*) count records, multiples of %d, never below %d." % (CELL_STEP, CELL_FLOOR))
    o.append(" * Do not edit.")
    o.append(" */")
    o.append("#ifndef OPENPETE_TERRAIN_ARENA_CAPS_GEN_H")
    o.append("#define OPENPETE_TERRAIN_ARENA_CAPS_GEN_H")
    o.append("")
    o.append("typedef struct { int level_id; uint32_t cap[%d]; } optc_level_caps_t;"
             % len(ARENAS))
    o.append("")
    o.append("/* Every level id with a baseline, in id order. */")
    o.append("static const optc_level_caps_t k_optc_caps_level[] = {")
    for lid, slug, caps in rows:
        o.append("    { %2d, { %s } },   /* %s */"
                 % (lid, ", ".join("%7d" % c for c in caps), slug))
    o.append("};")
    o.append("static const int k_optc_caps_level_n = %d;" % len(rows))
    o.append("")
    o.append("/* Per-arena maximum over every level: an unmeasured level id, and the")
    o.append(" * allocation at init before any level has loaded. */")
    o.append("static const uint32_t k_optc_caps_union[%d] = { %s };"
             % (len(ARENAS), ", ".join("%7d" % c for c in ucaps)))
    o.append("")
    o.append("#endif /* OPENPETE_TERRAIN_ARENA_CAPS_GEN_H */")
    txt = "\n".join(o) + "\n"

    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    if os.path.exists(a.out) and open(a.out).read() == txt:
        return 0
    open(a.out, "w").write(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
