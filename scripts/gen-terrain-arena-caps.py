#!/usr/bin/env python3
"""gen-terrain-arena-caps.py - per-level terrain-arena capacities, generated.

The retained terrain cache allocates fifteen vertex arenas and eight
cell-record arenas per level. Sizing
them by guess costs device memory where the guess is high and sends sectors
back to the CPU walk where it is low, so the capacities come from the measured
high-water baseline under baselines/terrain-arena/ instead: per level, the
maximum `high` an arena reached over every pose and replay row of that level,
times a headroom factor, rounded up to a whole allocation step.

The table is keyed by (game, level id): one openpete_core serves three games
whose level ids overlap (Spyro 2's metro_speedway and Spyro 1's
crystal_flight are both 35), so a level id alone names a different level in
each game. Each game's rows live under baselines/terrain-arena/<game>/, and
its slug-to-id map is read from that game's k_levels table
(scripts/lib/game_conf.py level_table) so the ids cannot drift from the ones
the baseline was measured against. Each game also gets a union row, the
per-arena maximum over its own levels: a level id that game's table does not
name takes it, and so does the allocation at init, before any level has
loaded. A union over every game covers a run with no registered game.

Run at configure time by core/CMakeLists.txt; the output is rewritten only
when its content changes, so a reconfigure does not rebuild the world.
"""
import argparse
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
import game_conf  # noqa: E402

# core/include/openpete_terrain_cache.h, the OPTC_ARENA_* enum order.
ARENAS = [
    "OPAQUE", "ALPHA", "ADD", "SUB", "LP",
    "A_OPAQUE", "A_ALPHA", "A_ADD", "A_SUB", "A_LP",
    "N_OPAQUE", "N_ALPHA", "N_ADD", "N_SUB", "N_LP",
    "CN_OPAQUE", "CN_ALPHA", "CN_ADD", "CN_SUB",
    "CA_OPAQUE", "CA_ALPHA", "CA_ADD", "CA_SUB",
]

HEADROOM = 1.25      # the level's measured peak is not its bound
STEP = 16384         # allocation granularity, vertices
FLOOR = 16384        # smallest arena worth a buffer of its own
# The cell-record arenas (CN_*, CA_*) count records of 176-200 bytes, each
# standing in for 48-96 baked vertices, so their granularity and floor are
# record counts of about the same byte size as a few thousand vertices.
CELL_STEP = 256
CELL_FLOOR = 256

def read_rows(path):
    """arena -> maximum `high` over every pose row of one level file."""
    out = {}
    for line in open(path):
        if line.startswith("#") or line.startswith("pose\t"):
            continue
        f = line.rstrip("\n").split("\t")
        if len(f) < 3:
            continue
        out[f[1]] = max(out.get(f[1], 0), int(f[2]))
    return out


def cap_of(high, name):
    step, floor = (CELL_STEP, CELL_FLOOR) if name.startswith("C") else (STEP, FLOOR)
    n = int(math.ceil(high * HEADROOM / step)) * step
    return max(n, floor)


def caps_init(caps):
    return "{ %s }" % ", ".join("%7d" % c for c in caps)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--baselines", required=True,
                    help="baselines/terrain-arena: one directory per game")
    ap.add_argument("--root", required=True, help="source root (the level tables)")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    rows, games = [], []
    every = {n: 0 for n in ARENAS}
    for game in game_conf.GAMES:
        gdir = os.path.join(a.baselines, game)
        if not os.path.isdir(gdir):
            continue
        union = {n: 0 for n in ARENAS}
        for slug, lid in game_conf.level_table(a.root, game):
            path = os.path.join(gdir, slug + ".tsv")
            if not os.path.exists(path):
                continue
            high = read_rows(path)
            rows.append((game, lid, slug, [cap_of(high.get(n, 0), n) for n in ARENAS]))
            for n in ARENAS:
                union[n] = max(union[n], high.get(n, 0))
                every[n] = max(every[n], high.get(n, 0))
        games.append((game, [cap_of(union[n], n) for n in ARENAS]))
    rows.sort()
    ecaps = [cap_of(every[n], n) for n in ARENAS]

    o = []
    o.append("/* Generated by scripts/gen-terrain-arena-caps.py from")
    o.append(" * baselines/terrain-arena/<game>/. Per-arena vertex capacities: the")
    o.append(" * level's measured high-water mark over every baseline row, times %.2f," % HEADROOM)
    o.append(" * rounded up to a multiple of %d and never below %d; the cell-record" % (STEP, FLOOR))
    o.append(" * arenas (CN_*, CA_*) count records, multiples of %d, never below %d."
             % (CELL_STEP, CELL_FLOOR))
    o.append(" * Do not edit.")
    o.append(" */")
    o.append("#ifndef OPENPETE_TERRAIN_ARENA_CAPS_GEN_H")
    o.append("#define OPENPETE_TERRAIN_ARENA_CAPS_GEN_H")
    o.append("")
    o.append("typedef struct { const char *game; int level_id; uint32_t cap[%d]; } "
             "optc_level_caps_t;" % len(ARENAS))
    o.append("typedef struct { const char *game; uint32_t cap[%d]; } optc_game_caps_t;"
             % len(ARENAS))
    o.append("")
    o.append("/* Every (game, level id) with a baseline, in game then id order. */")
    o.append("static const optc_level_caps_t k_optc_caps_level[] = {")
    for game, lid, slug, caps in rows:
        o.append("    { \"%s\", %2d, %s },   /* %s */" % (game, lid, caps_init(caps), slug))
    o.append("};")
    o.append("static const int k_optc_caps_level_n = %d;" % len(rows))
    o.append("")
    o.append("/* Per game, the per-arena maximum over its levels: a level id of that")
    o.append(" * game with no row, and the allocation at init before any level has")
    o.append(" * loaded. */")
    o.append("static const optc_game_caps_t k_optc_caps_game[] = {")
    for game, caps in games:
        o.append("    { \"%s\", %s }," % (game, caps_init(caps)))
    o.append("};")
    o.append("static const int k_optc_caps_game_n = %d;" % len(games))
    o.append("")
    o.append("/* Per-arena maximum over every game: a run with no registered game. */")
    o.append("static const uint32_t k_optc_caps_union[%d] = %s;" % (len(ARENAS), caps_init(ecaps)))
    o.append("")
    o.append("#endif /* OPENPETE_TERRAIN_ARENA_CAPS_GEN_H */")
    txt = "\n".join(o) + "\n"

    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    if os.path.exists(a.out) and open(a.out).read() == txt:
        return 0
    open(a.out, "w").write(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
