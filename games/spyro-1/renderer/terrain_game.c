/* Which LP faces may back-fill sightlines no authored HP covers is a FROZEN,
 * human-reviewed list (terrain_fill_tags.h, generated by
 * scripts/gen-fill-tags.py from tests/freecam/fill-tags.verdicts). Candidates
 * are measured per pixel from the game's own renderer - og-original coverage
 * minus pure-HP coverage (m_LodDistance doubled) - attributed to LP faces by
 * projected screen footprint, then reviewed face-by-face. FILL faces are
 * og-terrain-over-void (water planes, level-boundary channels); every
 * rejected candidate was a silhouette sliver between the coarse/alternate LP
 * shape and the HP silhouette, where filling paints LP wedges over sky.
 * Absence from the table = not a fill face: a face the sweep never measured
 * fails loud (an unfilled hole at a new camera) instead of silently shipping
 * a guess - the failure mode is visible and local, unlike a threshold
 * classifier patched per newly discovered misprediction. */
#include "terrain_fill_tags.h"

/** @brief Reports whether (level, sec, face) is in the frozen LP fill-face table.
 *
 * Binary-searches k_terrain_fill_tags, which is sorted ascending on the key
 * level << 20 | sec << 8 | face. The key gives face 8 bits, so a face of 256
 * or more shares a key with a face of the next sector.
 * @param level The level id.
 * @param sec The sector index.
 * @param face The LP face index within the sector.
 * @return 1 when the face is a fill face, else 0. */
static int s1_fill_tag(int level, int sec, int face) {
    int lo = 0, hi = (int)(sizeof(k_terrain_fill_tags)/sizeof(k_terrain_fill_tags[0])) - 1;
    long q = ((long)level << 20) | ((long)sec << 8) | face;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        const tft_entry_t* e = &k_terrain_fill_tags[mid];
        long k = ((long)e->level << 20) | ((long)e->sec << 8) | e->face;
        if (k == q) return 1;
        if (k < q) lo = mid + 1; else hi = mid - 1;
    }
    return 0;
}

/** @brief Writes the level's name as the fill-tag verdict files spell it.
 *
 * The name is spyro1_levels' row for the level; a level absent from the
 * table gets "level<id>". Truncates to cap, which snprintf terminates.
 * @param level The level id.
 * @param out Receives the NUL-terminated name.
 * @param cap The size of out in bytes; must be at least 1. */
static void s1_level_name(int level, char* out, size_t cap) {
    game_level_name(&spyro1_levels, level, out, cap);
}

/* Level-data authoring bugs corrected at the native colour fetch, keyed on
 * exact (g_LevelId, sector, face).
 *
 * stone_hill s205 f4-f7: four quads of the water backdrop group carry the
 * editor-default vertex colour 7F7F7F (unpainted) while every sibling panel
 * is FF7F60 - the pre-fogged sky camouflage. On PSX the grey shows when
 * looking up from under the water; natively it also shows from above (the LP
 * either-half NCLIP acceptance draws the underside the .s culls). Recolour
 * to the sibling sky-blue. */
typedef struct { int level, sec, face; uint32_t rgb; } lp_artfix_t;
static const lp_artfix_t k_lp_artfix[] = {
    { 11, 205, 4, 0xFF7F60u }, { 11, 205, 5, 0xFF7F60u },
    { 11, 205, 6, 0xFF7F60u }, { 11, 205, 7, 0xFF7F60u },
};
/** @brief Looks up the authored-data colour correction for (level, sec, face) in k_lp_artfix.
 *
 * @param level The level id.
 * @param sec The sector index.
 * @param face The LP face index within the sector.
 * @param rgb Receives the corrected 0x00BBGGRR colour; unchanged when the
 *        face has no correction.
 * @return 1 when the face is corrected, else 0. */
static int s1_lp_artfix(int level, int sec, int face, uint32_t* rgb) {
    for (size_t k = 0; k < sizeof(k_lp_artfix)/sizeof(k_lp_artfix[0]); k++)
        if (k_lp_artfix[k].level == level && k_lp_artfix[k].sec == sec
            && k_lp_artfix[k].face == face) { *rgb = k_lp_artfix[k].rgb; return 1; }
    return 0;
}

#define S1_GS_LEVEL_TRANSITION 1u
#define S1_G_LOAD_STAGE        0x80075864u   /* g_LoadStage */

/** @brief 1 while GS_LevelTransition has not run LoadLevel's stage 2.
 *
 * The transition stops the world draw and calls LoadLevel once per tick
 * (func_8002DF9C). Stage 0 and 1 write only the cyclorama and sound table
 * copies below the lower polygon buffer. Stage 2 sets g_LevelId and starts the
 * overlay read, the first write into the level's memory; the VRAM pages follow
 * at stage 5. A stage of 2 or less read at the present therefore names the
 * level being left, with its sectors and textures whole, whatever time the
 * overlay read takes. Other game states answer 0: GS_TitleScreen's load
 * replaces the VRAM pages in the tick that stops the draw.
 * @param cpu The guest CPU state.
 * @return 1 when the level being left is whole, else 0. */
static int s1_world_outlives_draw(CPUState* cpu) {
    const int32_t stage = (int32_t)cpu->read_word(S1_G_LOAD_STAGE);
    if (cut_census_on())
        fprintf(stderr, "[cut-census vbl=%u] held-terrain gs=%u stage=%d\n", openpete_frame,
                cpu->read_word(game_layout.game_state), stage);
    return cpu->read_word(game_layout.game_state) == S1_GS_LEVEL_TRANSITION &&
           stage >= 0 && stage <= 2;
}

