#!/usr/bin/env python3
"""Filter a global overlay-fn-pointer candidate list against one overlay.

`extract_overlay_func_pointers.py` produces a union of fn-pointer-table
constants harvested from the main EXE — applicable to any overlay's
vaddr range. Each individual overlay then needs to filter that union
to entries that aren't *delay slots* in its own bytes: forcing a
function entry on a delay slot causes psxrecomp to split the previous
function such that its post-jal continuation address (delay+4) is a
mid-function block of the new entry, which the runtime dispatcher
then can't resolve → stub miss.

Filter rules (the candidate addr must be inside `load_addr..load_addr+size`):
  - DROP if the instruction at addr-4 is a JAL or JALR. The delay slot
    of a call has a meaningful "return-after-call" continuation at
    addr+4; splitting the function at addr makes psxrecomp emit the
    continuation as a dispatch on addr+4, which never resolves.
  - KEEP otherwise. Plain branches (J, B, BEQ, BNE, ...) are fine —
    if entry happens at the delay slot via JALR-from-main-EXE, control
    enters cleanly and never executes the dead branch at addr-4.

Usage:
    filter_overlay_fn_pointers.py <candidates.txt> <overlay.ovl> \\
        --load-addr=0xADDR <out>
"""
import argparse
import struct
import sys
from pathlib import Path


def is_call_delay_slot(ovl: bytes, off: int) -> bool:
    """True iff the instruction at off-4 is JAL (op=3) or JALR (op=0,
    funct=9) — i.e., the bytes at off are the delay slot of a call."""
    if off < 4 or off + 4 > len(ovl):
        return False
    pred, = struct.unpack_from('<I', ovl, off - 4)
    op = (pred >> 26) & 0x3F
    if op == 0x03:
        return True
    if op == 0x00 and (pred & 0x3F) == 0x09:
        return True
    return False


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('candidates', type=Path)
    p.add_argument('overlay', type=Path)
    p.add_argument('out', type=Path)
    p.add_argument('--load-addr', required=True)
    args = p.parse_args()

    load_addr = int(args.load_addr, 0)
    ovl = args.overlay.read_bytes()
    end = load_addr + len(ovl)

    kept, dropped_oor, dropped_delay = 0, 0, 0
    with args.out.open('w') as f:
        f.write(
            f"# {args.out.name} — auto-generated by\n"
            f"# tools/filter_overlay_fn_pointers.py from {args.candidates.name}\n"
            f"# (overlay {args.overlay.name}, load=0x{load_addr:08X}).\n"
        )
        for line in args.candidates.read_text().splitlines():
            s = line.strip()
            if not s or s.startswith('#'):
                continue
            try:
                addr = int(s, 0)
            except ValueError:
                continue
            if not (load_addr <= addr < end):
                dropped_oor += 1
                continue
            if is_call_delay_slot(ovl, addr - load_addr):
                dropped_delay += 1
                continue
            f.write(f'0x{addr:08X}\n')
            kept += 1
    print(f'{args.out.name}: kept {kept}, dropped {dropped_delay} call-delay-slot, '
          f'{dropped_oor} out-of-range', file=sys.stderr)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
