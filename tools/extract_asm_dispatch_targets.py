#!/usr/bin/env python3
"""Extract handwritten-asm jr/jalr target addresses for the recompiler.

Spyro's `spyro-1/asm/**/*.s` files include handwritten dispatch tables -
mostly GTE MAC1/MAC2/MAC3 read stubs in collision.s - that the static
analyzer can't trace through `lui+addiu+jr`. Each `glabel D_<addr>` is
itself a jr target; sequences of `mfc2 ... C2_MAC*` at 0x10 stride after
the glabel are also valid mid-table entries.

Output is one file per binary (main EXE + each overlay) in
discovered_functions.log style. Each file is suitable for psxrecomp's
`--extra-funcs=<file>` for that specific binary; passing main-EXE
addresses to an overlay regen would silently fail psxrecomp's
range-validation, but worse, an address that happens to fall in the
overlay's vaddr range would be accepted at the wrong binary (overlays
share vaddr 0x8007AA38 but contain different bytes).

Binary ownership is derived from the `.s` file's location:
  asm/nonmatchings/overlays/<name>/...   ->  overlay <name>
  everything else                        ->  main_exe

Usage:
    extract_asm_dispatch_targets.py <asm-root> <out-dir>
"""
import argparse
import re
from collections import defaultdict
from pathlib import Path

GLABEL_RE = re.compile(r'^glabel\s+D_([0-9A-Fa-f]+)\s*$')
ADDR_INSTR_RE = re.compile(
    r'^/\*\s+\w+\s+([0-9A-Fa-f]{8})\s+([0-9A-Fa-f]{8})\s+\*/\s*(.*)'
)

JUMP_TABLE_INSTR = ('mfc2', 'j ', 'b ', 'beqz', 'bnez')


def binary_for(asm_root: Path, path: Path) -> str:
    """Map a .s file to its owning binary based on path. Files under
    nonmatchings/overlays/<name>/ belong to that overlay; everything
    else (top-level handwritten .s + other nonmatchings/) belongs to
    the main EXE."""
    parts = path.relative_to(asm_root).parts
    if 'overlays' in parts:
        i = parts.index('overlays')
        if i + 1 < len(parts):
            return parts[i + 1]
    return 'main_exe'


def harvest(asm_root: Path) -> dict[str, set[int]]:
    """For each `glabel D_<addr>` walk forward up to ~200 lines, harvesting
    addresses that look like jump-table slots - `mfc2` MAC-read stubs
    (16-byte stride in collision.s, math.s) and `j .Llabel` entries
    (8-byte stride in dispatch tables). The label itself plus any of
    these is added to the forced-entry set, keyed by the .s file's
    owning binary."""
    out: dict[str, set[int]] = defaultdict(set)
    for path in asm_root.rglob('*.s'):
        binary = binary_for(asm_root, path)
        lines = path.read_text().splitlines(keepends=False)
        for i, line in enumerate(lines):
            m = GLABEL_RE.match(line.strip())
            if not m:
                continue
            out[binary].add(int(m.group(1), 16))
            for j in range(i + 1, min(i + 200, len(lines))):
                ln = lines[j].strip()
                if (ln.startswith(('glabel ', '.L'))
                        or ln.startswith('/* glabel')):
                    break
                am = ADDR_INSTR_RE.match(lines[j])
                if not am:
                    continue
                addr = int(am.group(1), 16)
                rest = am.group(3).lstrip()
                if any(rest.startswith(t) for t in JUMP_TABLE_INSTR):
                    out[binary].add(addr)
                # `jr/jalr <reg>` at the end of a basic block is the table
                # consumer itself, not a slot - stop here.
                if rest.startswith(('jr ', 'jalr ')):
                    break
    return out


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        'asm_root',
        type=Path,
        nargs='?',
        default=Path('games/spyro-1/spyro-1/asm'),
        help='root dir to scan for .s files',
    )
    p.add_argument('out_dir', type=Path,
                   help='output directory; one <binary>.txt per binary')
    args = p.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    by_binary = harvest(args.asm_root)

    # Always touch main_exe.txt so its absence isn't ambiguous.
    by_binary.setdefault('main_exe', set())

    total = 0
    for binary, addrs in sorted(by_binary.items()):
        path = args.out_dir / f'{binary}.txt'
        with path.open('w') as f:
            f.write(
                f"# {binary}.txt - auto-generated by\n"
                "# tools/extract_asm_dispatch_targets.py. Do not hand-edit.\n"
            )
            for a in sorted(addrs):
                f.write(f'0x{a:08X}\n')
        print(f'wrote {len(addrs)} entries to {path}')
        total += len(addrs)
    print(f'total: {total} entries across {len(by_binary)} binaries')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
