#!/usr/bin/env python3
"""gen_overlay_entries.py - emit a game's per-overlay entry-address arrays.

Reads the game's generated spyro_overlay_table.c (overlay ids, names and
the shared vaddr window) and, per overlay, the `case 0x...u:` labels of
generated/<overlay>/<overlay>.bin_dispatch.c, the addresses the overlay's
recompiled dispatch accepts as function entries. Writes one C file
defining, for the mod layer's override_ovl argument checks:

  game_mod_overlays[]        {id, name, sorted entries, count} per overlay
  game_mod_overlay_count
  game_mod_window_lo, game_mod_window_hi

Usage: gen_overlay_entries.py --generated <dir> --out <file.c>
"""

import argparse
import re
import sys
from pathlib import Path

ROW_RE = re.compile(r'\{\s*(\d+)\s*,\s*"([^"]+)"')
LO_RE = re.compile(r"spyro_overlay_window_lo\s*=\s*(0x[0-9A-Fa-f]+)u")
HI_RE = re.compile(r"spyro_overlay_window_hi\s*=\s*(0x[0-9A-Fa-f]+)u")
CASE_RE = re.compile(r"^\s*case (0x[0-9A-Fa-f]+)u:", re.M)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--generated", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    table = (args.generated / "spyro_overlay_table.c").read_text(encoding="utf-8")
    rows = [(int(i), n) for i, n in ROW_RE.findall(table)]
    lo, hi = LO_RE.search(table), HI_RE.search(table)
    if not lo or not hi:
        sys.exit("gen_overlay_entries: no overlay window in spyro_overlay_table.c")

    L = ["/* Generated by tools/gen_overlay_entries.py from the generated\n"
         " * overlay table and dispatch files - do not edit. */\n"
         "#include \"game_mod_desc.h\"\n\n"]
    total = 0
    for oid, name in rows:
        disp = args.generated / name / f"{name}.bin_dispatch.c"
        if not disp.exists():
            sys.exit(f"gen_overlay_entries: {disp} missing for overlay {name}")
        entries = sorted({int(a, 16) for a in
                          CASE_RE.findall(disp.read_text(encoding="utf-8"))})
        total += len(entries)
        L.append(f"static const uint32_t k_entries_{oid}[] = {{")
        for i, a in enumerate(entries):
            L.append(("\n    " if i % 6 == 0 else " ") + f"0x{a:08X}u,")
        L.append("\n};\n")
    L.append("\nconst game_mod_overlay_t game_mod_overlays[] = {\n")
    for oid, name in rows:
        L.append(f'    {{ {oid}u, "{name}", k_entries_{oid}, '
                 f"sizeof k_entries_{oid} / sizeof k_entries_{oid}[0] }},\n")
    L.append("};\n"
             "const size_t game_mod_overlay_count = "
             "sizeof game_mod_overlays / sizeof game_mod_overlays[0];\n"
             f"const uint32_t game_mod_window_lo = {lo.group(1)}u;\n"
             f"const uint32_t game_mod_window_hi = {hi.group(1)}u;\n")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("".join(L), encoding="utf-8")
    print(f"gen_overlay_entries: {len(rows)} overlays, {total} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
