#!/usr/bin/env python3
"""Generate the link-time --defsym aliasing block.

Reads native.toml's `alias_globals` list, looks each name up in
globals.toml, and writes a CMake fragment that:

  1. set(SPYRO_NATIVE_DEFSYMS ...) — list of -Wl,--defsym=NAME=g_ram+OFF
  2. PE/COFF guard — emits a fatal_error if the platform can't represent
     absolute symbols, until a PE-friendly aliasing path lands (plan §8).

The CMakeLists.txt picks up the fragment with `include()` and feeds
SPYRO_NATIVE_DEFSYMS straight into target_link_options.

Usage:
    gen_defsyms.py <manifest_dir> <out_cmake_path>
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _manifest_lib import load_manifest, fail


def main(argv: list[str]) -> int:
    if len(argv) not in (3, 4):
        print("usage: gen_defsyms.py <manifest_dir> <out_cmake> [<rewriter_dir>]",
              file=sys.stderr)
        return 2
    manifest_dir = Path(argv[1])
    out_path = Path(argv[2])
    rewriter_dir = Path(argv[3]) if len(argv) == 4 else None

    native, _syms, glob_idx = load_manifest(manifest_dir)

    # Default policy: alias every global whose storage isn't provided by
    # a natively-compiled C source. That's:
    #   - all "recomp" globals (defined in build/asm/data/*.s)
    #   - "decomp" globals from src/*.c TUs not in native_source
    # Native-compiled TUs provide their own storage; --defsym aliasing
    # those would collide. native.toml can opt out further with
    # `alias_globals_skip = [...]` for collisions with PsyCross/CRT.
    skip = set(native.get("alias_globals_skip", []))
    native_sources = {
        ns["file"] for ns in native.get("native_source", [])
    }
    aliases: list[tuple[str, int]] = []
    for name, info in glob_idx.items():
        if name in skip:
            continue
        # Skip globals whose defining .c is natively-compiled — that
        # TU's compilation provides real host storage.
        if info.get("kind") == "decomp" and info.get("source_file") in native_sources:
            continue
        aliases.append((name, info["addr"]))
    aliases.sort(key=lambda x: x[1])
    if not aliases:
        fail("no recomp globals found in globals.toml")

    # Merge bare-global redirects emitted by tools/rewrite_tu.py. Each
    # *.redirects.txt file contains `<__psx_name> <orig_name>` lines. We
    # look up the address of <orig_name> in globals.toml and emit a
    # second --defsym pointing __psx_<name> at the same g_ram offset, so
    # rewritten native code reads the PSX-laid bytes.
    redirect_aliases: list[tuple[str, int]] = []
    if rewriter_dir is not None and rewriter_dir.exists():
        seen: set[str] = set()
        for txt in sorted(rewriter_dir.glob("*.redirects.txt")):
            for raw in txt.read_text().splitlines():
                line = raw.strip()
                if not line or line.startswith("#"):
                    continue
                psx_name, _, orig_name = line.partition(" ")
                if not psx_name or not orig_name:
                    continue
                if psx_name in seen:
                    continue
                seen.add(psx_name)
                if orig_name not in glob_idx:
                    fail(f"rewriter redirect references unknown global {orig_name}")
                redirect_aliases.append((psx_name, glob_idx[orig_name]["addr"]))
        redirect_aliases.sort(key=lambda x: x[1])

    PSX_RAM_BASE = 0x80000000
    lines = [
        "# Auto-generated by tools/gen_defsyms.py — do not edit.",
        "# Source: manifest/globals.toml (every kind=recomp global is aliased",
        "# into g_ram unless listed in native.toml's alias_globals_skip).",
        "",
        "set(SPYRO_NATIVE_DEFSYMS",
    ]
    for name, addr in aliases:
        offset = addr - PSX_RAM_BASE
        if not (0 <= offset < 2 * 1024 * 1024):
            fail(f"{name} addr 0x{addr:08X} not in 2MB g_ram window")
        lines.append(f'    "-Wl,--defsym={name}=g_ram+0x{offset:X}"')
    if redirect_aliases:
        lines.append("    # Rewriter Pass 2 — bare-global __psx_<name> redirects")
        for name, addr in redirect_aliases:
            offset = addr - PSX_RAM_BASE
            if not (0 <= offset < 2 * 1024 * 1024):
                fail(f"{name} addr 0x{addr:08X} not in 2MB g_ram window")
            lines.append(f'    "-Wl,--defsym={name}=g_ram+0x{offset:X}"')
    lines.append(")")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n")
    extra = f" (+ {len(redirect_aliases)} rewriter redirects)" if redirect_aliases else ""
    print(f"emitted {len(aliases)} defsyms{extra} → {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
