#!/usr/bin/env python3
"""Per-entry caller census of the mod-facing API surface.

Regenerates docs/src/developer/mod-api-audit.md from the tree: every
function pointer in openpete_mod_api_t and openpete_mod_ui_t, with call
counts and the mods that call it. The counting basis is stated in the emitted document; run from the
repo root with no arguments.
"""
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "core/include/openpete_mod_api.h"
UI_HEADER = ROOT / "core/include/openpete_mod_ui.h"
MODS = ROOT / "mods"
OUT = ROOT / "docs/src/developer/mod-api-audit.md"

MEMBER_RE = re.compile(r"\(\*\s*(\w+)\s*\)\s*\(")


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def struct_members(text: str, struct_start: str, struct_end: str):
    """Top-level function-pointer members only: a nested (*name)( inside a
    member's parameter list sits at paren depth > 0 and is skipped."""
    body = strip_comments(
        text.split(struct_start, 1)[1].split(struct_end, 1)[0])
    out = []
    for m in MEMBER_RE.finditer(body):
        depth = body.count("(", 0, m.start()) - body.count(")", 0, m.start())
        if depth == 0 and not m.group(1).startswith("_"):
            out.append(m.group(1))
    return out


def file_scope_callback_typedefs(text: str):
    out = []
    for line in text.splitlines():
        m = re.match(r"typedef\s+[\w* ]+\(\*\s*(\w+)\s*\)\s*\(", line)
        if m:
            out.append(m.group(1))
    return out


def main() -> int:
    text = HEADER.read_text()
    api_entries = struct_members(text, "typedef struct openpete_mod_api {",
                                 "} openpete_mod_api_t;")
    ui_entries = struct_members(UI_HEADER.read_text(),
                                "typedef struct openpete_mod_ui {",
                                "} openpete_mod_ui_t;")
    typedefs = file_scope_callback_typedefs(text)
    api_version = re.search(r"OPENPETE_MOD_API_VERSION\s+(\d+)", text).group(1)

    mod_dirs = sorted(d for d in MODS.iterdir()
                      if d.is_dir() and (d / "mod.toml").exists())
    srcs = {d.name: sorted(d.glob("src/*.c")) for d in mod_dirs}
    zero_c = [name for name, files in srcs.items() if not files]

    # calls[entry] -> {mod: count}; api entries matched as "->entry(",
    # widget entries as "ui->entry(" (see basis note in the document).
    api_calls = defaultdict(lambda: defaultdict(int))
    ui_calls = defaultdict(lambda: defaultdict(int))
    for name, files in srcs.items():
        blob = "\n".join(f.read_text() for f in files)
        for e in api_entries:
            n = len(re.findall(r"->\s*" + e + r"\s*\(", blob))
            if n:
                api_calls[e][name] += n
        for e in ui_entries:
            n = len(re.findall(r"\bui->\s*" + e + r"\s*\(", blob))
            if n:
                ui_calls[e][name] += n

    manifest_keys = defaultdict(list)
    for d in mod_dirs:
        mtext = (d / "mod.toml").read_text()
        for key, pat in [("tier", r"^\s*tier\s*="),
                         ("[test]", r"^\s*\[test\]"),
                         ("[[level]]", r"^\s*\[\[level\]\]"),
                         ("[[binding]]", r"^\s*\[\[binding\]\]")]:
            if re.search(pat, mtext, re.M):
                manifest_keys[key].append(d.name)

    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                          cwd=ROOT, capture_output=True, text=True
                          ).stdout.strip() or "unknown"

    def entry_rows(entries, calls):
        rows = []
        for e in entries:
            callers = calls.get(e, {})
            total = sum(callers.values())
            rows.append((e, total, sorted(callers)))
        rows.sort(key=lambda r: (-len(r[2]), -r[1], r[0]))
        return rows

    lines = []
    w = lines.append
    w("# Mod API caller census")
    w("")
    w(f"Generated by `tools/mod_api_census.py` at `{head}`. Regenerate with:")
    w("")
    w("    python3 tools/mod_api_census.py")
    w("")
    w("## Counting basis")
    w("")
    w(f"- The api struct (`openpete_mod_api_t`) has **{len(api_entries)}** "
      "function-pointer entries; the UI vtable (`openpete_mod_ui_t`) has "
      f"**{len(ui_entries)}** (openpete_mod_ui.h, the separately-versioned "
      f"UI header); **{len(typedefs)}** file-scope callback "
      "typedefs exist alongside. Counts of \"the API surface\" must name "
      "which of these they include.")
    w(f"- Header version: api v{api_version}.")
    w("- A *call* is a textual match of `->entry(` (api entries) or "
      "`ui->entry(` (widget entries) in `mods/*/src/*.c`. Pointer-stashing "
      "or macro indirection would undercount; none is known in-tree.")
    w("- A *caller* is a mod with at least one call. Probe mods count as "
      "callers; a tail analysis discounts them by hand.")
    w("")
    w(f"## API struct entries ({len(api_entries)})")
    w("")
    w("| Entry | Calls | Caller mods |")
    w("|---|---:|---|")
    for e, total, callers in entry_rows(api_entries, api_calls):
        w(f"| `{e}` | {total} | {', '.join(f'`{c}`' for c in callers) or '-'} |")
    w("")
    w(f"## UI vtable entries ({len(ui_entries)})")
    w("")
    w("| Widget | Calls | Caller mods |")
    w("|---|---:|---|")
    for e, total, callers in entry_rows(ui_entries, ui_calls):
        w(f"| `{e}` | {total} | {', '.join(f'`{c}`' for c in callers) or '-'} |")
    w("")
    w("## Mods")
    w("")
    w(f"- {len(mod_dirs)} mods under `mods/`.")
    w(f"- Declarative (manifest and files, nothing compiled): "
      f"{', '.join(f'`{m}`' for m in zero_c) or 'none'}.")
    w("")
    w("## Manifest key usage")
    w("")
    w("| Key | Mods |")
    w("|---|---|")
    for key in ["tier", "[test]", "[[level]]", "[[binding]]"]:
        mods = manifest_keys.get(key, [])
        w(f"| `{key}` | {', '.join(f'`{m}`' for m in mods) or '-'} |")
    w("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} "
          f"({len(api_entries)} api entries, {len(ui_entries)} widgets, "
          f"{len(mod_dirs)} mods)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
