#!/usr/bin/env python3
"""Generate the SoundTable slot-name table from the decomp's sound_table.h.

The game's SoundTable is 256 one-byte def indices, one per semantic
sound; the decomp names each field (gemPickup, spyroCharge, ...) and
leaves the unidentified ones as sound_0xNN. This emits one C table the
engine and the sfx census share, so a slot's name is the same string in
the resolver, the pack scanner (the symbolic `<name>.wav` form) and the
dump's file labels.

  tools/gen_sfx_names.py --header <sound_table.h> --out <spyro1_sfx_names.h>
"""
import argparse
import re
import sys

FIELD = re.compile(r"^\s*u_char\s+([A-Za-z_][A-Za-z0-9_]*)\s*;")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--header", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    names = []
    with open(a.header, encoding="utf-8") as f:
        for line in f:
            m = FIELD.match(line)
            if m:
                names.append(m.group(1))
    if len(names) != 256:
        sys.exit(f"gen_sfx_names: expected 256 slot fields, found {len(names)}")

    named = sum(1 for n in names if not n.startswith("sound_0x"))
    with open(a.out, "w", encoding="utf-8") as o:
        o.write("/* Generated by tools/gen_sfx_names.py from sound_table.h — do not edit.\n"
                " * SoundTable slot index -> name. Unidentified slots keep the decomp's\n"
                f" * sound_0xNN spelling. {named} of 256 slots are named. */\n"
                "#ifndef SPYRO1_SFX_NAMES_H\n#define SPYRO1_SFX_NAMES_H\n\n"
                "#define SPYRO1_SFX_SLOT_COUNT 256\n"
                "static const char* const spyro1_sfx_slot_names[SPYRO1_SFX_SLOT_COUNT] = {\n")
        for i, n in enumerate(names):
            o.write(f'    /* 0x{i:02x} */ "{n}",\n')
        o.write("};\n\n#endif /* SPYRO1_SFX_NAMES_H */\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
