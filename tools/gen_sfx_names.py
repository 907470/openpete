#!/usr/bin/env python3
"""Generate the SoundTable slot-name table from a decomp's SoundTable struct.

The game's SoundTable is 256 one-byte def indices, one per semantic
sound; the decomp names each field (gemPickup, spyroCharge, ...) and
leaves the unidentified ones as sound_0xNN or unkNN. This emits one C
table the engine and the sfx census share, so a slot's name is the same
string in the resolver, the pack scanner (the symbolic `<name>.wav` form)
and the dump's file labels.

  tools/gen_sfx_names.py --header <sound_table.h> --out <spyro1_sfx_names.h>
  tools/gen_sfx_names.py --prefix spyro3 --pad --header <spu.h> --out <spyro3_sfx_names.h>
  tools/gen_sfx_names.py --prefix spyro2 --pad --name 0x01=gemCollect ... --out <spyro2_sfx_names.h>

Only the fields of the struct closed by `} SoundTable;` count. A decomp
placeholder field `unkNN` (NN the decimal slot index) is emitted as
sound_0xNN, the spelling of an unidentified slot. --pad fills the slots
past the struct's last field with sound_0xNN up to 256; the game's loader
reads the table as 0x100 bytes whatever the struct declares. --name
IDX=NAME names one slot that no header names; it may not rename a slot
the header names.
"""
import argparse
import re
import sys

FIELD = re.compile(r"^\s*(?:u_char|unsigned\s+char)\s+([A-Za-z_][A-Za-z0-9_]*)\s*;")
UNK = re.compile(r"^unk(\d+)$")
SLOTS = 256


def soundtable_fields(path: str) -> list:
    """The field names of the struct closed by `} SoundTable;`, in order."""
    names = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if re.match(r"^\s*typedef\s+struct\b", line):
                names = []
            elif re.match(r"^\s*}\s*SoundTable\s*;", line):
                return names
            else:
                m = FIELD.match(line)
                if m:
                    names.append(m.group(1))
    sys.exit(f"gen_sfx_names: no `}} SoundTable;` struct in {path}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--header",
                    help="decomp header declaring SoundTable; omitted, every slot is sound_0xNN (needs --pad)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--prefix", default="spyro1",
                    help="identifier prefix of the emitted table (default spyro1)")
    ap.add_argument("--pad", action="store_true",
                    help="fill slots past the struct's last field with sound_0xNN")
    ap.add_argument("--name", action="append", default=[], metavar="IDX=NAME",
                    help="name slot IDX (0x.. or decimal), once per slot")
    a = ap.parse_args()

    names = soundtable_fields(a.header) if a.header else []
    for i, n in enumerate(names):
        m = UNK.match(n)
        if m and int(m.group(1)) == i:
            names[i] = f"sound_0x{i:x}"
    if a.pad:
        names += [f"sound_0x{i:x}" for i in range(len(names), SLOTS)]
    if len(names) != SLOTS:
        sys.exit(f"gen_sfx_names: expected {SLOTS} slot fields, found {len(names)}")
    for spec in a.name:
        idx_s, _, name = spec.partition("=")
        idx = int(idx_s, 0)
        if not name or not 0 <= idx < SLOTS or not names[idx].startswith("sound_0x"):
            sys.exit(f"gen_sfx_names: --name {spec}: not an unnamed slot 0..{SLOTS - 1}")
        if name in names:
            sys.exit(f"gen_sfx_names: --name {spec}: {name} already names a slot")
        names[idx] = name

    named = sum(1 for n in names if not n.startswith("sound_0x"))
    up = a.prefix.upper()
    with open(a.out, "w", encoding="utf-8") as o:
        o.write("/* Generated by tools/gen_sfx_names.py from sound_table.h - do not edit.\n"
                if a.prefix == "spyro1" else
                f"/* Generated by tools/gen_sfx_names.py from "
                f"{a.header.rsplit('/', 1)[-1] if a.header else 'no header'} - do not edit.\n")
        o.write(" * SoundTable slot index -> name. Unidentified slots keep the decomp's\n"
                f" * sound_0xNN spelling. {named} of 256 slots are named. */\n"
                f"#ifndef {up}_SFX_NAMES_H\n#define {up}_SFX_NAMES_H\n\n"
                f"#define {up}_SFX_SLOT_COUNT 256\n"
                f"static const char* const {a.prefix}_sfx_slot_names[{up}_SFX_SLOT_COUNT] = {{\n")
        for i, n in enumerate(names):
            o.write(f'    /* 0x{i:02x} */ "{n}",\n')
        o.write(f"}};\n\n#endif /* {up}_SFX_NAMES_H */\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
