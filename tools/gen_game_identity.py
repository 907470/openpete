#!/usr/bin/env python3
"""Emit a game's identity TU from its recomp.conf.

    gen_game_identity.py --game <id> --conf games/<id>/recomp.conf --out <c>

recomp.conf is a shell fragment of KEY=value lines; the keys read here are
DISPLAY_NAME, EXE_FILENAME, OVERLAY_LOAD_ADDR, LIBCD_BLOCK_ADDR and
CD_READ_CB_ADDR (0 when absent: the game registers its read callback through
the thunk). The output defines the game_extras.h identity accessors and the
three address-only PSYQ hooks, so a game's hand-written sources carry no
identity constants.
"""
import argparse
import re
import sys

ASSIGN = re.compile(r'^\s*([A-Z_][A-Z0-9_]*)=(.*?)\s*$')


def parse_conf(path):
    conf = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            if line.lstrip().startswith('#'):
                continue
            m = ASSIGN.match(line)
            if not m:
                continue
            key, val = m.group(1), m.group(2).strip()
            if len(val) >= 2 and val[0] == val[-1] and val[0] in '"\'':
                val = val[1:-1]
            conf[key] = val
    return conf


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def hex_addr(conf, key, default=None):
    val = conf.get(key, '')
    if val == '':
        if default is None:
            sys.exit(f'gen_game_identity: {key} is not set')
        return default
    try:
        return int(val, 16)
    except ValueError:
        sys.exit(f'gen_game_identity: {key}={val!r} is not a hex address')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--game', required=True)
    ap.add_argument('--conf', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()

    conf = parse_conf(a.conf)
    for key in ('DISPLAY_NAME', 'EXE_FILENAME'):
        if not conf.get(key):
            sys.exit(f'gen_game_identity: {a.conf} sets no {key}')
    overlay = hex_addr(conf, 'OVERLAY_LOAD_ADDR')
    libcd = hex_addr(conf, 'LIBCD_BLOCK_ADDR')
    cd_cb = hex_addr(conf, 'CD_READ_CB_ADDR', 0)

    text = f'''/* game_identity.c — generated by tools/gen_game_identity.py from
 * {a.conf}. Edit that file, not this one. */

#include "game_extras.h"
#include "psyq_game_hooks.h"

/* The stable machine id keys the [game.{a.game}] scope in openpete.toml. */
const char* game_get_id(void)           {{ return {c_string(a.game)}; }}
const char* game_get_display_name(void) {{ return {c_string(conf['DISPLAY_NAME'])}; }}
const char* game_get_exe_filename(void) {{ return {c_string(conf['EXE_FILENAME'])}; }}

/* Every overlay loads at this one vaddr; the first word landed there is the
 * overlay id that re-points the dispatcher. */
uint32_t psyq_game_overlay_vaddr(void)    {{ return 0x{overlay:08X}u; }}
/* libcd's state block, read by CdStatus, CdLastPos, CdMode and CdLastCom. */
uint32_t psyq_game_libcd_block_addr(void) {{ return 0x{libcd:08X}u; }}
/* The guest slot libcd's own CdReadCallback stores the handler in; 0 when
 * the game registers through the thunk instead. */
uint32_t psyq_game_cd_read_cb_addr(void)  {{ return 0x{cd_cb:08X}u; }}
'''
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write(text)


if __name__ == '__main__':
    main()
