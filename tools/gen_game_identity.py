#!/usr/bin/env python3
"""Emit a game's identity TU from its recomp.conf.

    gen_game_identity.py --game <id> --conf games/<id>/recomp.conf --out <c>

recomp.conf is a shell fragment of KEY=value lines; the keys read here are
DISPLAY_NAME, EXE_FILENAME, OVERLAY_LOAD_ADDR, LIBCD_BLOCK_ADDR and
CD_READ_CB_ADDR (0 when absent: the game registers its read callback through
the thunk). The output defines the game's runtime-descriptor identity,
`<tag>_game_identity` (<tag> is <id> without its hyphens), and its PSYQ
descriptor's recomp.conf addresses, `<tag>_psyq_conf`, so a game's
hand-written sources carry no identity constants.
"""
import argparse
import re
import sys

ASSIGN = re.compile(r'^\s*([A-Z_][A-Z0-9_]*)=(.*?)\s*$')


def parse_conf(path):
    conf = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            if line.lstrip().startswith('#'):
                continue
            m = ASSIGN.match(line)
            if not m:
                continue
            key, val = m.group(1), m.group(2).strip()
            if len(val) >= 2 and val[0] == val[-1] and val[0] in '"\'':
                val = val[1:-1]
            conf[key] = val
    return conf


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def hex_addr(conf, key, default=None):
    val = conf.get(key, '')
    if val == '':
        if default is None:
            sys.exit(f'gen_game_identity: {key} is not set')
        return default
    try:
        return int(val, 16)
    except ValueError:
        sys.exit(f'gen_game_identity: {key}={val!r} is not a hex address')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--game', required=True)
    ap.add_argument('--conf', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()

    conf = parse_conf(a.conf)
    for key in ('DISPLAY_NAME', 'EXE_FILENAME'):
        if not conf.get(key):
            sys.exit(f'gen_game_identity: {a.conf} sets no {key}')
    overlay = hex_addr(conf, 'OVERLAY_LOAD_ADDR')
    libcd = hex_addr(conf, 'LIBCD_BLOCK_ADDR')
    cd_cb = hex_addr(conf, 'CD_READ_CB_ADDR', 0)
    tag = a.game.replace('-', '')

    text = f'''/* game_identity.c - generated by tools/gen_game_identity.py from
 * {a.conf}. Edit that file, not this one. */

#include "openpete_game_runtime.h"
#include "psyq/psyq_game_hooks.h"

/* The stable machine id keys the [game.{a.game}] scope in openpete.toml. */
const openpete_game_identity_t {tag}_game_identity = {{
    .id           = {c_string(a.game)},
    .display_name = {c_string(conf['DISPLAY_NAME'])},
    .exe_filename = {c_string(conf['EXE_FILENAME'])},
}};

/* overlay_vaddr: every overlay loads there; the first word landed there is
 * the overlay id that re-points the dispatcher. libcd_block_addr: libcd's
 * state block, read by CdStatus, CdLastPos, CdMode and CdLastCom.
 * cd_read_cb_addr: the guest slot libcd's own CdReadCallback stores the
 * handler in; 0 when the game registers through the thunk instead. */
const psyq_game_conf_t {tag}_psyq_conf = {{
    .overlay_vaddr    = 0x{overlay:08X}u,
    .libcd_block_addr = 0x{libcd:08X}u,
    .cd_read_cb_addr  = 0x{cd_cb:08X}u,
}};
'''
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write(text)


if __name__ == '__main__':
    main()
