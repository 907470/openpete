#!/usr/bin/env python3
"""gen_channel_sites.py — emit the recompiler's render-channel substitution
table from games/spyro-1/manifest/render_channels.toml.

This is the generation half of "render_channels.toml is the source of truth":
gen_state_regions.py already makes gameplay_state_regions.toml authoritative
for the runtime's hash table; this does the same for the recompiler's
address-keyed substitutions. The recompiler (psxrecomp) loads the emitted
flat file at regen time via --channel-sites and substitutes each site,
instead of carrying the Spyro addresses hardcoded in code_generator.cpp.

Input schema: a channel's `substitution_sites` entry may be either
  * a bare address int (legacy: still hardcoded in code_generator.cpp), or
  * an inline table { addr, imm, kind, knob } describing a GENERATED site.
Only the inline-table entries (those with a `kind`) are emitted here; bare
ints are left to the recompiler's remaining hand-written arms.

Output: one site per line, `<kind> <addr-hex> <imm-hex> <symbol>`, e.g.
  offset_add 0x800259BC 0x1C00 psx_runtime_env_hp_queue_offset
"""
import argparse
import sys
from pathlib import Path

try:
    import tomllib  # py 3.11+
except ImportError:
    import tomli as tomllib  # type: ignore

# kind -> required keys (beyond addr/kind) for that emission shape.
KIND_KEYS = {
    "offset_add": ("imm", "knob"),            # addi: rt = rs + knob
    "const_load": ("imm", "knob"),            # lui/addiu: rt = knob
    "append_call": ("operand", "hook"),       # <verbatim>; hook(operands...);
    "replace_call": ("dest", "operand", "hook"),  # dest = hook(operands...);
}


def coerce_int(v):
    return v if isinstance(v, int) else int(v, 0)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default="games/spyro-1/manifest/render_channels.toml")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    with open(args.manifest, "rb") as f:
        data = tomllib.load(f)
    channels = data.get("channel", [])

    lines: list[str] = [
        "# Auto-generated by tools/gen_channel_sites.py — do not edit.",
        f"# Source: {args.manifest}",
        "# Format: <kind> <addr-hex> <imm-hex> <symbol>",
    ]
    seen: dict[int, str] = {}
    n = 0
    for ch in channels:
        name = ch.get("name", "<unnamed>")
        for s in ch.get("substitution_sites") or []:
            if not isinstance(s, dict):
                continue  # bare int: hardcoded site, not generated
            kind = s.get("kind")
            if kind is None:
                print(f"error: channel {name!r}: inline-table site missing "
                      f"`kind`: {s}", file=sys.stderr)
                return 1
            if kind not in KIND_KEYS:
                print(f"error: channel {name!r}: unknown site kind {kind!r}",
                      file=sys.stderr)
                return 1
            for k in ("addr",) + KIND_KEYS[kind]:
                if k not in s:
                    print(f"error: channel {name!r}: {kind} site missing "
                          f"{k!r}: {s}", file=sys.stderr)
                    return 1
            addr = coerce_int(s["addr"])
            if addr in seen:
                print(f"error: duplicate generated site 0x{addr:08X} "
                      f"(channels {seen[addr]!r} and {name!r})", file=sys.stderr)
                return 1
            seen[addr] = name
            if kind in ("offset_add", "const_load"):
                lines.append(
                    f"{kind} 0x{addr:08X} 0x{coerce_int(s['imm']):X} "
                    f"{s['knob']}")
                n += 1
            elif kind == "append_call":
                # operand may be a single role or "op1,op2,..." (no spaces).
                lines.append(
                    f"append_call 0x{addr:08X} {s['operand']} {s['hook']}")
                n += 1
            elif kind == "replace_call":
                lines.append(
                    f"replace_call 0x{addr:08X} "
                    f"{s['dest']}={s['operand']} {s['hook']}")
                n += 1

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"[gen_channel_sites] wrote {out} ({n} generated sites)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
