#!/usr/bin/env python3
"""gen_mod_docs.py — generate the mod-author reference pages (markdown).

Extracts the SDK surface into docs/modding/pages/reference/ for the
mkdocs-material site (see docs/modding/ and scripts/build-mod-docs.sh):

  api.md        <- core/include/openpete_mod_api.h   (the API contract:
                   struct members with their comment blocks, section
                   splitters, supporting types)
  functions.md  <- manifest/symbols.toml x prototypes.toml (overridable
                   functions: address, kind, natural signature +
                   op_call_*/op_base_* wrapper availability)
  globals.md    <- manifest/globals.toml (the OP_GADDR_* surface)
  structs.md    <- generated openpete_game_structs.h (typed guest-RAM
                   views + offset tables recovered from the pins)
  gallery.md    <- mod.toml header comments of the mods in
                   mods/examples.txt (the SDK-shipped set)
  cpustate.md   <- third_party/psxrecomp/runner/include/psx_runtime.h
                   (the CPUState an override receives: struct prose +
                   one row per field)
  imgui.md      <- third_party/imgui/imgui.h (the version the engine
                   builds) x tools/gen_imgui_annex.py (the denylist that
                   generator applies) — the Dear ImGui annex page

Stdlib only, deterministic output (no timestamps): re-running on
unchanged inputs is byte-identical. Prose comes from the comment blocks
the compiler sees, so there is no second copy to drift.
"""
import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

GEN_NOTE = ("<!-- GENERATED by tools/gen_mod_docs.py — edit the source "
            "it was extracted from, not this file. -->\n\n")


# ── tiny TOML readers (house pattern: the manifests are machine-written,
# a full parser buys nothing) ─────────────────────────────────────────────

def read_toml_blocks(path: Path, block: str):
    """Yield dicts for each [[block]] of simple key = value lines."""
    entries, cur = [], None
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line == f"[[{block}]]":
            cur = {}
            entries.append(cur)
            continue
        if cur is None or not line or line.startswith("#"):
            continue
        if line.startswith("[["):          # a different block type starts
            cur = None
            continue
        m = re.match(r"(\w+)\s*=\s*(.+)$", line)
        if m:
            key, val = m.group(1), m.group(2).strip()
            cur[key] = val
    return entries


def unq(v: str) -> str:
    """A TOML scalar as text: the value with any trailing `# comment`
    removed, then unquoted."""
    v = v.strip()
    if not v.startswith('"'):
        v = v.split('#', 1)[0].strip()
    else:
        m = re.match(r'"([^"]*)"', v)
        if m:
            v = m.group(1)
    return v.strip('"')


# ── api.md ───────────────────────────────────────────────────────────────

def md_prose(text: str) -> str:
    """Extracted comment prose -> markdown-safe text: literal <tokens>
    like <exe>/sdk would otherwise be swallowed as HTML, and bare *
    pairs (pointer decls, src/*.c) would become italics. Backtick spans
    are left alone."""
    out, i = [], 0
    for part in re.split(r"(`[^`]*`|\*\*[^*\n]+\*\*)", text):
        if part.startswith(("`", "**")):
            out.append(part)
        else:
            out.append(part.replace("&", "&amp;").replace("<", "&lt;")
                           .replace("*", "\\*"))
    return "".join(out)


def strip_comment(block: str) -> str:
    """/** ... */ block -> its text, preserving blank-line paragraphs."""
    out = []
    for line in block.splitlines():
        line = re.sub(r"^\s*/?\*+<?/?", "", line)
        line = re.sub(r"\*/\s*$", "", line)
        out.append(line.rstrip())
    text = "\n".join(out).strip("\n")
    lines = text.splitlines()
    pad = min((len(l) - len(l.lstrip()) for l in lines if l.strip()),
              default=0)
    return "\n".join(l[pad:] for l in lines).strip()


PARAM_RE = re.compile(r"^@param\s+(\w+)\s*(.*)$")


def dox_to_md(text: str) -> str:
    """Doxygen tags -> markdown. @param/@return/@since become list
    items and sentences; @code fences; inline @p/@c/#/:: become code
    spans; @brief is dropped (the text stands on its own)."""
    text = re.sub(r"@brief\s+", "", text)
    text = re.sub(r"@[pc]\s+([\w.>-]+)", r"`\1`", text)
    text = re.sub(r"(?<![\w`])#([A-Z_][A-Z0-9_]+)", r"`\1`", text)
    text = re.sub(r"(?<![\w`])::(\w+)", r"`\1`", text)
    text = re.sub(r"(?<![\w`/])(\w+)::(\w+)", r"`\1.\2`", text)
    text = text.replace("@code", "```c").replace("@endcode", "```")
    text = re.sub(r"(?<=\S)[ \t]+@since[ \t]+([^\n]*)", r" Since \1.", text)
    text = re.sub(r"\n(@since|@return|@param)", r"\n\n\1", text, count=1)
    out, i, lines = [], 0, text.splitlines()
    while i < len(lines):
        line = lines[i]
        m = PARAM_RE.match(line)
        if m or line.startswith("@return") or line.startswith("@since") \
                or line.startswith("@par "):
            # gather indented continuation lines
            body = [line]
            while i + 1 < len(lines) and lines[i + 1].startswith(" "):
                i += 1
                body.append(lines[i].strip())
            joined = " ".join(b.strip() for b in body)
            if m:
                pm = PARAM_RE.match(joined)
                out.append(f"- `{pm.group(1)}`: {pm.group(2)}")
            elif joined.startswith("@return"):
                out.append("- Returns: " + joined[len("@return"):].strip())
            elif joined.startswith("@since"):
                out.append("Since " + joined[len("@since"):].strip() + ".")
            else:
                out.append("**" + joined[len("@par "):].strip() + "**")
        else:
            out.append(line)
        i += 1
    return "\n".join(out)


def split_members(body: str):
    """Yield (comments, decl) for struct members: every /** */ block
    between one declaration and the next, then the declaration."""
    i, n = 0, len(body)
    comments = []
    while i < n:
        rest = body[i:]
        ws = len(rest) - len(rest.lstrip())
        i += ws
        if i >= n:
            break
        if body.startswith("/*", i):
            end = body.index("*/", i) + 2
            comments.append(body[i:end])
            i = end
            continue
        end = body.index(";", i) + 1
        yield comments, " ".join(body[i:end].split())
        comments = []
        i = end
    if comments:
        yield comments, ""


def scan_types(pre: str):
    """(comment, code) pairs for the documented items between extern "C"
    and the api struct: typedefs, enums and the version define. Static
    inline helpers and bare forward declarations are skipped."""
    items, i, n, comment = [], 0, len(pre), ""
    while i < n:
        ws = len(pre[i:]) - len(pre[i:].lstrip())
        i += ws
        if i >= n:
            break
        if pre.startswith("/*", i):
            end = pre.index("*/", i) + 2
            comment = pre[i:end]
            i = end
            continue
        if pre.startswith("#define", i):
            end = pre.index("\n", i)
            while pre[end - 1] == "\\":
                end = pre.index("\n", end + 1)
            line = pre[i:end]
            if line.startswith("#define OPENPETE_MOD_API_VERSION"):
                items.append((comment, line))
            comment = ""
            i = end
            continue
        # a declaration: ends at the first ';' outside braces
        depth, j = 0, i
        while j < n:
            c = pre[j]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0 and pre.startswith("static inline", i):
                    break
            elif c == ";" and depth == 0:
                break
            j += 1
        code = pre[i:j + 1].strip()
        if code.startswith(("typedef", "enum")):
            items.append((comment, code))
        comment = ""
        i = j + 1
    return items


MEMBER_NAME_RE = re.compile(r"\(\s*\*\s*(\w+)\s*\)")


def gen_api(api_header: Path) -> str:
    src = api_header.read_text(encoding="utf-8")

    # the file-top overview is the leading /** @file */ block
    intro = ""
    m = re.match(r"\s*(/\*\*(?:[^*]|\*(?!/))*\*/)", src)
    if m:
        intro = "\n".join(l for l in strip_comment(m.group(1)).splitlines()
                          if not l.startswith("@file"))
        intro = dox_to_md(intro).strip()

    out = [GEN_NOTE, "# API reference\n"]
    out.append(f"The contract that every mod compiles against, extracted "
               f"from `{api_header.relative_to(REPO)}`. The staged copy "
               f"lives at `<exe>/sdk/openpete_mod_api.h`.\n")
    out.append("\n".join("> " + l for l in md_prose(intro).splitlines()) + "\n")

    # supporting types: documented typedefs, enums and the version
    # define between extern "C" and the api struct
    pre = src[src.index('extern "C" {') + len('extern "C" {'):
              src.index("typedef struct openpete_mod_api")]
    types = scan_types(pre)
    out.append("## Supporting types\n")
    for comment, code in types:
        code = code.strip()
        if code.startswith("typedef struct CPUState"):
            continue
        if comment.strip():
            out.append(md_prose(dox_to_md(strip_comment(comment))) + "\n")
        out.append(f"```c\n{code}\n```\n")

    # the struct itself
    body = src[src.index("typedef struct openpete_mod_api {"):]
    body = body[body.index("{") + 1: body.index("} openpete_mod_api_t;")]

    members = 0
    sections = []          # rendered per-entry sections, in header order
    index = []             # (group, name, since, brief) for the index table
    group = ""
    for comments, decl in split_members(body):
        prose = ""
        for c in comments:
            text = strip_comment(c)
            if text.startswith("@name"):
                first, _, restp = text.partition("\n")
                group = first[len('@name'):].strip()
                sections.append(f"## {group}\n")
                restp = restp.replace("@{", "").strip()
                if restp:
                    sections.append(md_prose(dox_to_md(restp)) + "\n")
            elif text.strip() in ("@}", ""):
                continue
            else:
                prose = text
        if not decl:
            continue
        name_m = MEMBER_NAME_RE.search(decl)
        name = name_m.group(1) if name_m else decl.split()[-1].rstrip(";")
        sections.append(f"### `api->{name}`\n")
        sections.append(f"```c\n{decl}\n```\n")
        if prose:
            sections.append(md_prose(dox_to_md(prose)) + "\n")
        since_m = re.search(r"@since\s+api\s+(\d+)", prose)
        # @brief runs to the next blank line or @tag; the index keeps
        # its first sentence.
        brief_m = re.search(r"@brief\s+(.*?)(?:\n\s*\n|\n\s*@|\Z)", prose,
                            re.S)
        brief = ""
        if brief_m:
            brief = " ".join(brief_m.group(1).split())
            cut = re.search(r"\.(\s|$)", brief)
            if cut:
                brief = brief[:cut.start() + 1]
            brief = brief.replace("#OPENPETE", "OPENPETE")
        index.append((group, name,
                      since_m.group(1) if since_m else "", brief))
        members += 1

    # Index: one row per entry with the api version it appeared in, so a
    # mod pinning `api = N` can see at a glance which entries it may use.
    out.append("## Index\n")
    out.append("Every entry and the api version that introduced it. A mod "
               "declaring `api = N` in its manifest may use entries with "
               "Since ≤ N; the loader refuses a newer pin than the engine "
               "provides.\n")
    out.append("| Entry | Since | Group | Brief |")
    out.append("|---|---|---|---|")
    for grp, name, since, brief in index:
        anchor = f"api-{name}"  # mkdocs slug of "`api->name`"
        since_cell = f"api {since}" if since else "—"
        out.append(f"| [`api->{name}`](#{anchor}) | {since_cell} | {grp} "
                   f"| {md_prose(brief)} |")
    out.append("")
    missing_since = [n for _, n, s_, _ in index if not s_]
    if missing_since:
        print(f"[gen_mod_docs] WARNING: no @since on {missing_since}",
              file=sys.stderr)
    out.extend(sections)

    # convenience accessors at the tail of the header
    tail = src[src.index("} openpete_mod_api_t;") + len("} openpete_mod_api_t;"):]
    acc = re.findall(r"static inline [^{]+\{[^}]*\}", tail)
    if acc:
        out.append("## Convenience guest accessors\n")
        out.append("Typed guest-RAM helpers, defined inline in the header "
                   "itself, so they need no extra link step:\n")
        sigs = [re.sub(r"\s+", " ", a[: a.index("{")]).strip() for a in acc]
        out.append("```c\n" + "\n".join(s + ";" for s in sigs) + "\n```\n")

    return "\n".join(out), members


# ── functions.md ─────────────────────────────────────────────────────────

def fmt_param(p: str) -> str:
    """'{ type = "int", name = "pY" }' fragments -> 'int pY'."""
    t = re.search(r'type\s*=\s*"([^"]+)"', p)
    n = re.search(r'name\s*=\s*"([^"]+)"', p)
    ty = t.group(1) if t else "?"
    if ty.startswith("ptr:"):
        ty = ty[4:] + "*"
    return f"{ty} {n.group(1) if n else '?'}"


def parse_protos(path: Path):
    protos = {}
    for chunk in path.read_text(encoding="utf-8").split("[[proto]]")[1:]:
        name = re.search(r'name = "([^"]+)"', chunk)
        ret = re.search(r'ret = "([^"]+)"', chunk)
        if not name or not ret:
            continue
        params = re.search(r"params = \[(.*?)\]\s*\n", chunk, re.S)
        plist = ([fmt_param(p) for p in re.findall(r"\{[^}]*\}",
                                                   params.group(1))]
                 if params else [])
        r = ret.group(1)
        if r.startswith("ptr:"):
            r = r[4:] + "*"
        protos[name.group(1)] = (
            f"{r} {name.group(1)}({', '.join(plist) if plist else 'void'})")
    return protos


def gen_functions(symbols: Path, protos_path: Path) -> str:
    funcs = read_toml_blocks(symbols, "function")
    protos = parse_protos(protos_path)

    rows = []
    for f in funcs:
        name = unq(f.get("name", ""))
        rows.append((name, f.get("addr", "?"), unq(f.get("kind", "")),
                     unq(f.get("source_file", ""))))
    rows.sort(key=lambda r: r[0].lower())
    n_proto = sum(1 for r in rows if r[0] in protos)

    out = [GEN_NOTE, "# Functions\n"]
    out.append(
        f"Every guest function that a mod can override or call: "
        f"**{len(rows)}** symbols from `manifest/symbols.toml`, of which "
        f"**{n_proto}** have natural-signature prototypes in "
        f"`manifest/prototypes.toml`.\n\n"
        "Hook a function by name with "
        "`api->override_name(self, \"Name\", fn)`, or by address with "
        "`api->override_addr`. A prototyped function also gets generated "
        "wrappers in `openpete_sdk_wrappers.h`: `OP_OVERRIDE_IMPL_Name`, "
        "`OP_REGISTER_OVERRIDE_Name`, `op_base_Name`, and "
        "`op_call_Name`, which give you typed arguments, pointer "
        "marshalling, and argument-register save and restore. Everything "
        "else uses the raw tier: read `cpu->a0` through `cpu->a3`, and "
        "write `cpu->v0`.\n\n"
        "A `func_XXXXXXXX` name belongs to the part of the decompilation "
        "that isn't named yet. Those names resolve forever under the "
        "decompilation promotion contract, but the loader warns you once "
        "a stable name exists.\n")

    letter = None
    for name, addr, kind, srcf in rows:
        l = name[0].upper() if name[:1].isalpha() else "#"
        if l != letter:
            letter = l
            out.append(f"\n## {letter}\n")
            out.append("| Function | Address | Kind | Signature | Source |")
            out.append("|---|---|---|---|---|")
        sig = protos.get(name)
        sigcell = f"`{sig}` + wrappers" if sig else "raw tier"
        out.append(f"| `{name}` | `{addr}` | {kind} | {sigcell} | {srcf} |")
    out.append("")
    return "\n".join(out), len(rows), n_proto


# ── globals.md ───────────────────────────────────────────────────────────

def gen_globals(globals_path: Path) -> str:
    gl = read_toml_blocks(globals_path, "global")
    rows = sorted(
        ((unq(g.get("name", "")), g.get("addr", "?"),
          unq(g.get("section", "")), unq(g.get("source_file", "")))
         for g in gl),
        key=lambda r: r[0].lower())

    out = [GEN_NOTE, "# Globals\n"]
    out.append(
        f"**{len(rows)}** named guest-RAM globals from "
        "`manifest/globals.toml`. Each one is exported to mods as an "
        "`OP_GADDR_<Name>` virtual-address constant in "
        "`openpete_sdk_symbols.h`. Read and write them through "
        "`api->guest()`, or through the `op_read_*` and `op_write_*` "
        "helpers:\n\n"
        "```c\n"
        "uint32_t spyro = OP_GADDR_g_Spyro;\n"
        "int x = op_read_s32(api, spyro + 0x0C);   /* position.x */\n"
        "```\n\n"
        "Pointers stored inside guest structs are guest virtual "
        "addresses, so translate them again before you follow them. A "
        "`D_80XXXXXX` name belongs to the part of the decompilation that "
        "isn't named yet.\n")
    letter = None
    for name, addr, section, srcf in rows:
        l = name.lstrip("gD_")[:1].upper() or "#"
        base = name[2:] if name.startswith("g_") else name
        l = base[:1].upper() if base[:1].isalpha() else "#"
        if l != letter:
            letter = l
            out.append(f"\n## {letter}\n")
            out.append("| Global | Address | Section | Source |")
            out.append("|---|---|---|---|")
        out.append(f"| `{name}` | `{addr}` | {section} | {srcf} |")
    out.append("")
    return "\n".join(out), len(rows)


# ── structs.md ───────────────────────────────────────────────────────────

def gen_structs(structs_header: Path) -> str:
    out = [GEN_NOTE, "# Game structs\n"]
    if not structs_header or not structs_header.exists():
        out.append("!!! warning\n    `openpete_game_structs.h` wasn\'t "
                   "found. Build the game target once, then run "
                   "`scripts/build-mod-docs.sh` again.\n")
        return "\n".join(out), 0

    src = structs_header.read_text(encoding="utf-8")
    intro_m = re.match(r"\s*(/\*(?:[^*]|\*(?!/))*\*/)", src)
    if intro_m:
        intro = "\n".join(l for l in strip_comment(intro_m.group(1)).splitlines()
                          if not l.startswith("@file"))
        out.append("\n".join("> " + l for l in md_prose(
            dox_to_md(intro).strip()).splitlines()) + "\n")

    sizes = dict(re.findall(
        r'_Static_assert\(sizeof\((\w+)\)\s*==\s*(0x[0-9a-fA-F]+|\d+)', src))
    offsets = {}
    for s, f, off in re.findall(
            r'_Static_assert\(offsetof\((\w+),\s*(\w+)\)\s*==\s*'
            r'(0x[0-9a-fA-F]+|\d+)', src):
        offsets.setdefault(s, []).append((f, off))

    n = 0
    for m in re.finditer(r"typedef struct (\w+) \{(.*?)\} \1;", src, re.S):
        name, body = m.group(1), m.group(0)
        out.append(f"## `{name}`\n")
        meta = []
        if name in sizes:
            meta.append(f"`sizeof == {sizes[name]}`")
        if meta:
            out.append(" · ".join(meta) + ". The layout is pinned, so "
                       "drift fails the mod's compile rather than a "
                       "player's session.\n")
        if name in offsets:
            out.append("| Field | Offset |")
            out.append("|---|---|")
            for f, off in offsets[name]:
                out.append(f"| `{f}` | `{off}` |")
            out.append("")
        out.append(f"```c\n{body.strip()}\n```\n")
        n += 1
    return "\n".join(out), n


# ── gallery.md ───────────────────────────────────────────────────────────


def read_examples(mods_dir: Path) -> list:
    """mods/examples.txt: the ids package-dist.sh stages into
    <exe>/sdk/examples/, one per line, comments with #."""
    f = mods_dir / "examples.txt"
    if not f.exists():
        return []
    return [l.strip() for l in f.read_text(encoding="utf-8").splitlines()
            if l.strip() and not l.startswith("#")]


def gen_gallery(mods_dir: Path) -> str:
    out = [GEN_NOTE, "# Examples\n"]
    shipped = read_examples(mods_dir)
    out.append("The example mods that ship with the SDK under "
               "`<exe>/sdk/examples/<id>/`, extracted from each one's "
               "`mod.toml` header. Copy one into your `mods` directory "
               "to run it; start from the one nearest to your idea.\n")
    by_id = {t.parent.name: t for t in mods_dir.glob("*/mod.toml")}
    missing = [e for e in shipped if e not in by_id]
    if missing:
        sys.exit(f"gen_mod_docs: mods/examples.txt names {missing} "
                 f"but no such mod directory exists")
    sections = []
    for toml in (by_id[e] for e in shipped):
        text = toml.read_text(encoding="utf-8")
        desc = []
        for line in text.splitlines():
            if line.startswith("#"):
                desc.append(line.lstrip("#").strip())
            elif line.strip():
                break
        fields = {}
        for m in re.finditer(r'^(\w+)\s*=\s*(.+)$', text, re.M):
            fields.setdefault(m.group(1), unq(m.group(2)))
        mid = fields.get("id", toml.parent.name)
        title = fields.get("name", mid)
        srcs = sorted(p.name for p in (toml.parent / "src").glob("*.c"))
        sm = fields.get("sim_mutative")
        mutative = (sm == "true") if sm in ("true", "false") \
            else bool(srcs) or bool(re.search(r"^\[\[level\]\]", text, re.M))
        bits = [f"v{fields.get('version', '?')}"]
        bits.append("writes guest RAM" if mutative else "writes no guest RAM")
        blocks = sorted({b for b in re.findall(r"^\[\[(\w+)\]\]", text, re.M)})
        if blocks:
            bits.append(", ".join(f"`[[{b}]]`" for b in blocks))
        if srcs:
            bits.append("src: " + ", ".join(f"`{s}`" for s in srcs))
        sec = [f"## `{mid}` — {title}\n", " · ".join(bits) + "\n"]
        # A blank comment line in the header is a paragraph break.
        paras, cur = [], []
        for d in desc:
            if d:
                cur.append(d)
            elif cur:
                paras.append(" ".join(cur)); cur = []
        if cur:
            paras.append(" ".join(cur))
        sec.extend(md_prose(pg) + "\n" for pg in paras)
        sections.append("\n".join(sec))
    out.extend(sections)
    return "\n".join(out), len(sections)


# ── cpustate.md ──────────────────────────────────────────────────────────

SCALAR_FIELD_RE = re.compile(
    r"^\s*(\w+)\s+([\w, ]+?)(\[\d+\])?;\s*/\*\*<\s*(.*?)\s*\*/")
FNPTR_FIELD_RE = re.compile(
    r"^\s*([\w ]+?)\s*\(\*(\w+)\)(\([^)]*\));\s*/\*\*<\s*(.*?)\s*\*/")


def gen_cpustate(runtime_header: Path):
    """psx_runtime.h -> cpustate.md: the struct's comment block as prose
    and a table with one row per declarator (a line declaring several
    registers with one comment becomes one row per register)."""
    out = [GEN_NOTE, "# CPUState\n"]
    if not runtime_header.exists():
        out.append(f"!!! warning\n    `{runtime_header.name}` not found.\n")
        return "\n".join(out), 0
    src = runtime_header.read_text(encoding="utf-8")
    m = re.search(r"(/\*\*(?:(?!\*/).)*?\*/)\s*typedef struct CPUState \{(.*?)\} CPUState;",
                  src, re.S)
    if not m:
        sys.exit("gen_mod_docs: CPUState not found in psx_runtime.h")
    out.append(md_prose(dox_to_md(strip_comment(m.group(1)))) + "\n")
    out.append("Declared in `psx_runtime.h`, shipped in `sdk/`; include it "
               "beside `openpete_mod_api.h`, which only forward-declares "
               "the type.\n")
    rows = []
    for line in m.group(2).splitlines():
        fm = FNPTR_FIELD_RE.match(line)
        if fm:
            ret, name, params, brief = fm.groups()
            rows.append((f"{ret.strip()} (*{name}){params}", "",
                         md_prose(dox_to_md(brief))))
            continue
        fm = SCALAR_FIELD_RE.match(line)
        if not fm:
            continue
        ctype, names, suffix, brief = fm.groups()
        for name in [n.strip() for n in names.split(",")]:
            rows.append((name + (suffix or ""), ctype,
                         md_prose(dox_to_md(brief))))
    out.append("## Fields\n")
    out.append("| Field | Type | Meaning |")
    out.append("|---|---|---|")
    for decl, ctype, brief in rows:
        out.append(f"| `{decl}` | {('`' + ctype + '`') if ctype else '—'} | {brief} |")
    out.append("")
    return "\n".join(out), len(rows)



# ── imgui.md ─────────────────────────────────────────────────────────────

def imgui_version(imgui_header: Path) -> str:
    """The Dear ImGui version the engine builds against, from the pinned
    header. Never hard-coded here: the page would then claim a version the
    SDK does not ship the moment the submodule moves."""
    m = re.search(r'^#define\s+IMGUI_VERSION\s+"([^"]+)"',
                  imgui_header.read_text(encoding="utf-8"), re.M)
    if not m:
        sys.exit(f"gen_mod_docs: no IMGUI_VERSION in {imgui_header}")
    return m.group(1)


def imgui_denylist(annex_gen: Path) -> list:
    """The denied families, taken from the generator that applies them, so
    the page and the table cannot disagree."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("gen_imgui_annex", annex_gen)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return list(mod.DENY_DOC)


def gen_imgui(imgui_header: Path, annex_gen: Path):
    ver = imgui_version(imgui_header)
    deny = imgui_denylist(annex_gen)
    out = [GEN_NOTE, "# Dear ImGui annex\n"]
    out.append(
        f"`openpete_imgui.h` hands a mod the whole Dear ImGui C API — "
        f"Dear ImGui {ver}, through the C bindings "
        f"[dear_bindings](https://github.com/dearimgui/dear_bindings) "
        f"generates — driving the engine's own ImGui context.\n")
    out.append(
        "[`openpete_mod_ui.h`](api.md) stays the simple path: eleven "
        "widgets, no opt-in, and no ImGui version in the mod's build. Reach "
        "for this header when those eleven are not enough — windows, "
        "tables, plots, tree nodes, tabs, popups, colour editors, drag and "
        "input widgets, draw lists, fonts.\n")

    out.append("## Opting in\n")
    out.append(
        "Include the header and place the macro at file scope in exactly "
        "one source file of the mod:\n")
    out.append("""```c
#include <openpete_mod_api.h>
#include <openpete_mod_ui.h>
#include <openpete_imgui.h>

OPENPETE_MOD_IMGUI()

static void ui_draw(const openpete_mod_ui_t* ui) {
    (void)ui;
    if (ImGui_Begin("my window", NULL, 0)) {
        ImGui_Text("hello from a mod");
    }
    ImGui_End();
}
OPENPETE_MOD_UI_SECTION(ui_draw)
```
""")
    out.append(
        "`OPENPETE_MOD_IMGUI()` defines the function-pointer table every "
        "`ImGui_*` call reads and exports the descriptor the loader "
        "resolves when it opens the mod. A mod without the macro "
        "references no table and nothing is bound. Nothing is added to the "
        "mod's compile line and the mod still links no engine symbol: an "
        "`ImGui_*` name is a macro over one table entry.\n")
    out.append(
        "The descriptor pins the Dear ImGui version, the table size and a "
        "digest of the table's entries. A prebuilt object built against a "
        "different SDK is refused and its mod disabled, because a mod bound "
        "to a table whose slots have moved would call the wrong function on "
        "its first widget. A source mod never meets that refusal: the SDK "
        "headers are part of the mod's build key, so a Dear ImGui bump "
        "recompiles it at the next boot.\n")
    out.append(
        "Binding is logged once per mod:\n\n"
        "```\n"
        "mods: <id>: imgui annex bound (ImGui " + ver + ", N entries)\n"
        "```\n")

    out.append("## Where the calls are legal\n")
    out.append(
        "Inside a UI section body, and nowhere else. A body runs on the "
        "compose thread, inside the engine's ImGui frame, while the mod is "
        "enabled. A plain `OPENPETE_MOD_UI_SECTION` body runs in the mod's "
        "node of the Mods section, so only while the dev overlay is open; "
        "an always section (below) runs on every present.\n")
    out.append(
        "A call from a present hook or a tick hook is dropped: those run "
        "outside the frame and on another thread, where Dear ImGui's own "
        "checks are compiled out and the failure would be a null-window "
        "dereference. The call returns a zeroed value and the engine logs "
        "the mod and the function once:\n\n"
        "```\n"
        "mods: <id>: ImGui_Begin called outside the mod's UI section "
        "(from a present or tick hook) — dropped\n"
        "```\n")
    out.append(
        "The body still receives the `openpete_mod_ui_t*` argument, so the "
        "vtable and the annex mix freely in one body. An `ImGui_Begin` "
        "inside the mod's node opens an independent top-level window, which "
        "is Dear ImGui's documented behaviour.\n")

    out.append("## Always-on sections\n")
    out.append(
        "Register the body with the flags form to run it on every present "
        "instead of only inside the Mods panel:\n")
    out.append("""```c
OPENPETE_MOD_UI_SECTION_FLAGS(ui_draw, OPENPETE_MOD_UI_ALWAYS)
```
""")
    out.append(
        "This is how a mod keeps a stats window or a draw-list overlay on "
        "screen during play. The rules that change with it:\n")
    out.append(
        "- **The body owns its windows.** It runs at top level, not inside "
        "a tree node — a node the player collapsed must not make a window "
        "disappear — so every widget emitted outside an `ImGui_Begin` "
        "lands in Dear ImGui's default debug window. Open a window and put "
        "the content in it.\n"
        "- **No input while the overlay is closed.** The game keeps the "
        "mouse and the keyboard, and the engine puts "
        "`ImGuiWindowFlags_NoInputs` on every window the body opens: no "
        "clicks, no nav, no hover. `ui->overlay_open()` returns 1 while the "
        "overlay is up, which is when widgets in an always window can be "
        "used; draw the interactive half only then. `ImGui_GetMousePos` "
        "still reports the game's cursor.\n"
        "- **The pass is skipped while the in-game settings menu is "
        "open.** The menu and the dev overlay are mutually exclusive input "
        "owners and the menu is drawn first, so an always window would "
        "paint over it.\n"
        "- **`ui_status` lines stay in the mod's node** in the Mods "
        "section, where the rest of the mod's row is.\n"
        "- **Always windows are not on the chrome anchor ledger** "
        "(`openpete_overlay_anchor.h`), which places the perf readout and "
        "the toasts. Position your own windows.\n")
    out.append(
        "**Chrome, not content.** Dear ImGui records into the live present "
        "only, so an always window is never in a `--record` capture, a "
        "screenshot, or an A/B compose, and it is drawn on top of a "
        "COMPOSITE postfx chain rather than through it. A HUD that must "
        "appear in captures belongs in the draw service (`draw_text`), "
        "which is drawn pre-chain as content. The two paths have opposite "
        "record policy on purpose.\n")
    out.append(
        "The containment below is unchanged for an always body: same guard "
        "wrappers, same error bracket, same three-strike refusal, same "
        "engagement counter.\n")
    out.append(
        "The purity rule is unchanged and matters more here: guest access, "
        "game calls and registration are refused inside a body. Read guest "
        "RAM in a tick hook, copy what the panel needs into host memory, "
        "and let the body read the copy.\n")

    out.append("## Calls the table does not carry\n")
    out.append(
        "These are absent from the table and from the macros. The "
        "`dcimgui.h` declaration stays, so calling one fails the mod's own "
        "compile with an undefined reference, which is the diagnostic "
        "wanted:\n")
    for line in deny:
        # The generator's prose names bare identifiers; a trailing * is part
        # of the family name, so each goes in a code span rather than
        # through the italics escape.
        out.append("- " + re.sub(r"\bIm(?:Gui|Font|Draw)(?:\w|\*)*",
                                 lambda m: "`" + m.group(0) + "`", line))
    out.append("")
    out.append(
        "Scope: the list protects the frame and context lifecycle and the "
        "input path. It does not protect data reachable through structs. "
        "`ImGui_GetIO()` returns a writable `ImGuiIO`, and a mod can "
        "address another panel by name. That is unguarded by design: mod C "
        "runs with the game's privileges. The bracket below puts a named "
        "set of those fields back after every body, and the rest stays a "
        "mod author's responsibility.\n")
    out.append(
        "`ImGui_GetIO`, `ImGui_GetStyle`, `ImGui_GetWindowDrawList`, "
        "`ImGui_GetForegroundDrawList`, the `ImDrawList_*` family and "
        "`ImGui_ShowDemoWindow` are all callable: they are the point of the "
        "escape hatch.\n")

    out.append("## What contains a body\n")
    out.append(
        "Dear ImGui reports unbalanced `Begin`/`End`, `Push`/`Pop` and "
        "similar misuse as recoverable user errors. The engine brackets "
        "every body:\n")
    out.append(
        "- the ImGui stack sizes are stored before the body and recovered "
        "after it, so a window left open does not swallow the panel or the "
        "frame;\n"
        "- `ImGuiStyle` and the `ImGuiIO` fields a body can reach "
        "(`IniFilename`, `LogFilename`, `ConfigFlags`, `UserData`, and the "
        "backend user-data pointers) are snapshotted and put back;\n"
        "- Dear ImGui's own assert and error tooltip are switched off for "
        "the body and the engine logs the error against the mod instead:\n")
    out.append(
        "```\n"
        "mods: <id>: Dear ImGui error inside the mod's UI section: "
        "Missing End()\n"
        "```\n")
    out.append(
        "A body that errors on three consecutive presents loses its section "
        "for the rest of the session, with one more line saying so, so one "
        "broken mod cannot flood the log or distort the panel. Misuse Dear "
        "ImGui cannot recover from — a null `ImDrawList*`, a bad pointer "
        "into `ImGuiIO` — crashes the process, which is the existing "
        "contract for mod C.\n")
    out.append(
        "Calls that reach Dear ImGui are counted per body. The first "
        "non-zero count is logged and the running count shows in the mod's "
        "tooltip in the Mods panel:\n\n"
        "```\n"
        "mods: <id>: imgui annex engaged (N calls)\n"
        "```\n")

    out.append("## Learning the API\n")
    out.append(
        "The API is upstream's, so this page does not restate it. Names "
        "follow dear_bindings: `ImGui::Begin` is `ImGui_Begin`, a call "
        "passing every optional argument is the `...Ex` form "
        "(`ImGui_PlotLinesEx`), an overload takes a type suffix "
        "(`ImGui_ComboChar`), and a member function takes its struct's "
        "prefix (`ImDrawList_AddLine`). The reference is the comment block "
        "on each declaration in `sdk/dcimgui.h`, and "
        "`ImGui_ShowDemoWindow()` — callable from a body — is the live "
        "catalogue every Dear ImGui user reads.\n")
    out.append(
        "One thing a mod cannot do: take the address of an `ImGui_*` "
        "function. Take the table entry instead "
        "(`openpete_imgui_tbl->ImGui_Begin`).\n")
    out.append(
        "`mods/imgui-panel` is the worked example: a tick hook samples the "
        "level's mobys into a host-side ring, and the section draws it as a "
        "plot, a table, a floating window with a colour editor, and a "
        "foreground draw-list marker. Its section is an always section: the "
        "stats window and the marker draw every present, the detail window "
        "only while the overlay is open. Two of its settings rows "
        "deliberately break the rules above so the containment paths can be "
        "watched.\n")
    return "\n".join(out), len(deny)


# ── main ─────────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--api-header",
                    default=REPO / "core/include/openpete_mod_api.h",
                    type=Path)
    ap.add_argument("--symbols",
                    default=REPO / "games/spyro-1/manifest/symbols.toml",
                    type=Path)
    ap.add_argument("--globals", dest="globals_",
                    default=REPO / "games/spyro-1/manifest/globals.toml",
                    type=Path)
    ap.add_argument("--protos",
                    default=REPO / "games/spyro-1/manifest/prototypes.toml",
                    type=Path)
    ap.add_argument("--structs", type=Path, default=None,
                    help="generated openpete_game_structs.h (default: "
                         "search known build dirs)")
    ap.add_argument("--mods-dir", default=REPO / "mods", type=Path)
    ap.add_argument("--psx-runtime",
                    default=REPO / "third_party/psxrecomp/runner/include/psx_runtime.h",
                    type=Path)
    ap.add_argument("--imgui-header",
                    default=REPO / "third_party/imgui/imgui.h",
                    type=Path)
    ap.add_argument("--imgui-annex-gen",
                    default=REPO / "tools/gen_imgui_annex.py",
                    type=Path)
    ap.add_argument("--out",
                    default=REPO / "docs/modding/pages/reference",
                    type=Path)
    args = ap.parse_args()

    structs = args.structs
    if structs is None:
        for cand in ("build/linux-release", "build/dev",
                     "build/windows-mingw", "build/windows-mingw-shared"):
            p = REPO / cand / "games/spyro-1/mod_sdk_gen/openpete_game_structs.h"
            if p.exists():
                structs = p
                break

    args.out.mkdir(parents=True, exist_ok=True)

    api_md, n_api = gen_api(args.api_header)
    fn_md, n_fn, n_proto = gen_functions(args.symbols, args.protos)
    gl_md, n_gl = gen_globals(args.globals_)
    st_md, n_st = gen_structs(structs)
    ga_md, n_mods = gen_gallery(args.mods_dir)
    cs_md, n_cs = gen_cpustate(args.psx_runtime)
    ig_md, n_deny = gen_imgui(args.imgui_header, args.imgui_annex_gen)

    for fname, content in (("api.md", api_md), ("functions.md", fn_md),
                           ("globals.md", gl_md), ("structs.md", st_md),
                           ("gallery.md", ga_md), ("cpustate.md", cs_md),
                           ("imgui.md", ig_md)):
        (args.out / fname).write_text(content, encoding="utf-8")

    if n_cs < 40:   # 32 GPRs + pc/hi/lo + 3 arrays + 10 callbacks
        sys.exit(f"gen_mod_docs: only {n_cs} CPUState fields parsed — the "
                 "struct layout or comment style changed; fix the extractor")
    if n_api < 25:  # 28 entries + api_version at api v1
        sys.exit(f"gen_mod_docs: only {n_api} API members parsed — the "
                 "header layout changed; fix the extractor")
    print(f"[gen_mod_docs] api: {n_api} members | functions: {n_fn} "
          f"({n_proto} prototyped) | globals: {n_gl} | structs: {n_st} | "
          f"gallery: {n_mods} mods | cpustate: {n_cs} fields | "
          f"imgui: {n_deny} denied families -> {args.out}")


if __name__ == "__main__":
    main()
