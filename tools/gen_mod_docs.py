#!/usr/bin/env python3
"""gen_mod_docs.py — generate the mod-author reference pages (markdown).

Extracts the SDK surface into docs/modding/pages/reference/ for the
mkdocs-material site (see docs/modding/ and scripts/build-mod-docs.sh):

  api.md        <- core/include/openpete_mod_api.h   (the API contract:
                   struct members with their comment blocks, section
                   splitters, supporting types) + core/include/
                   openpete_mod_ui.h (the separately versioned widget
                   vtable, appended as `## UI widgets`)
  spyro-1/functions.md
                <- manifest/symbols.toml x prototypes.toml (overridable
                   functions: address, natural signature +
                   op_call_*/op_base_* wrapper availability)
  spyro-1/globals.md
                <- manifest/globals.toml (the OP_GADDR_* surface)
  spyro-1/structs.md
                <- generated openpete_game_structs.h (typed guest-RAM
                   views + offset tables recovered from the pins)
  The Source column of the function and global tables and the "Defined
  in" line of each struct link to the definition in the decompilation
  repository (games/spyro-1/spyro-1: the .gitmodules url, the checked-out
  commit, and the line found by scanning the file symbols.toml names).

  The three above come from one game's manifests; the rest describe the
  engine, so they sit a level up from the per-game slug.
  examples.md   <- mod.toml header comments of the mods in
                   mods/examples.txt (the SDK-shipped set)
  cpustate.md   <- third_party/psxrecomp/runner/include/psx_runtime.h
                   (the CPUState an override receives: struct prose +
                   one row per field)
  imgui.md      <- third_party/imgui/imgui.h (the version the engine
                   builds) x tools/gen_imgui_table.py (the denylist that
                   generator applies) — the ImGui page. Written to
                   pages/, one level above the reference set: it is a
                   guide, not an extracted catalogue.

Stdlib only, deterministic output (no timestamps): re-running on
unchanged inputs is byte-identical. Prose comes from the comment blocks
the compiler sees, so there is no second copy to drift.
"""
import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

GEN_NOTE = ("<!-- GENERATED by tools/gen_mod_docs.py — edit the source "
            "it was extracted from, not this file. -->\n\n")


# ── tiny TOML readers (house pattern: the manifests are machine-written,
# a full parser buys nothing) ─────────────────────────────────────────────

def read_toml_blocks(path: Path, block: str):
    """Yield dicts for each [[block]] of simple key = value lines."""
    entries, cur = [], None
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line == f"[[{block}]]":
            cur = {}
            entries.append(cur)
            continue
        if cur is None or not line or line.startswith("#"):
            continue
        if line.startswith("[["):          # a different block type starts
            cur = None
            continue
        m = re.match(r"(\w+)\s*=\s*(.+)$", line)
        if m:
            key, val = m.group(1), m.group(2).strip()
            cur[key] = val
    return entries


def unq(v: str) -> str:
    """A TOML scalar as text: the value with any trailing `# comment`
    removed, then unquoted."""
    v = v.strip()
    if not v.startswith('"'):
        v = v.split('#', 1)[0].strip()
    else:
        m = re.match(r'"([^"]*)"', v)
        if m:
            v = m.group(1)
    return v.strip('"')


# ── api.md ───────────────────────────────────────────────────────────────

def md_prose(text: str) -> str:
    """Extracted comment prose -> markdown-safe text: literal <tokens>
    like <exe>/sdk would otherwise be swallowed as HTML, and bare *
    pairs (pointer decls, src/*.c) would become italics. Backtick spans
    are left alone."""
    out, i = [], 0
    for part in re.split(r"(`[^`]*`|\*\*[^*\n]+\*\*)", text):
        if part.startswith(("`", "**")):
            out.append(part)
        else:
            out.append(part.replace("&", "&amp;").replace("<", "&lt;")
                           .replace("*", "\\*"))
    return "".join(out)


def strip_comment(block: str) -> str:
    """/** ... */ block -> its text, preserving blank-line paragraphs."""
    out = []
    for line in block.splitlines():
        line = re.sub(r"^\s*/?\*+<?/?", "", line)
        line = re.sub(r"\*/\s*$", "", line)
        out.append(line.rstrip())
    text = "\n".join(out).strip("\n")
    lines = text.splitlines()
    pad = min((len(l) - len(l.lstrip()) for l in lines if l.strip()),
              default=0)
    return "\n".join(l[pad:] for l in lines).strip()


PARAM_RE = re.compile(r"^@param\s+(\w+)\s*(.*)$")


def dox_to_md(text: str) -> str:
    """Doxygen tags -> markdown. @param/@return/@since become list
    items and sentences; @code fences; inline @p/@c/#/:: become code
    spans; @brief is dropped (the text stands on its own)."""
    text = re.sub(r"@brief\s+", "", text)
    text = re.sub(r"@[pc]\s+([\w.>-]+)", r"`\1`", text)
    text = re.sub(r"(?<![\w`])#([A-Z_][A-Z0-9_]+)", r"`\1`", text)
    text = re.sub(r"(?<![\w`])::(\w+)", r"`\1`", text)
    text = re.sub(r"(?<![\w`/])(\w+)::(\w+)", r"`\1.\2`", text)
    text = text.replace("@code", "```c").replace("@endcode", "```")
    text = re.sub(r"(?<=\S)[ \t]+@since[ \t]+([^\n]*)", r" Since \1.", text)
    text = re.sub(r"\n(@since|@return|@param)", r"\n\n\1", text, count=1)
    out, i, lines = [], 0, text.splitlines()
    while i < len(lines):
        line = lines[i]
        m = PARAM_RE.match(line)
        if m or line.startswith("@return") or line.startswith("@since") \
                or line.startswith("@par "):
            # gather indented continuation lines
            body = [line]
            while i + 1 < len(lines) and lines[i + 1].startswith(" "):
                i += 1
                body.append(lines[i].strip())
            joined = " ".join(b.strip() for b in body)
            if m:
                pm = PARAM_RE.match(joined)
                out.append(f"- `{pm.group(1)}`: {pm.group(2)}")
            elif joined.startswith("@return"):
                out.append("- Returns: " + joined[len("@return"):].strip())
            elif joined.startswith("@since"):
                out.append("Since " + joined[len("@since"):].strip() + ".")
            else:
                out.append("**" + joined[len("@par "):].strip() + "**")
        else:
            out.append(line)
        i += 1
    return "\n".join(out)


def split_members(body: str):
    """Yield (comments, decl) for struct members: every /** */ block
    between one declaration and the next, then the declaration."""
    i, n = 0, len(body)
    comments = []
    while i < n:
        rest = body[i:]
        ws = len(rest) - len(rest.lstrip())
        i += ws
        if i >= n:
            break
        if body.startswith("/*", i):
            end = body.index("*/", i) + 2
            comments.append(body[i:end])
            i = end
            continue
        end = body.index(";", i) + 1
        yield comments, " ".join(body[i:end].split())
        comments = []
        i = end
    if comments:
        yield comments, ""


def scan_types(pre: str):
    """(comment, code) pairs for the documented items between extern "C"
    and the api struct: typedefs, enums and the version define. Static
    inline helpers and bare forward declarations are skipped."""
    items, i, n, comment = [], 0, len(pre), ""
    while i < n:
        ws = len(pre[i:]) - len(pre[i:].lstrip())
        i += ws
        if i >= n:
            break
        if pre.startswith("/*", i):
            end = pre.index("*/", i) + 2
            comment = pre[i:end]
            i = end
            continue
        if pre.startswith("#define", i):
            end = pre.index("\n", i)
            while pre[end - 1] == "\\":
                end = pre.index("\n", end + 1)
            line = pre[i:end]
            if line.startswith("#define OPENPETE_MOD_API_VERSION"):
                items.append((comment, line))
            comment = ""
            i = end
            continue
        # a declaration: ends at the first ';' outside braces
        depth, j = 0, i
        while j < n:
            c = pre[j]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0 and pre.startswith("static inline", i):
                    break
            elif c == ";" and depth == 0:
                break
            j += 1
        code = pre[i:j + 1].strip()
        if code.startswith(("typedef", "enum")):
            items.append((comment, code))
        comment = ""
        i = j + 1
    return items


MEMBER_NAME_RE = re.compile(r"\(\s*\*\s*(\w+)\s*\)")


def gen_api(api_header: Path) -> str:
    src = api_header.read_text(encoding="utf-8")

    # the file-top overview is the leading /** @file */ block
    intro = ""
    m = re.match(r"\s*(/\*\*(?:[^*]|\*(?!/))*\*/)", src)
    if m:
        intro = "\n".join(l for l in strip_comment(m.group(1)).splitlines()
                          if not l.startswith("@file"))
        intro = dox_to_md(intro).strip()

    out = [GEN_NOTE, "# API reference\n"]
    out.append(f"The contract that every mod compiles against, extracted "
               f"from `{api_header.relative_to(REPO)}`. The staged copy "
               f"lives at `<exe>/sdk/openpete_mod_api.h`.\n")
    out.append("\n".join("> " + l for l in md_prose(intro).splitlines()) + "\n")

    # supporting types: documented typedefs, enums and the version
    # define between extern "C" and the api struct
    pre = src[src.index('extern "C" {') + len('extern "C" {'):
              src.index("typedef struct openpete_mod_api")]
    types = scan_types(pre)
    out.append("## Supporting types\n")
    for comment, code in types:
        code = code.strip()
        if code.startswith("typedef struct CPUState"):
            continue
        if comment.strip():
            out.append(md_prose(dox_to_md(strip_comment(comment))) + "\n")
        out.append(f"```c\n{code}\n```\n")

    # the struct itself
    body = src[src.index("typedef struct openpete_mod_api {"):]
    body = body[body.index("{") + 1: body.index("} openpete_mod_api_t;")]

    members = 0
    sections = []          # rendered per-entry sections, in header order
    index = []             # (group, name, since, brief) for the index table
    group = ""
    for comments, decl in split_members(body):
        prose = ""
        for c in comments:
            text = strip_comment(c)
            if text.startswith("@name"):
                first, _, restp = text.partition("\n")
                group = first[len('@name'):].strip()
                sections.append(f"## {group}\n")
                restp = restp.replace("@{", "").strip()
                if restp:
                    sections.append(md_prose(dox_to_md(restp)) + "\n")
            elif text.strip() in ("@}", ""):
                continue
            else:
                prose = text
        if not decl:
            continue
        name_m = MEMBER_NAME_RE.search(decl)
        name = name_m.group(1) if name_m else decl.split()[-1].rstrip(";")
        sections.append(f"### `api->{name}`\n")
        sections.append(f"```c\n{decl}\n```\n")
        if prose:
            sections.append(md_prose(dox_to_md(prose)) + "\n")
        since_m = re.search(r"@since\s+api\s+(\d+)", prose)
        # @brief runs to the next blank line or @tag; the index keeps
        # its first sentence.
        brief_m = re.search(r"@brief\s+(.*?)(?:\n\s*\n|\n\s*@|\Z)", prose,
                            re.S)
        brief = ""
        if brief_m:
            brief = " ".join(brief_m.group(1).split())
            cut = re.search(r"\.(\s|$)", brief)
            if cut:
                brief = brief[:cut.start() + 1]
            brief = brief.replace("#OPENPETE", "OPENPETE")
        index.append((group, name,
                      since_m.group(1) if since_m else "", brief))
        members += 1

    # Index: one row per entry with the api version it appeared in, so a
    # mod pinning `api = N` can see at a glance which entries it may use.
    out.append("## Index\n")
    out.append("Every entry and the api version that introduced it. A mod "
               "declaring `api = N` in its manifest may use entries with "
               "Since ≤ N; the loader refuses a newer pin than the engine "
               "provides.\n")
    out.append("| Entry | Since | Group | Brief |")
    out.append("|---|---|---|---|")
    for grp, name, since, brief in index:
        anchor = f"api-{name}"  # mkdocs slug of "`api->name`"
        since_cell = f"api {since}" if since else "—"
        out.append(f"| [`api->{name}`](#{anchor}) | {since_cell} | {grp} "
                   f"| {md_prose(brief)} |")
    out.append("")
    missing_since = [n for _, n, s_, _ in index if not s_]
    if missing_since:
        print(f"[gen_mod_docs] WARNING: no @since on {missing_since}",
              file=sys.stderr)
    out.extend(sections)

    # convenience accessors at the tail of the header
    tail = src[src.index("} openpete_mod_api_t;") + len("} openpete_mod_api_t;"):]
    acc = re.findall(r"static inline [^{]+\{[^}]*\}", tail)
    if acc:
        out.append("## Convenience guest accessors\n")
        out.append("Typed guest-RAM helpers, defined inline in the header "
                   "itself, so they need no extra link step:\n")
        sigs = [re.sub(r"\s+", " ", a[: a.index("{")]).strip() for a in acc]
        out.append("```c\n" + "\n".join(s + ";" for s in sigs) + "\n```\n")

    return "\n".join(out), members


def scan_ui_items(pre: str):
    """(comment, code) pairs for the documented items of
    openpete_mod_ui.h: the ABI and flag defines, the widget struct, the
    body typedef and the two registration macros. A macro is reported by
    its first line, since its body is the descriptor the doc block
    describes, not something a mod writes."""
    items, i, n, comment = [], 0, len(pre), ""
    while i < n:
        i += len(pre[i:]) - len(pre[i:].lstrip())
        if i >= n:
            break
        if pre.startswith("/*", i):
            end = pre.index("*/", i) + 2
            comment = pre[i:end]
            i = end
            continue
        if pre.startswith("#", i) and not pre.startswith("#define", i):
            # a guard line (#endif and friends): skipping it keeps the
            # declaration scan below from swallowing the struct after it
            i = pre.index("\n", i) + 1
            comment = ""
            continue
        if pre.startswith("#define", i):
            end = pre.index("\n", i)
            first = pre[i:end]
            while pre[end - 1] == "\\":
                end = pre.index("\n", end + 1)
            items.append((comment, first.rstrip(" \\").rstrip()))
            comment = ""
            i = end
            continue
        depth, j = 0, i
        while j < n:
            c = pre[j]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
            elif c == ";" and depth == 0:
                break
            j += 1
        code = pre[i:j + 1].strip()
        if code.startswith("typedef"):
            items.append((comment, code))
        comment = ""
        i = j + 1
    return items


def gen_mod_ui(ui_header: Path):
    """The `## UI widgets` section of api.md: openpete_mod_ui.h, the
    separately versioned header the api struct does not cover."""
    src = ui_header.read_text(encoding="utf-8")

    intro = ""
    m = re.match(r"\s*(/\*\*(?:[^*]|\*(?!/))*\*/)", src)
    if m:
        intro = "\n".join(l for l in strip_comment(m.group(1)).splitlines()
                           if not l.startswith("@file"))
        intro = dox_to_md(intro).strip()

    out = ["## UI widgets\n"]
    out.append(f"A section body draws with this header, extracted from "
               f"`{ui_header.relative_to(REPO)}`. The staged copy lives at "
               f"`<exe>/sdk/openpete_mod_ui.h`. It carries its own abi, "
               f"checked at load, and is not covered by "
               f"`OPENPETE_MOD_API_VERSION`. The whole ImGui C API is "
               f"available instead through "
               f"[`openpete_imgui.h`](../imgui.md).\n")
    if intro:
        out.append(md_prose(intro) + "\n")

    pre = src[src.index('extern "C" {') + len('extern "C" {'):
              src.rindex("#ifdef __cplusplus")]
    items = scan_ui_items(pre)
    for comment, code in items:
        if comment.strip():
            out.append(md_prose(dox_to_md(strip_comment(comment))) + "\n")
        out.append(f"```c\n{code}\n```\n")
    return "\n".join(out), len(items)


# ── functions.md ─────────────────────────────────────────────────────────

def fmt_param(p: str) -> str:
    """'{ type = "int", name = "pY" }' fragments -> 'int pY'."""
    t = re.search(r'type\s*=\s*"([^"]+)"', p)
    n = re.search(r'name\s*=\s*"([^"]+)"', p)
    ty = t.group(1) if t else "?"
    if ty.startswith("ptr:"):
        ty = ty[4:] + "*"
    return f"{ty} {n.group(1) if n else '?'}"


def parse_protos(path: Path):
    protos = {}
    for chunk in path.read_text(encoding="utf-8").split("[[proto]]")[1:]:
        name = re.search(r'name = "([^"]+)"', chunk)
        ret = re.search(r'ret = "([^"]+)"', chunk)
        if not name or not ret:
            continue
        params = re.search(r"params = \[(.*?)\]\s*\n", chunk, re.S)
        plist = ([fmt_param(p) for p in re.findall(r"\{[^}]*\}",
                                                   params.group(1))]
                 if params else [])
        r = ret.group(1)
        if r.startswith("ptr:"):
            r = r[4:] + "*"
        protos[name.group(1)] = (
            f"{r} {name.group(1)}({', '.join(plist) if plist else 'void'})")
    return protos


# ── source links ─────────────────────────────────────────────────────────

class SourceLinker:
    """Resolves a manifest symbol to its definition line in the decomp
    checkout and renders a link pinned to the checked-out commit.

    psx.map names the object each symbol came from, not the line, so the
    line is recovered by scanning the source: `glabel`/`dlabel` in .s
    files, a file-scope definition in .c files, `typedef struct ... }
    Name;` in headers. A symbol the scan does not find links to the file;
    a file that does not exist renders as plain text. Without a GitHub
    url or a resolvable commit every cell is plain text."""

    FUNC_MACRO_RE = re.compile(r'^INCLUDE_ASM\w*\("([^"]+)",\s*(\w+)\)')

    def __init__(self, decomp_dir: Path, base_url, sha):
        self.dir = decomp_dir
        self.base = base_url
        self.sha = sha
        self._files = {}

    @property
    def enabled(self) -> bool:
        return bool(self.base and self.sha)

    def lines(self, rel: str):
        if rel not in self._files:
            p = self.dir / rel
            self._files[rel] = (p.read_text(encoding="utf-8",
                                            errors="replace").splitlines()
                                if p.is_file() else None)
        return self._files[rel]

    def url(self, rel: str, line=None, end=None) -> str:
        u = f"{self.base}/blob/{self.sha}/{rel}"
        if line:
            u += f"#L{line}" + (f"-L{end}" if end and end != line else "")
        return u

    def cell(self, rel: str, line=None, end=None) -> str:
        """Markdown for one Source cell: `[path:line](url)` or plain."""
        if not rel:
            return ""
        label = rel + (f":{line}" if line else "")
        if not self.enabled or self.lines(rel) is None:
            return f"`{label}`"
        return f"[`{label}`]({self.url(rel, line, end)})"

    def _find(self, rel: str, pattern):
        ls = self.lines(rel)
        if ls is None:
            return None
        for i, l in enumerate(ls, 1):
            if pattern.match(l):
                return i
        return None

    def function(self, name: str, rel: str):
        """(file, line) of a function definition; the INCLUDE_ASM site of
        a non-matching function redirects to its .s file."""
        # `name.NON_MATCHING` is the alias INCLUDE_ASM emits for the
        # C body kept beside the assembly; it has the same definition.
        name = name.removesuffix(".NON_MATCHING")
        if rel.endswith(".s"):
            return rel, self._find(rel, re.compile(rf"^glabel {name}\b"))
        ls = self.lines(rel)
        if ls is None:
            return rel, None
        defn = re.compile(rf"^(?!\s)(?!extern\b)[^;{{}}]*\b{name}\s*\(")
        for i, l in enumerate(ls, 1):
            m = self.FUNC_MACRO_RE.match(l)
            if m and m.group(2) == name:
                asm = f"{m.group(1)}/{name}.s"
                if self.lines(asm) is not None:
                    return asm, self._find(asm, re.compile(rf"^glabel {name}\b"))
                return rel, i
            if defn.match(l) and ("{" in l or not l.rstrip().endswith(";")):
                return rel, i
        # A per-level overlay function `Base_level_N` is defined as
        # `NAME_OVERLAY_FUNCTION(Base)` in a .inc.h the overlay's .c
        # includes once per level.
        m = re.fullmatch(r"(\w+)_level_(\d+)", name)
        if m:
            macro = re.compile(
                rf"^(?!\s)[^;{{}}]*\bNAME_OVERLAY_FUNCTION(?:_LEVEL)?\("
                rf"\s*{m.group(1)}\s*[,)]")
            for l in ls:
                inc = re.match(r'#include\s+"([^"]+)"', l)
                if not inc:
                    continue
                for cand in (f"include/{inc.group(1)}",
                             str(Path(rel).parent / inc.group(1))):
                    line = self._find(cand, macro)
                    if line:
                        return cand, line
        return rel, None

    def global_(self, name: str, rel: str):
        if rel.endswith(".s"):
            return rel, self._find(rel, re.compile(rf"^[dg]label {name}\b"))
        # A file-scope definition: starts in column 0, is not a prototype
        # or extern, and the name is followed by a subscript, `=` or `;`.
        return rel, self._find(rel, re.compile(
            rf"^(?!\s)(?!extern\b)(?!typedef\b)[^(;]*\b{name}\b"
            rf"\s*(\[[^\]]*\]\s*)*(=|;)"))

    def struct(self, name: str, headers):
        """(file, first line, last line) of `typedef struct ... } Name;`
        across the given include/ headers."""
        close = re.compile(rf"^\}}\s*{name}\s*;")
        opener = re.compile(r"^typedef\s+struct\b")
        for rel in headers:
            ls = self.lines(rel)
            if ls is None:
                continue
            for i, l in enumerate(ls, 1):
                if close.match(l):
                    start = i
                    for j in range(i - 1, 0, -1):
                        if opener.match(ls[j - 1]):
                            start = j
                            break
                    return rel, start, i
        return None


def decomp_remote(gitmodules: Path, sub_path: str):
    """GitHub web url of a submodule from .gitmodules, or None when the
    url is not a GitHub repository (ssh aliases like `github-x:o/r.git`
    and `git@github.com:o/r.git` are recognised)."""
    if not gitmodules.exists():
        return None
    cur = None
    for l in gitmodules.read_text(encoding="utf-8").splitlines():
        l = l.strip()
        m = re.match(r"path\s*=\s*(\S+)", l)
        if m:
            cur = m.group(1)
            continue
        m = re.match(r"url\s*=\s*(\S+)", l)
        if m and cur == sub_path:
            u = m.group(1)
            m2 = (re.match(r"https?://github\.com/([^/]+)/([^/]+?)(?:\.git)?/?$", u)
                  or re.match(r"(?:git@github\.com|[\w-]*github[\w-]*):([^/]+)/([^/]+?)(?:\.git)?$", u))
            return f"https://github.com/{m2.group(1)}/{m2.group(2)}" if m2 else None
    return None


def decomp_commit(decomp_dir: Path):
    """Commit of the checkout the manifests were built from: the
    submodule's HEAD, else the gitlink recorded in the parent repository."""
    import subprocess
    for cmd in (["git", "-C", str(decomp_dir), "rev-parse", "HEAD"],
                ["git", "-C", str(REPO), "rev-parse",
                 "HEAD:" + str(decomp_dir.relative_to(REPO))]):
        try:
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=10)
        except (OSError, ValueError, subprocess.SubprocessError):
            continue
        sha = r.stdout.strip()
        if r.returncode == 0 and re.fullmatch(r"[0-9a-f]{40}", sha):
            return sha
    return None


def source_note(linker: SourceLinker) -> str:
    if not linker.enabled:
        return ""
    return (f"Source links open the definition in "
            f"[the decompilation]({linker.base}) at commit "
            f"[`{linker.sha[:10]}`]({linker.base}/tree/{linker.sha}), the "
            "checkout this SDK was generated from.\n")


def gen_functions(symbols: Path, protos_path: Path, linker: SourceLinker) -> str:
    funcs = read_toml_blocks(symbols, "function")
    protos = parse_protos(protos_path)

    rows = []
    for f in funcs:
        name = unq(f.get("name", ""))
        # INCLUDE_ASM emits `name.NON_MATCHING` beside `name` at the same
        # address; a mod hooks the base name.
        if name.endswith(".NON_MATCHING"):
            continue
        rows.append((name, f.get("addr", "?"),
                     unq(f.get("source_file", ""))))
    rows.sort(key=lambda r: r[0].lower())
    n_proto = sum(1 for r in rows if r[0] in protos)

    out = [GEN_NOTE, "# Functions\n"]
    out.append(
        f"Every guest function that a mod can override or call: "
        f"**{len(rows)}** symbols from `manifest/symbols.toml`, of which "
        f"**{n_proto}** have natural-signature prototypes in "
        f"`manifest/prototypes.toml`.\n\n"
        "Hook a function by name with "
        "`api->override_name(self, \"Name\", fn)`, or by address with "
        "`api->override_addr`. A prototyped function also gets generated "
        "wrappers in `openpete_sdk_wrappers.h`: `OP_OVERRIDE_IMPL_Name`, "
        "`OP_REGISTER_OVERRIDE_Name`, `op_base_Name`, and "
        "`op_call_Name`, which give you typed arguments, pointer "
        "marshalling, and argument-register save and restore. A function "
        "with an empty Signature cell has no prototype: read `cpu->a0` "
        "through `cpu->a3`, and write `cpu->v0`.\n\n"
        "A `func_XXXXXXXX` name belongs to the part of the decompilation "
        "that isn't named yet. Those names resolve forever under the "
        "decompilation promotion contract, but the loader warns you once "
        "a stable name exists.\n")
    out.append(source_note(linker))

    letter = None
    for name, addr, srcf in rows:
        l = name[0].upper() if name[:1].isalpha() else "#"
        if l != letter:
            letter = l
            out.append(f"\n## {letter}\n")
            out.append("| Function | Address | Signature | Source |")
            out.append("|---|---|---|---|")
        sig = protos.get(name)
        sigcell = f"`{sig}` + wrappers" if sig else ""
        rel, line = linker.function(name, srcf) if srcf else (srcf, None)
        out.append(f"| `{name}` | `{addr}` | {sigcell} | "
                   f"{linker.cell(rel, line)} |")
    out.append("")
    return "\n".join(out), len(rows), n_proto


