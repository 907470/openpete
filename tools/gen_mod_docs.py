def gen_structs(structs_header: Path, linker: SourceLinker,
                layout_toml: Path = None) -> str:
    out = [GEN_NOTE, "# Game structs\n"]
    if not structs_header or not structs_header.exists():
        out.append("!!! warning\n    `openpete_game_structs.h` wasn\'t "
                   "found. Build the game target once, then run "
                   "`scripts/build-mod-docs.sh` again.\n")
        return "\n".join(out), 0

    src = structs_header.read_text(encoding="utf-8")
    intro_m = re.match(r"\s*(/\*(?:[^*]|\*(?!/))*\*/)", src)
    if intro_m:
        intro = "\n".join(l for l in strip_comment(intro_m.group(1)).splitlines()
                          if not l.startswith("@file"))
        out.append("\n".join("> " + l for l in md_prose(
            dox_to_md(intro).strip()).splitlines()) + "\n")
    out.append(source_note(linker))
    headers = sorted(p.relative_to(linker.dir).as_posix()
                     for p in (linker.dir / "include").glob("*.h")
                     ) if (linker.dir / "include").is_dir() else []

    sizes = dict(re.findall(
        r'_Static_assert\(sizeof\((\w+)\)\s*==\s*(0x[0-9a-fA-F]+|\d+)', src))
    offsets = {}
    for s, f, off in re.findall(
            r'_Static_assert\(offsetof\((\w+),\s*([\w.\[\]]+)\)\s*==\s*'
            r'(0x[0-9a-fA-F]+|\d+)', src):
        offsets.setdefault(s, []).append((f, off))
    n_pins = len(sizes) + sum(len(v) for v in offsets.values())

    # PSYQ types are emitted ahead of the game structs and have no decomp
    # source range; they are listed in their own section.
    sys.path.insert(0, str(REPO / "tools"))
    import psyq_types as P
    psyq = set(P.psyq_names())

    def emit(name, body):
        out.append(f"## `{name}`\n")
        meta = []
        where = linker.struct(name, headers) if name not in psyq else None
        if where:
            rel, first, last = where
            meta.append("Source: " + linker.cell(rel, first, last)
                        .replace(f":{first}`", f":{first}-{last}`"))
        elif name in psyq:
            meta.append("Source: PSYQ SDK (`tools/psyq_types.py`)")
        if name in sizes:
            meta.append(f"Size: `{sizes[name]}`")
        if meta:
            out.append("  \n".join(meta) + "\n")
        if name in offsets:
            out.append("| Field | Offset |")
            out.append("|---|---|")
            for f, off in offsets[name]:
                out.append(f"| `{f}` | `{off}` |")
            out.append("")
        out.append(f"```c\n{body.strip()}\n```\n")

    game, psyq_blocks = [], []
    for m in re.finditer(r"typedef struct (\w+) \{(.*?)\} \1;", src, re.S):
        (psyq_blocks if m.group(1) in psyq else game).append(
            (m.group(1), m.group(0)))
    game.sort(key=lambda t: t[0].lower())
    for name, body in game:
        emit(name, body)
    if psyq_blocks:
        out.append("## PSYQ types\n")
        out.append("Types from the PlayStation SDK that the game structs "
                   "embed. Their layouts are pinned like every other struct; "
                   "`RECT` and `MATRIX` complete the forward declarations "
                   "the wrappers header makes.\n")
        for name, body in psyq_blocks:
            emit(name, body)

    if layout_toml and layout_toml.exists():
        t = layout_toml.read_text(encoding="utf-8")
        n_toml = (len(re.findall(r"^size = ", t, re.M))
                  + len(re.findall(r"\{ name = ", t)))
        if n_toml != n_pins:
            sys.exit(f"gen_mod_docs: {n_pins} pins on the structs page, "
                     f"{n_toml} in {layout_toml.name}; the pin extractor "
                     "missed some")
    return "\n".join(out), len(game) + len(psyq_blocks)


# ── examples.md ──────────────────────────────────────────────────────────


# Where a "uses:" row points, from examples.md in pages/reference/. An
# api-> entry has its own section in api.md; everything else lands on the
# page that documents the surface, since neither the widget vtable nor the
# function table gives its members anchors.
USES_LINK = (
    (re.compile(r"`(OP_OVERRIDE_IMPL|OP_REGISTER_OVERRIDE)_\w+`"),
     "spyro-1/functions.md"),
    (re.compile(r"`(op_base|op_call)_\w+`"), "spyro-1/functions.md"),
    (re.compile(r"openpete_imgui\.h"), "../imgui.md"),
    (re.compile(r"openpete_mod_ui\.h|`OPENPETE_MOD_UI_\w+`|`ui->\w+`"),
     "api.md#ui-widgets"),
    (re.compile(r"\[\[material\]\]"), "../shaders.md#materials"),
    (re.compile(r"assets/textures/"), "../textures.md"),
    (re.compile(r"assets/music/"), "../music.md"),
    (re.compile(r"assets/sfx/"), "../sounds.md"),
    (re.compile(r"shaders/"), "../shaders.md"),
)


def link_uses(cell: str, api_names: set, mid: str) -> str:
    """Link each name in a uses: row to the page documenting it. The row
    may name several entries, so each comma-separated token is linked on
    its own."""
    out = []
    for token in cell.split(", "):
        m = re.fullmatch(r"`api->(\w+)`", token)
        if m:
            if m.group(1) not in api_names:
                sys.exit(f"gen_mod_docs: {mid} documents {token} in a "
                         f"uses: line but api.md has no such entry")
            out.append(f"[{token}](api.md#api-{m.group(1)})")
            continue
        for rx, href in USES_LINK:
            if rx.search(token):
                out.append(f"[{token}]({href})")
                break
        else:
            out.append(token)
    return ", ".join(out)


def read_examples(mods_dir: Path) -> list:
    """mods/examples.txt: the ids package-dist.sh stages into
    <exe>/sdk/examples/, one per line, comments with #."""
    f = mods_dir / "examples.txt"
    if not f.exists():
        return []
    return [l.strip() for l in f.read_text(encoding="utf-8").splitlines()
            if l.strip() and not l.startswith("#")]


def gen_examples(mods_dir: Path, api_names: set) -> str:
    out = [GEN_NOTE, "# Examples\n"]
    shipped = read_examples(mods_dir)
    out.append("The example mods that ship with the SDK under "
               "`<exe>/sdk/examples/<id>/`, extracted from each one's "
               "`mod.toml` header. Copy one into your `mods` directory "
               "to run it; start from the one nearest to your idea.\n")
    by_id = {t.parent.name: t for t in mods_dir.glob("*/mod.toml")}
    missing = [e for e in shipped if e not in by_id]
    if missing:
        sys.exit(f"gen_mod_docs: mods/examples.txt names {missing} "
                 f"but no such mod directory exists")
    sections = []
    for toml in (by_id[e] for e in shipped):
        text = toml.read_text(encoding="utf-8")
        desc = []
        for line in text.splitlines():
            if line.startswith("#"):
                desc.append(line.lstrip("#").strip())
            elif line.strip():
                break
        fields = {}
        for m in re.finditer(r'^(\w+)\s*=\s*(.+)$', text, re.M):
            fields.setdefault(m.group(1), unq(m.group(2)))
        mid = fields.get("id", toml.parent.name)
        title = fields.get("name", mid)
        srcs = sorted(p.name for p in (toml.parent / "src").glob("*.c"))
        sm = fields.get("sim_mutative")
        mutative = (sm == "true") if sm in ("true", "false") \
            else bool(srcs) or bool(re.search(r"^\[\[level\]\]", text, re.M))
        bits = [f"v{fields.get('version', '?')}"]
        bits.append("writes guest RAM" if mutative else "writes no guest RAM")
        blocks = sorted({b for b in re.findall(r"^\[\[(\w+)\]\]", text, re.M)})
        if blocks:
            bits.append(", ".join(f"`[[{b}]]`" for b in blocks))
        if srcs:
            bits.append("src: " + ", ".join(f"`{s}`" for s in srcs))
        sec = [f"## `{mid}` — {title}\n", " · ".join(bits) + "\n"]
        # A blank comment line in the header is a paragraph break; a
        # "uses:" line leaves the prose and becomes a row of the API table.
        paras, cur, uses = [], [], []
        for d in desc:
            if d.startswith("uses:"):
                what, _, why = d[len("uses:"):].strip().partition(" - ")
                uses.append((what.strip(), why.strip()))
                continue
            if d:
                cur.append(d)
            elif cur:
                paras.append(" ".join(cur)); cur = []
        if cur:
            paras.append(" ".join(cur))
        # The header opens "<id>: ...", which names the file's subject in
        # the source and repeats the heading on the page.
        if paras and paras[0].startswith(mid + ": "):
            first = paras[0][len(mid) + 2:]
            paras[0] = first[0].upper() + first[1:]
        sec.extend(md_prose(pg) + "\n" for pg in paras)
        if uses:
            # A row naming an api-> or ui-> entry the sources do not call
            # is stale documentation, so the extraction refuses it.
            src_text = "".join(f.read_text(encoding="utf-8")
                               for f in sorted((toml.parent / "src").glob("*.c")))
            for what, _why in uses:
                m = re.fullmatch(r"`?(api|ui)->(\w+)`?", what)
                if m and ("->" + m.group(2) + "(") not in src_text:
                    sys.exit(f"gen_mod_docs: {mid} documents {what} in a "
                             f"uses: line but no src/*.c calls it")
            sec.append("| Uses | Why |")
            sec.append("|---|---|")
            sec.extend(f"| {link_uses(what, api_names, mid)} | {why} |"
                       for what, why in uses)
            sec.append("")
        sections.append("\n".join(sec))
    out.extend(sections)
    return "\n".join(out), len(sections)


# ── cpustate.md ──────────────────────────────────────────────────────────

SCALAR_FIELD_RE = re.compile(
    r"^\s*(\w+)\s+([\w, ]+?)(\[\d+\])?;\s*/\*\*<\s*(.*?)\s*\*/")
FNPTR_FIELD_RE = re.compile(
    r"^\s*([\w ]+?)\s*\(\*(\w+)\)(\([^)]*\));\s*/\*\*<\s*(.*?)\s*\*/")


def gen_cpustate(runtime_header: Path):
    """psx_runtime.h -> cpustate.md: the struct's comment block as prose
    and a table with one row per declarator (a line declaring several
    registers with one comment becomes one row per register)."""
    out = [GEN_NOTE, "# CPUState\n"]
    if not runtime_header.exists():
        out.append(f"!!! warning\n    `{runtime_header.name}` not found.\n")
        return "\n".join(out), 0
    src = runtime_header.read_text(encoding="utf-8")
    m = re.search(r"(/\*\*(?:(?!\*/).)*?\*/)\s*typedef struct CPUState \{(.*?)\} CPUState;",
                  src, re.S)
    if not m:
        sys.exit("gen_mod_docs: CPUState not found in psx_runtime.h")
    out.append(md_prose(dox_to_md(strip_comment(m.group(1)))) + "\n")
    out.append("Declared in `psx_runtime.h`, shipped in `sdk/`; include it "
               "beside `openpete_mod_api.h`, which only forward-declares "
               "the type.\n")
    rows = []
    for line in m.group(2).splitlines():
        fm = FNPTR_FIELD_RE.match(line)
        if fm:
            ret, name, params, brief = fm.groups()
            rows.append((f"{ret.strip()} (*{name}){params}", "",
                         md_prose(dox_to_md(brief))))
            continue
        fm = SCALAR_FIELD_RE.match(line)
        if not fm:
            continue
        ctype, names, suffix, brief = fm.groups()
        for name in [n.strip() for n in names.split(",")]:
            rows.append((name + (suffix or ""), ctype,
                         md_prose(dox_to_md(brief))))
    out.append("## Fields\n")
    out.append("| Field | Type | Meaning |")
    out.append("|---|---|---|")
    for decl, ctype, brief in rows:
        out.append(f"| `{decl}` | {('`' + ctype + '`') if ctype else '—'} | {brief} |")
    out.append("")
    return "\n".join(out), len(rows)



# ── imgui.md ─────────────────────────────────────────────────────────────

def imgui_version(imgui_header: Path) -> str:
    """The ImGui version the engine builds against, from the pinned
    header. Never hard-coded here: the page would then claim a version the
    SDK does not ship the moment the submodule moves."""
    m = re.search(r'^#define\s+IMGUI_VERSION\s+"([^"]+)"',
                  imgui_header.read_text(encoding="utf-8"), re.M)
    if not m:
        sys.exit(f"gen_mod_docs: no IMGUI_VERSION in {imgui_header}")
    return m.group(1)


def imgui_denylist(table_gen: Path) -> list:
    """The denied families, taken from the generator that applies them, so
    the page and the table cannot disagree."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("gen_imgui_table", table_gen)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return list(mod.DENY_DOC)


def gen_imgui(imgui_header: Path, table_gen: Path):
    ver = imgui_version(imgui_header)
    deny = imgui_denylist(table_gen)
    out = [GEN_NOTE, "# ImGui\n"]
    out.append(
        f"`openpete_imgui.h` gives a mod access to the ImGui C API (ImGui {ver}, "
        f"through the C bindings "
        f"[dear_bindings](https://github.com/dearimgui/dear_bindings) "
        f"generates).\n")
    out.append(
        "- [ImGui docs](https://github.com/ocornut/imgui/wiki)\n"
        "- Generated bindings: `<exe>/sdk/dcimgui.h`\n"
        "- `ImGui_ShowDemoWindow()` draws a "
        "running demo of every widget\n")
    out.append(
        "Names follow dear_bindings: "
        "`ImGui::Begin` is `ImGui_Begin`, a call passing every optional "
        "argument is the `...Ex` form (`ImGui_PlotLinesEx`), an overload "
        "takes a type suffix (`ImGui_ComboChar`), and a member function "
        "takes its struct's prefix (`ImDrawList_AddLine`). A mod cannot take "
        "the address of an `ImGui_*` function, since the name is a macro "
        "over a table entry; use the entry "
        "(`openpete_imgui_tbl->ImGui_Begin`).\n")
    out.append(
        "[`openpete_mod_ui.h`](reference/api.md#ui-widgets) stays the simple "
        "path: eleven "
        "widgets, no macro to add, and no ImGui version in the mod's build. Use "
        "this header when those eleven are not enough: windows, "
        "tables, plots, tree nodes, tabs, popups, colour editors, drag and "
        "input widgets, draw lists, fonts.\n")

    out.append("## Glossary\n")
    out.append(
        "| Term | Meaning |\n"
        "|---|---|\n"
        "| body | The function registered as the mod's UI, run by the "
        "engine inside its ImGui frame. Every `ImGui_*` call a mod makes "
        "is made here. |\n"
        "| section | A mod's registered UI, drawn in the mod's node of the "
        "Mods panel. |\n"
        "| always section | A section registered with "
        "`OPENPETE_MOD_UI_ALWAYS`, whose body runs at top level on every "
        "present instead of inside the mod's node. |\n"
        "| table | The function-pointer table (`openpete_imgui_tbl`) every "
        "`ImGui_*` macro reads, one entry per callable ImGui function. |\n"
        "| descriptor | The symbol `OPENPETE_MOD_IMGUI()` exports, which "
        "the loader checks against the engine's table before binding. |\n"
        "| overlay | The dev overlay, opened with the M key. Its Mods "
        "panel gives each mod a node. |\n"
        "| present | One drawn frame, as distinct from a tick, the "
        "29.913 Hz simulation step. Presents per tick depend on the "
        "machine. |\n")

    out.append("## Adding ImGui to a mod\n")
    out.append(
        "Include the header and place the macro at file scope in exactly "
        "one source file of the mod:\n")
    out.append("""```c
#include <openpete_mod_api.h>
#include <openpete_mod_ui.h>
#include <openpete_imgui.h>

OPENPETE_MOD_IMGUI()

static void ui_draw(const openpete_mod_ui_t* ui) {
    (void)ui;
    if (ImGui_Begin("my window", NULL, 0)) {
        ImGui_Text("hello from a mod");
    }
    ImGui_End();
}
OPENPETE_MOD_UI_SECTION(ui_draw)
```
""")
    out.append(
        "`OPENPETE_MOD_IMGUI()` defines the function-pointer table every "
        "`ImGui_*` call reads and exports the descriptor the loader "
        "resolves when it opens the mod. A mod without the macro "
        "references no table and nothing is bound. Nothing is added to the "
        "mod's compile line and the mod still links no engine symbol: an "
        "`ImGui_*` name is a macro over one table entry.\n")
    out.append(
        "The descriptor pins the ImGui version, the table size and a "
        "digest of the table's entries. A prebuilt object built against a "
        "different SDK is refused and its mod disabled, because a mod bound "
        "to a table whose slots have moved would call the wrong function on "
        "its first widget. A source mod is never refused: the SDK "
        "headers are part of the mod's build key, so an ImGui bump "
        "recompiles it at the next boot.\n")
    out.append(
        "Binding is logged once per mod:\n\n"
        "```\n"
        "mods: <id>: ImGui bound (" + ver + ", N entries)\n"
        "```\n")

    out.append("## Where the calls are legal\n")
    out.append(
        "Inside a UI section body, and nowhere else. A body runs on the "
        "compose thread, inside the engine's ImGui frame, while the mod is "
        "enabled. A plain `OPENPETE_MOD_UI_SECTION` body runs in the mod's "
        "node of the Mods section, so only while the dev overlay is open; "
        "an always section (below) runs on every present.\n")
    out.append(
        "A call from a [present hook or a tick hook]"
        "(code.md#tick-context-and-present-context) is dropped: those run "
        "outside the frame and on another thread, where ImGui's own "
        "checks are compiled out and the failure would be a null-window "
        "dereference. The call returns a zeroed value and the engine logs "
        "the mod and the function once:\n\n"
        "```\n"
        "mods: <id>: ImGui_Begin called outside the mod's UI section "
        "(from a present or tick hook) — dropped\n"
        "```\n")
    out.append(
        "A body draws and nothing else: guest access, game calls and "
        "override registration are refused inside one, as they are inside "
        "[a present hook](reference/api.md#api-register_present_hook). "
        "Read [guest RAM](code.md#guest-memory) in a tick hook, copy what "
        "the panel needs into host memory, and let the body read the "
        "copy.\n")
    out.append(
        "The body still receives the `openpete_mod_ui_t*` argument, so the "
        "vtable and the ImGui calls mix freely in one body. An `ImGui_Begin` "
        "inside the mod's node opens an independent top-level window, which "
        "is ImGui's documented behaviour.\n")

    out.append("## Always-on sections\n")
    out.append(
        "Register the body with the flags form to run it on every present "
        "instead of only inside the Mods panel:\n")
    out.append("""```c
OPENPETE_MOD_UI_SECTION_FLAGS(ui_draw, OPENPETE_MOD_UI_ALWAYS)
```
""")
    out.append(
        "An always section keeps a stats window or a draw-list overlay on "
        "screen during play. The rules that change with it:\n")
    out.append(
        "- **The body owns its windows.** It runs at top level, not inside "
        "a tree node (a node the player collapsed must not make a window "
        "disappear), so every widget emitted outside an `ImGui_Begin` "
        "lands in ImGui's default debug window. Open a window and put "
        "the content in it.\n"
        "- **No input while the overlay is closed.** The game keeps the "
        "mouse and the keyboard, and the engine puts "
        "`ImGuiWindowFlags_NoInputs` on every window the body opens: no "
        "clicks, no nav, no hover. `ui->overlay_open()` returns 1 while the "
        "overlay is up, which is when widgets in an always window can be "
        "used; draw interactive widgets only then. `ImGui_GetMousePos` "
        "still reports the game's cursor.\n"
        "- **The pass is skipped while the in-game settings menu is "
        "open.** The menu and the dev overlay are mutually exclusive input "
        "owners and the menu is drawn first, so an always window would "
        "paint over it.\n"
        "- **[`ui_status`](reference/api.md#api-ui_status) lines stay in the "
        "mod's node** in the Mods "
        "section, where the rest of the mod's row is.\n")
    out.append(
        "ImGui draws into the live present "
        "only, so an always window is never in a `--record` capture or a "
        "screenshot, and it is drawn on top of an "
        "[`OP_POSTFX_COMPOSITE` chain](shaders.md#post-process-passes) rather "
        "than through it. A HUD that must "
        "appear in captures belongs in the draw service "
        "([`draw_text`](reference/api.md#api-draw_text)), "
        "which is drawn pre-chain as content.\n")

    out.append("## Calls not in the table\n")
    out.append(
        "The table omits these, and the macros with them, so calling one "
        "fails the mod's compile with an undefined reference to the "
        "`dcimgui.h` declaration.\n")
    out.append("| Family | Calls |")
    out.append("|---|---|")
    for line in deny:
        # The generator's prose names bare identifiers; a trailing * is part
        # of the family name, so each goes in a code span rather than
        # through the italics escape.
        line = re.sub(r"\bIm(?:Gui|Font|Draw)(?:\w|\*)*",
                      lambda m: "`" + m.group(0) + "`", line)
        family, calls = line.split(": ", 1)
        # A family whose entry ends in a second sentence (one name kept out
        # of the denial) carries it as a parenthetical, so the cell stays a
        # list of names.
        calls, _, note = calls.rstrip(".").partition(". ")
        if note:
            calls += " (" + note[0].lower() + note[1:] + ")"
        out.append("| " + family + " | " + calls + " |")
    out.append("")

    out.append("## Error handling\n")
    out.append(
        "ImGui reports unbalanced `Begin`/`End`, `Push`/`Pop` and "
        "similar issues as recoverable user errors. The engine brackets "
        "every body:\n")
    out.append(
        "- the ImGui stack sizes are stored before the body and recovered "
        "after it, so a window left open does not swallow the panel or the "
        "frame;\n"
        "- `ImGuiStyle` and the `ImGuiIO` fields a body can reach "
        "(`IniFilename`, `LogFilename`, `ConfigFlags`, `UserData`, and the "
        "backend user-data pointers) are snapshotted and put back;\n"
        "- ImGui's own assert and error tooltip are switched off for "
        "the body and the engine logs the error against the mod instead:\n")
    out.append(
        "```\n"
        "mods: <id>: ImGui error inside the mod's UI section: "
        "Missing End()\n"
        "```\n")
    out.append(
        "A body that errors on three consecutive presents is logged once "
        "more and then stops drawing for the rest of the session, so it "
        "cannot flood the log or keep drawing a broken section. Issues ImGui "
        "cannot recover from (a null `ImDrawList*`, a bad pointer "
        "into `ImGuiIO`) crash the process.\n")

    return "\n".join(out), len(deny)


# ── main ─────────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--api-header",
                    default=REPO / "core/include/openpete_mod_api.h",
                    type=Path)
    ap.add_argument("--ui-header",
                    default=REPO / "core/include/openpete_mod_ui.h",
                    type=Path)
    ap.add_argument("--symbols",
                    default=REPO / "games/spyro-1/manifest/symbols.toml",
                    type=Path)
    ap.add_argument("--globals", dest="globals_",
                    default=REPO / "games/spyro-1/manifest/globals.toml",
                    type=Path)
    ap.add_argument("--protos",
                    default=REPO / "games/spyro-1/manifest/prototypes.toml",
                    type=Path)
    ap.add_argument("--decomp-dir", dest="decomp_dir",
                    default=REPO / "games/spyro-1/spyro-1", type=Path,
                    help="decompilation checkout the manifests were "
                         "built from; source links resolve against it")
    ap.add_argument("--structs", type=Path, default=None,
                    help="generated openpete_game_structs.h (default: "
                         "search known build dirs)")
    ap.add_argument("--layout", type=Path,
                    default=REPO / "games/spyro-1/manifest/struct_layout.toml",
                    help="struct_layout.toml; the structs page must carry "
                         "exactly its pins")
    ap.add_argument("--mods-dir", default=REPO / "mods", type=Path)
    ap.add_argument("--psx-runtime",
                    default=REPO / "third_party/psxrecomp/runner/include/psx_runtime.h",
                    type=Path)
    ap.add_argument("--imgui-header",
                    default=REPO / "third_party/imgui/imgui.h",
                    type=Path)
    ap.add_argument("--imgui-table-gen",
                    default=REPO / "tools/gen_imgui_table.py",
                    type=Path)
    ap.add_argument("--out",
                    default=REPO / "docs/modding/pages/reference",
                    type=Path)
    ap.add_argument("--out-game", dest="out_game",
                    default=REPO / "docs/modding/pages/reference/spyro-1",
                    type=Path,
                    help="where the pages extracted from one game's "
                         "manifests go")
    ap.add_argument("--out-pages", dest="out_pages",
                    default=REPO / "docs/modding/pages",
                    type=Path,
                    help="where the non-reference generated pages go")
    args = ap.parse_args()

    structs = args.structs
    if structs is None:
        for cand in ("build/linux-release", "build/dev",
                     "build/windows-mingw", "build/windows-mingw-shared"):
            p = REPO / cand / "games/spyro-1/mod_sdk_gen/openpete_game_structs.h"
            if p.exists():
                structs = p
                break

    args.out.mkdir(parents=True, exist_ok=True)
    args.out_game.mkdir(parents=True, exist_ok=True)

    linker = SourceLinker(
        args.decomp_dir,
        decomp_remote(REPO / ".gitmodules",
                      args.decomp_dir.resolve().relative_to(REPO).as_posix()
                      if args.decomp_dir.resolve().is_relative_to(REPO)
                      else ""),
        decomp_commit(args.decomp_dir))
    if not linker.enabled:
        print("[gen_mod_docs] no decomp remote/commit: source cells "
              "unlinked", file=sys.stderr)

    api_md, n_api = gen_api(args.api_header)
    ui_md, n_ui = gen_mod_ui(args.ui_header)
    api_md = api_md.rstrip("\n") + "\n\n" + ui_md
    fn_md, n_fn, n_proto = gen_functions(args.symbols, args.protos, linker)
    gl_md, n_gl = gen_globals(args.globals_, linker)
    st_md, n_st = gen_structs(structs, linker, args.layout)
    api_names = set(re.findall(r"^### `api->(\w+)`", api_md, re.M))
    ex_md, n_mods = gen_examples(args.mods_dir, api_names)
    cs_md, n_cs = gen_cpustate(args.psx_runtime)
    ig_md, n_deny = gen_imgui(args.imgui_header, args.imgui_table_gen)

    for fname, content in (("api.md", api_md), ("examples.md", ex_md),
                           ("cpustate.md", cs_md)):
        (args.out / fname).write_text(content, encoding="utf-8")
    for fname, content in (("functions.md", fn_md), ("globals.md", gl_md),
                           ("structs.md", st_md)):
        (args.out_game / fname).write_text(content, encoding="utf-8")
    (args.out_pages / "imgui.md").write_text(ig_md, encoding="utf-8")

    if n_cs < 40:   # 32 GPRs + pc/hi/lo + 3 arrays + 10 callbacks
        sys.exit(f"gen_mod_docs: only {n_cs} CPUState fields parsed — the "
                 "struct layout or comment style changed; fix the extractor")
    if n_api < 25:  # 28 entries + api_version at api v1
        sys.exit(f"gen_mod_docs: only {n_api} API members parsed — the "
                 "header layout changed; fix the extractor")
    print(f"[gen_mod_docs] api: {n_api} members (+{n_ui} ui) | "
          f"functions: {n_fn} "
          f"({n_proto} prototyped) | globals: {n_gl} | structs: {n_st} | "
          f"examples: {n_mods} mods | cpustate: {n_cs} fields | "
          f"imgui: {n_deny} denied families -> {args.out}, "
          f"{args.out_game}, {args.out_pages}/imgui.md")


if __name__ == "__main__":
    main()
