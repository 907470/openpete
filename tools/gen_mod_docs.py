#!/usr/bin/env python3
"""gen_mod_docs.py — generate the mod-author reference pages (markdown).

Extracts the SDK surface into docs/modding/pages/reference/ for the
mkdocs-material site (see docs/modding/ and scripts/build-mod-docs.sh):

  api.md        <- core/include/openpete_mod_api.h   (the API contract:
                   struct members with their comment blocks, section
                   splitters, supporting types)
  functions.md  <- manifest/symbols.toml x prototypes.toml (overridable
                   functions: address, kind, natural signature +
                   op_call_*/op_base_* wrapper availability)
  globals.md    <- manifest/globals.toml (the OP_GADDR_* surface)
  structs.md    <- generated openpete_game_structs.h (typed guest-RAM
                   views + offset tables recovered from the pins)
  gallery.md    <- mods/*/mod.toml header comments (CI fixtures omitted)

Stdlib only, deterministic output (no timestamps): re-running on
unchanged inputs is byte-identical. Prose comes from the comment blocks
the compiler sees, so there is no second copy to drift.
"""
import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

GEN_NOTE = ("<!-- GENERATED by tools/gen_mod_docs.py — edit the source "
            "it was extracted from, not this file. -->\n\n")


# ── tiny TOML readers (house pattern: the manifests are machine-written,
# a full parser buys nothing) ─────────────────────────────────────────────

def read_toml_blocks(path: Path, block: str):
    """Yield dicts for each [[block]] of simple key = value lines."""
    entries, cur = [], None
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line == f"[[{block}]]":
            cur = {}
            entries.append(cur)
            continue
        if cur is None or not line or line.startswith("#"):
            continue
        if line.startswith("[["):          # a different block type starts
            cur = None
            continue
        m = re.match(r"(\w+)\s*=\s*(.+)$", line)
        if m:
            key, val = m.group(1), m.group(2).strip()
            cur[key] = val
    return entries


def unq(v: str) -> str:
    return v.strip().strip('"')


# ── api.md ───────────────────────────────────────────────────────────────

def md_prose(text: str) -> str:
    """Extracted comment prose -> markdown-safe text: literal <tokens>
    like <exe>/sdk would otherwise be swallowed as HTML, and bare *
    pairs (pointer decls, src/*.c) would become italics. Backtick spans
    are left alone."""
    out, i = [], 0
    for part in re.split(r"(`[^`]*`|\*\*[^*\n]+\*\*)", text):
        if part.startswith(("`", "**")):
            out.append(part)
        else:
            out.append(part.replace("&", "&amp;").replace("<", "&lt;")
                           .replace("*", "\\*"))
    return "".join(out)


def strip_comment(block: str) -> str:
    """/** ... */ block -> its text, preserving blank-line paragraphs."""
    out = []
    for line in block.splitlines():
        line = re.sub(r"^\s*/?\*+<?/?", "", line)
        line = re.sub(r"\*/\s*$", "", line)
        out.append(line.rstrip())
    text = "\n".join(out).strip("\n")
    lines = text.splitlines()
    pad = min((len(l) - len(l.lstrip()) for l in lines if l.strip()),
              default=0)
    return "\n".join(l[pad:] for l in lines).strip()


PARAM_RE = re.compile(r"^@param\s+(\w+)\s*(.*)$")


def dox_to_md(text: str) -> str:
    """Doxygen tags -> markdown. @param/@return/@since become list
    items and sentences; @code fences; inline @p/@c/#/:: become code
    spans; @brief is dropped (the text stands on its own)."""
    text = re.sub(r"@brief\s+", "", text)
    text = re.sub(r"@[pc]\s+([\w.>-]+)", r"`\1`", text)
    text = re.sub(r"(?<![\w`])#([A-Z_][A-Z0-9_]+)", r"`\1`", text)
    text = re.sub(r"(?<![\w`])::(\w+)", r"`\1`", text)
    text = re.sub(r"(?<![\w`/])(\w+)::(\w+)", r"`\1.\2`", text)
    text = text.replace("@code", "```c").replace("@endcode", "```")
    text = re.sub(r"(?<=\S)[ \t]+@since[ \t]+([^\n]*)", r" Since \1.", text)
    text = re.sub(r"\n(@since|@return|@param)", r"\n\n\1", text, count=1)
    out, i, lines = [], 0, text.splitlines()
    while i < len(lines):
        line = lines[i]
        m = PARAM_RE.match(line)
        if m or line.startswith("@return") or line.startswith("@since") \
                or line.startswith("@par "):
            # gather indented continuation lines
            body = [line]
            while i + 1 < len(lines) and lines[i + 1].startswith(" "):
                i += 1
                body.append(lines[i].strip())
            joined = " ".join(b.strip() for b in body)
            if m:
                pm = PARAM_RE.match(joined)
                out.append(f"- `{pm.group(1)}`: {pm.group(2)}")
            elif joined.startswith("@return"):
                out.append("- Returns: " + joined[len("@return"):].strip())
            elif joined.startswith("@since"):
                out.append("Since " + joined[len("@since"):].strip() + ".")
            else:
                out.append("**" + joined[len("@par "):].strip() + "**")
        else:
            out.append(line)
        i += 1
    return "\n".join(out)


def split_members(body: str):
    """Yield (comments, decl) for struct members: every /** */ block
    between one declaration and the next, then the declaration."""
    i, n = 0, len(body)
    comments = []
    while i < n:
        rest = body[i:]
        ws = len(rest) - len(rest.lstrip())
        i += ws
        if i >= n:
            break
        if body.startswith("/*", i):
            end = body.index("*/", i) + 2
            comments.append(body[i:end])
            i = end
            continue
        end = body.index(";", i) + 1
        yield comments, " ".join(body[i:end].split())
        comments = []
        i = end
    if comments:
        yield comments, ""


def scan_types(pre: str):
    """(comment, code) pairs for the documented items between extern "C"
    and the api struct: typedefs, enums and the version define. Static
    inline helpers and bare forward declarations are skipped."""
    items, i, n, comment = [], 0, len(pre), ""
    while i < n:
        ws = len(pre[i:]) - len(pre[i:].lstrip())
        i += ws
        if i >= n:
            break
        if pre.startswith("/*", i):
            end = pre.index("*/", i) + 2
            comment = pre[i:end]
            i = end
            continue
        if pre.startswith("#define", i):
            end = pre.index("\n", i)
            while pre[end - 1] == "\\":
                end = pre.index("\n", end + 1)
            line = pre[i:end]
            if line.startswith("#define OPENPETE_MOD_API_VERSION"):
                items.append((comment, line))
            comment = ""
            i = end
            continue
        # a declaration: ends at the first ';' outside braces
        depth, j = 0, i
        while j < n:
            c = pre[j]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0 and pre.startswith("static inline", i):
                    break
            elif c == ";" and depth == 0:
                break
            j += 1
        code = pre[i:j + 1].strip()
        if code.startswith(("typedef", "enum")):
            items.append((comment, code))
        comment = ""
        i = j + 1
    return items


MEMBER_NAME_RE = re.compile(r"\(\s*\*\s*(\w+)\s*\)")


def gen_api(api_header: Path) -> str:
    src = api_header.read_text(encoding="utf-8")

    # the file-top overview is the leading /** @file */ block
    intro = ""
    m = re.match(r"\s*(/\*\*(?:[^*]|\*(?!/))*\*/)", src)
    if m:
        intro = "\n".join(l for l in strip_comment(m.group(1)).splitlines()
                          if not l.startswith("@file"))
        intro = dox_to_md(intro).strip()

    out = [GEN_NOTE, "# API reference\n"]
    out.append(f"The contract that every mod compiles against, extracted "
               f"from `{api_header.relative_to(REPO)}`. The staged copy "
               f"lives at `<exe>/sdk/openpete_mod_api.h`.\n")
    out.append("\n".join("> " + l for l in md_prose(intro).splitlines()) + "\n")

    # supporting types: documented typedefs, enums and the version
    # define between extern "C" and the api struct
    pre = src[src.index('extern "C" {') + len('extern "C" {'):
              src.index("typedef struct openpete_mod_api")]
    types = scan_types(pre)
    out.append("## Supporting types\n")
    for comment, code in types:
        code = code.strip()
        if code.startswith("typedef struct CPUState"):
            continue
        if comment.strip():
            out.append(md_prose(dox_to_md(strip_comment(comment))) + "\n")
        out.append(f"```c\n{code}\n```\n")

    # the struct itself
    body = src[src.index("typedef struct openpete_mod_api {"):]
    body = body[body.index("{") + 1: body.index("} openpete_mod_api_t;")]

    members = 0
    for comments, decl in split_members(body):
        prose = ""
        for c in comments:
            text = strip_comment(c)
            if text.startswith("@name"):
                first, _, restp = text.partition("\n")
                out.append(f"## {first[len('@name'):].strip()}\n")
                restp = restp.replace("@{", "").strip()
                if restp:
                    out.append(md_prose(dox_to_md(restp)) + "\n")
            elif text.strip() in ("@}", ""):
                continue
            else:
                prose = text
        if not decl:
            continue
        name_m = MEMBER_NAME_RE.search(decl)
        name = name_m.group(1) if name_m else decl.split()[-1].rstrip(";")
        out.append(f"### `api->{name}`\n")
        out.append(f"```c\n{decl}\n```\n")
        if prose:
            out.append(md_prose(dox_to_md(prose)) + "\n")
        members += 1

    # convenience accessors at the tail of the header
    tail = src[src.index("} openpete_mod_api_t;") + len("} openpete_mod_api_t;"):]
    acc = re.findall(r"static inline [^{]+\{[^}]*\}", tail)
    if acc:
        out.append("## Convenience guest accessors\n")
        out.append("Typed guest-RAM helpers, defined inline in the header "
                   "itself, so they need no extra link step:\n")
        sigs = [re.sub(r"\s+", " ", a[: a.index("{")]).strip() for a in acc]
        out.append("```c\n" + "\n".join(s + ";" for s in sigs) + "\n```\n")

    return "\n".join(out), members


# ── functions.md ─────────────────────────────────────────────────────────

def fmt_param(p: str) -> str:
    """'{ type = "int", name = "pY" }' fragments -> 'int pY'."""
    t = re.search(r'type\s*=\s*"([^"]+)"', p)
    n = re.search(r'name\s*=\s*"([^"]+)"', p)
    ty = t.group(1) if t else "?"
    if ty.startswith("ptr:"):
        ty = ty[4:] + "*"
    return f"{ty} {n.group(1) if n else '?'}"


def parse_protos(path: Path):
    protos = {}
    for chunk in path.read_text(encoding="utf-8").split("[[proto]]")[1:]:
        name = re.search(r'name = "([^"]+)"', chunk)
        ret = re.search(r'ret = "([^"]+)"', chunk)
        if not name or not ret:
            continue
        params = re.search(r"params = \[(.*?)\]\s*\n", chunk, re.S)
        plist = ([fmt_param(p) for p in re.findall(r"\{[^}]*\}",
                                                   params.group(1))]
                 if params else [])
        r = ret.group(1)
        if r.startswith("ptr:"):
            r = r[4:] + "*"
        protos[name.group(1)] = (
            f"{r} {name.group(1)}({', '.join(plist) if plist else 'void'})")
    return protos


def gen_functions(symbols: Path, protos_path: Path) -> str:
    funcs = read_toml_blocks(symbols, "function")
    protos = parse_protos(protos_path)

    rows = []
    for f in funcs:
        name = unq(f.get("name", ""))
        rows.append((name, f.get("addr", "?"), unq(f.get("kind", "")),
                     unq(f.get("source_file", ""))))
    rows.sort(key=lambda r: r[0].lower())
    n_proto = sum(1 for r in rows if r[0] in protos)

    out = [GEN_NOTE, "# Functions\n"]
    out.append(
        f"Every guest function that a mod can override or call: "
        f"**{len(rows)}** symbols from `manifest/symbols.toml`, of which "
        f"**{n_proto}** have natural-signature prototypes in "
        f"`manifest/prototypes.toml`.\n\n"
        "Hook a function by name with "
        "`api->override_name(self, \"Name\", fn)`, or by address with "
        "`api->override_addr`. A prototyped function also gets generated "
        "wrappers in `openpete_sdk_wrappers.h`: `OP_OVERRIDE_IMPL_Name`, "
        "`OP_REGISTER_OVERRIDE_Name`, `op_base_Name`, and "
        "`op_call_Name`, which give you typed arguments, pointer "
        "marshalling, and argument-register save and restore. Everything "
        "else uses the raw tier: read `cpu->a0` through `cpu->a3`, and "
        "write `cpu->v0`.\n\n"
        "A `func_XXXXXXXX` name belongs to the part of the decompilation "
        "that isn't named yet. Those names resolve forever under the "
        "decompilation promotion contract, but the loader warns you once "
        "a stable name exists.\n")

    letter = None
    for name, addr, kind, srcf in rows:
        l = name[0].upper() if name[:1].isalpha() else "#"
        if l != letter:
            letter = l
            out.append(f"\n## {letter}\n")
            out.append("| Function | Address | Kind | Signature | Source |")
            out.append("|---|---|---|---|---|")
        sig = protos.get(name)
        sigcell = f"`{sig}` + wrappers" if sig else "raw tier"
        out.append(f"| `{name}` | `{addr}` | {kind} | {sigcell} | {srcf} |")
    out.append("")
    return "\n".join(out), len(rows), n_proto


# ── globals.md ───────────────────────────────────────────────────────────

def gen_globals(globals_path: Path) -> str:
    gl = read_toml_blocks(globals_path, "global")
    rows = sorted(
        ((unq(g.get("name", "")), g.get("addr", "?"),
          unq(g.get("section", "")), unq(g.get("source_file", "")))
         for g in gl),
        key=lambda r: r[0].lower())

    out = [GEN_NOTE, "# Globals\n"]
    out.append(
        f"**{len(rows)}** named guest-RAM globals from "
        "`manifest/globals.toml`. Each one is exported to mods as an "
        "`OP_GADDR_<Name>` virtual-address constant in "
        "`openpete_sdk_symbols.h`. Read and write them through "
        "`api->guest()`, or through the `op_read_*` and `op_write_*` "
        "helpers:\n\n"
        "```c\n"
        "uint32_t spyro = OP_GADDR_g_Spyro;\n"
        "int x = op_read_s32(api, spyro + 0x0C);   /* position.x */\n"
        "```\n\n"
        "Pointers stored inside guest structs are guest virtual "
        "addresses, so translate them again before you follow them. A "
        "`D_80XXXXXX` name belongs to the part of the decompilation that "
        "isn't named yet.\n")
    letter = None
    for name, addr, section, srcf in rows:
        l = name.lstrip("gD_")[:1].upper() or "#"
        base = name[2:] if name.startswith("g_") else name
        l = base[:1].upper() if base[:1].isalpha() else "#"
        if l != letter:
            letter = l
            out.append(f"\n## {letter}\n")
            out.append("| Global | Address | Section | Source |")
            out.append("|---|---|---|---|")
        out.append(f"| `{name}` | `{addr}` | {section} | {srcf} |")
    out.append("")
    return "\n".join(out), len(rows)


# ── structs.md ───────────────────────────────────────────────────────────

def gen_structs(structs_header: Path) -> str:
    out = [GEN_NOTE, "# Game structs\n"]
    if not structs_header or not structs_header.exists():
        out.append("!!! warning\n    `openpete_game_structs.h` wasn\'t "
                   "found. Build the game target once, then run "
                   "`scripts/build-mod-docs.sh` again.\n")
        return "\n".join(out), 0

    src = structs_header.read_text(encoding="utf-8")
    intro_m = re.match(r"\s*(/\*(?:[^*]|\*(?!/))*\*/)", src)
    if intro_m:
        intro = "\n".join(l for l in strip_comment(intro_m.group(1)).splitlines()
                          if not l.startswith("@file"))
        out.append("\n".join("> " + l for l in md_prose(
            dox_to_md(intro).strip()).splitlines()) + "\n")

    sizes = dict(re.findall(
        r'_Static_assert\(sizeof\((\w+)\)\s*==\s*(0x[0-9a-fA-F]+|\d+)', src))
    offsets = {}
    for s, f, off in re.findall(
            r'_Static_assert\(offsetof\((\w+),\s*(\w+)\)\s*==\s*'
            r'(0x[0-9a-fA-F]+|\d+)', src):
        offsets.setdefault(s, []).append((f, off))

    n = 0
    for m in re.finditer(r"typedef struct (\w+) \{(.*?)\} \1;", src, re.S):
        name, body = m.group(1), m.group(0)
        out.append(f"## `{name}`\n")
        meta = []
        if name in sizes:
            meta.append(f"`sizeof == {sizes[name]}`")
        if meta:
            out.append(" · ".join(meta) + ". The layout is pinned, so "
                       "drift fails the mod's compile rather than a "
                       "player's session.\n")
        if name in offsets:
            out.append("| Field | Offset |")
            out.append("|---|---|")
            for f, off in offsets[name]:
                out.append(f"| `{f}` | `{off}` |")
            out.append("")
        out.append(f"```c\n{body.strip()}\n```\n")
        n += 1
    return "\n".join(out), n


# ── gallery.md ───────────────────────────────────────────────────────────

# In-tree mods that exist to exercise the loader in CI, not to show a
# mod author a mechanism. They are omitted from the gallery.
FIXTURES = {
    "arena-canary", "arena-probe", "chain-duo-a", "chain-duo-b",
    "crash-dummy", "demo-lib", "lib-and-client", "raw-probe",
    "sfx-replace-probe", "vstream-rehandle",
}


def gen_gallery(mods_dir: Path) -> str:
    out = [GEN_NOTE, "# Examples\n"]
    out.append("Working example mods from the openpete source tree, "
               "extracted from each `mods/<id>/mod.toml` header. Start "
               "from the one nearest to your idea.\n")
    groups = {"declarative": [], "code": []}
    for toml in sorted(mods_dir.glob("*/mod.toml")):
        if ".unpacked" in toml.parts or toml.parent.name in FIXTURES:
            continue
        text = toml.read_text(encoding="utf-8")
        desc = []
        for line in text.splitlines():
            if line.startswith("#"):
                desc.append(line.lstrip("#").strip())
            elif line.strip():
                break
        fields = {}
        for m in re.finditer(r'^(\w+)\s*=\s*(.+)$', text, re.M):
            fields.setdefault(m.group(1), unq(m.group(2)))
        mid = fields.get("id", toml.parent.name)
        title = fields.get("name", mid)
        srcs = sorted(p.name for p in (toml.parent / "src").glob("*.c"))
        sm = fields.get("sim_mutative")
        mutative = (sm == "true") if sm in ("true", "false") \
            else bool(srcs) or "[[level]]" in text
        bits = [f"v{fields.get('version', '?')}"]
        bits.append("writes guest RAM" if mutative else "writes no guest RAM")
        blocks = sorted({b for b in re.findall(r"^\[\[(\w+)\]\]", text, re.M)})
        if blocks:
            bits.append(", ".join(f"`[[{b}]]`" for b in blocks))
        if srcs:
            bits.append("src: " + ", ".join(f"`{s}`" for s in srcs))
        sec = [f"### `{mid}` — {title}\n", " · ".join(bits) + "\n"]
        # A blank comment line in the header is a paragraph break.
        paras, cur = [], []
        for d in desc:
            if d:
                cur.append(d)
            elif cur:
                paras.append(" ".join(cur)); cur = []
        if cur:
            paras.append(" ".join(cur))
        sec.extend(md_prose(pg) + "\n" for pg in paras)
        groups["code" if srcs else "declarative"].append("\n".join(sec))
    n = 0
    for head, key in (("## Declarative", "declarative"), ("## Code", "code")):
        if groups[key]:
            out.append(head + "\n")
            out.extend(groups[key])
            n += len(groups[key])
    return "\n".join(out), n


# ── main ─────────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--api-header",
                    default=REPO / "core/include/openpete_mod_api.h",
                    type=Path)
    ap.add_argument("--symbols",
                    default=REPO / "games/spyro-1/manifest/symbols.toml",
                    type=Path)
    ap.add_argument("--globals", dest="globals_",
                    default=REPO / "games/spyro-1/manifest/globals.toml",
                    type=Path)
    ap.add_argument("--protos",
                    default=REPO / "games/spyro-1/manifest/prototypes.toml",
                    type=Path)
    ap.add_argument("--structs", type=Path, default=None,
                    help="generated openpete_game_structs.h (default: "
                         "search known build dirs)")
    ap.add_argument("--mods-dir", default=REPO / "mods", type=Path)
    ap.add_argument("--out",
                    default=REPO / "docs/modding/pages/reference",
                    type=Path)
    args = ap.parse_args()

    structs = args.structs
    if structs is None:
        for cand in ("build/linux-release", "build/dev",
                     "build/windows-mingw", "build/windows-mingw-shared"):
            p = REPO / cand / "games/spyro-1/mod_sdk_gen/openpete_game_structs.h"
            if p.exists():
                structs = p
                break

    args.out.mkdir(parents=True, exist_ok=True)

    api_md, n_api = gen_api(args.api_header)
    fn_md, n_fn, n_proto = gen_functions(args.symbols, args.protos)
    gl_md, n_gl = gen_globals(args.globals_)
    st_md, n_st = gen_structs(structs)
    ga_md, n_mods = gen_gallery(args.mods_dir)

    for fname, content in (("api.md", api_md), ("functions.md", fn_md),
                           ("globals.md", gl_md), ("structs.md", st_md),
                           ("gallery.md", ga_md)):
        (args.out / fname).write_text(content, encoding="utf-8")

    if n_api < 25:  # 28 entries + api_version at api v1
        sys.exit(f"gen_mod_docs: only {n_api} API members parsed — the "
                 "header layout changed; fix the extractor")
    print(f"[gen_mod_docs] api: {n_api} members | functions: {n_fn} "
          f"({n_proto} prototyped) | globals: {n_gl} | structs: {n_st} | "
          f"gallery: {n_mods} mods -> {args.out}")


if __name__ == "__main__":
    main()
