#!/usr/bin/env python3
"""Extract jump-table target addresses from a recompiled overlay.

psxrecomp's static analyzer detects `lui+addu+lw+jr` jump tables and emits
a `/* jump table 0xADDR, N entries */` comment with each table-dispatch's
default-`call_by_address` fallback, but it only emits `case` statements for
table entries that resolve to discovered functions or in-function blocks.
Entries that point to *undiscovered* code fall through to the default case
and trigger `stub miss` warnings at runtime.

This tool:
  1) parses the generated `<name>_full.c` for jump-table comments,
  2) reads N consecutive words from the raw overlay bytes at each table
     address (translating vaddr -> file offset via load_addr),
  3) outputs unique entries (filtered to the overlay's address range) in
     discovered_functions.log style, ready to feed back to psxrecomp via
     `--extra-funcs=<file>`.

Usage:
    extract_jumptable_targets.py <generated-full.c> <raw-overlay-bytes> \\
        --load-addr=0xADDR <out-file>

The raw bytes are the *unwrapped* overlay (e.g. the matching-decomp's
`build/wad/*.ovl`), not the synthesized PS1-EXE wrapper - the wrapper
prefixes 2 KiB which would shift every offset.
"""
import argparse
import re
import struct
import sys
from pathlib import Path

JTBL_RE = re.compile(r'/\*\s*jump table 0x([0-9A-Fa-f]+),\s*(\d+)\s*entries\b[^*]*\*/')


def harvest(c_path: Path, ovl_path: Path, load_addr: int) -> tuple[set[int], int, int]:
    """Returns (target_set, table_count, total_entries)."""
    text = c_path.read_text()
    bytes_ = ovl_path.read_bytes()
    end_addr = load_addr + len(bytes_)

    targets: set[int] = set()
    table_count = 0
    total_entries = 0

    for m in JTBL_RE.finditer(text):
        tbl_vaddr = int(m.group(1), 16)
        n_entries = int(m.group(2))
        off = tbl_vaddr - load_addr
        if off < 0 or off + 4 * n_entries > len(bytes_):
            print(f'warn: table 0x{tbl_vaddr:08X} (+{n_entries}) out of bounds - skipped',
                  file=sys.stderr)
            continue
        table_count += 1
        for i in range(n_entries):
            val, = struct.unpack_from('<I', bytes_, off + 4 * i)
            total_entries += 1
            # Only valid kseg0 RAM addresses, 4-byte aligned, inside this overlay.
            if val == 0:
                continue
            if val & 0x3:
                continue
            if not (load_addr <= val < end_addr):
                continue
            targets.add(val)
    return targets, table_count, total_entries


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('generated_c', type=Path,
                   help='psxrecomp <name>_full.c with jump-table comments')
    p.add_argument('overlay_bytes', type=Path,
                   help='raw overlay bytes (matching-decomp build/wad/*.ovl)')
    p.add_argument('out_file', type=Path,
                   help='output addresses (one per line, hex)')
    p.add_argument('--load-addr', required=True,
                   help='kseg0 vaddr the overlay loads at (e.g. 0x8007AA38)')
    args = p.parse_args()

    load_addr = int(args.load_addr, 0)
    targets, table_count, total_entries = harvest(
        args.generated_c, args.overlay_bytes, load_addr)

    with args.out_file.open('w') as f:
        f.write(
            f"# {args.out_file.name} - auto-generated by\n"
            f"# tools/extract_jumptable_targets.py from {args.generated_c.name}.\n"
            f"# Do not hand-edit. {table_count} tables, {total_entries} entries scanned,\n"
            f"# {len(targets)} unique in-range targets.\n"
        )
        for a in sorted(targets):
            f.write(f'0x{a:08X}\n')
    print(f'wrote {len(targets)} jump-table entries to {args.out_file} '
          f'({table_count} tables, {total_entries} entries scanned)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
