#!/usr/bin/env python3
"""Generate placeholder bodies for every PSYQ symbol in a manifest.

Phase 1b uses these stubs so the binary links — every PSYQ symbol the
recompiled C declares `extern void NAME(CPUState* cpu);` resolves to a
function that logs the call and aborts. Phase 1c will replace selected
stubs with real PsyCross thunks (generated, ABI-translating).

Usage:
    gen_psyq_stubs.py manifest.toml output.c [--prefix STR]

The --prefix must match the recompiler's --external-prefix, so the stub
names match the names the dispatch table calls.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path


def parse_manifest(path: Path) -> list[tuple[str, int]]:
    text = path.read_text()
    syms: list[tuple[str, int]] = []
    name = addr = None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("[[") and line.endswith("]]"):
            if name is not None and addr is not None:
                syms.append((name, addr))
            name = addr = None
            continue
        m = re.match(r'name\s*=\s*"([^"]+)"', line)
        if m:
            name = m.group(1)
            continue
        m = re.match(r"addr\s*=\s*(0x[0-9a-fA-F]+|\d+)", line)
        if m:
            addr = int(m.group(1), 0)
    if name is not None and addr is not None:
        syms.append((name, addr))
    return syms


HEADER = """\
/* Generated by tools/gen_psyq_stubs.py — do not edit by hand.
 *
 * Phase 1b PSYQ-symbol shim. Every PSYQ symbol the recompiled C calls
 * lands here and aborts. The point is link-time visibility, not runtime
 * correctness — Phase 1c+ replaces these with real PsyCross thunks
 * (generated by tools/gen_psyq_thunks.py, with ABI translation).
 *
 * Caveat: PSYQ exports a few stdlib names (printf/sprintf/exit/rand/srand/
 * strlen/etc.). We deliberately do NOT include <stdio.h>/<stdlib.h> here
 * so those PSYQ stubs don't collide with libc's prototypes. The real
 * fprintf+abort body lives in psyq_stub_runtime.c.
 */

#include "psx_runtime.h"

extern void psyq_stub_hit(const char* name, uint32_t addr, CPUState* cpu);

"""


def main() -> int:
    args = sys.argv[1:]
    prefix = ""
    while args and args[0].startswith("--"):
        if args[0] == "--prefix" and len(args) >= 2:
            prefix = args[1]
            args = args[2:]
        else:
            print(__doc__, file=sys.stderr)
            return 2
    if len(args) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    manifest, output = Path(args[0]), Path(args[1])
    syms = parse_manifest(manifest)
    if not syms:
        print(f"no symbols parsed from {manifest}", file=sys.stderr)
        return 1

    seen: set[str] = set()
    lines = [HEADER]
    for name, addr in syms:
        sym = f"{prefix}{name}"
        if sym in seen:
            continue
        seen.add(sym)
        lines.append(
            f"void {sym}(CPUState* cpu) {{ psyq_stub_hit(\"{sym}\", 0x{addr:08X}u, cpu); }}\n"
        )
    output.write_text("".join(lines))
    print(f"wrote {output} ({len(seen)} PSYQ stubs, prefix='{prefix}')")
    return 0


if __name__ == "__main__":
    sys.exit(main())
