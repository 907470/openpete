#!/usr/bin/env python3
"""Generate the per-game list of PSYQ abort-on-call stubs from a manifest.

One stub line per PSYQ symbol in the manifest, naming the symbol and its
guest address. The build compiles no generated psyq_stubs.c:
tools/filter_psyq_stubs.py reads the lines, subtracts the names the shared
thunk layer defines, and emits the compile-once union of every game's stubs
and each game's address table.

Usage:
    gen_psyq_stubs.py manifest.toml output.c [--prefix STR]

The --prefix must match the recompiler's --external-prefix, so the stub
names match the names the dispatch table calls.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path


def parse_manifest(path: Path) -> list[tuple[str, int]]:
    text = path.read_text()
    syms: list[tuple[str, int]] = []
    name = addr = None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("[[") and line.endswith("]]"):
            if name is not None and addr is not None:
                syms.append((name, addr))
            name = addr = None
            continue
        m = re.match(r'name\s*=\s*"([^"]+)"', line)
        if m:
            name = m.group(1)
            continue
        m = re.match(r"addr\s*=\s*(0x[0-9a-fA-F]+|\d+)", line)
        if m:
            addr = int(m.group(1), 0)
    if name is not None and addr is not None:
        syms.append((name, addr))
    return syms


HEADER = """\
/* Generated by tools/gen_psyq_stubs.py - do not edit by hand.
 *
 * PSYQ-symbol stub list: one abort-on-call body per PSYQ symbol in the
 * manifest, with the symbol's guest address. The build does not compile
 * this file. tools/filter_psyq_stubs.py reads its stub lines, drops the
 * names the shared thunk layer defines, and emits the stubs of every game
 * as one compile-once set of strong definitions (no weak definition and no
 * permissive link option on any platform) plus this game's address table,
 * which psyq_stub_hit (psyq_stub_runtime.c) reads. OPENPETE_WEAK is the
 * stub-line marker the filter matches.
 */

"""


def main() -> int:
    args = sys.argv[1:]
    prefix = ""
    while args and args[0].startswith("--"):
        if args[0] == "--prefix" and len(args) >= 2:
            prefix = args[1]
            args = args[2:]
        else:
            print(__doc__, file=sys.stderr)
            return 2
    if len(args) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    manifest, output = Path(args[0]), Path(args[1])
    syms = parse_manifest(manifest)
    if not syms:
        print(f"no symbols parsed from {manifest}", file=sys.stderr)
        return 1

    seen: set[str] = set()
    lines = [HEADER]
    for name, addr in syms:
        sym = f"{prefix}{name}"
        if sym in seen:
            continue
        seen.add(sym)
        lines.append(
            f"OPENPETE_WEAK void {sym}(CPUState* cpu) {{ psyq_stub_hit(\"{sym}\", 0x{addr:08X}u, cpu); }}\n"
        )
    output.write_text("".join(lines))
    print(f"wrote {output} ({len(seen)} PSYQ stubs, prefix='{prefix}')")
    return 0


if __name__ == "__main__":
    sys.exit(main())
