#!/usr/bin/env python3
"""Extract basic blocks that no emitted control flow reaches.

Handwritten MIPS dispatches through a register whose value is a code
address built at run time, most often as a base plus a selector:

    lui   t3, 0x8004
    addiu t3, t3, -5448        # t3 = 0x8003EAB8, a label in this function
    addu  s1, s1, t3           # s1 = t3 + {0, 8, 16}
    jr    s1

psxrecomp cannot fold that into a switch, so it emits
`call_by_address(cpu, cpu->s1); return;`. The landing pads stay in the
generated C as `block_<addr>` labels, but nothing branches to them: the
only way in is the dispatch table, and they are not entries in it. The
call misses, the C function *returns*, and every instruction from the
landing pad to the end of the routine is skipped. The routine's caller
then reads whatever its output registers held before the call.

A block with no `goto` and no fall-through into it is exactly that shape.
Promoting it to a forced entry is safe by the same property that
identifies it: with no fall-in path, splitting the containing function
there cannot make any block execute twice.

This differs from the sibling extractors: `extract_jumptable_targets.py`
reads `lui+addu+lw+jr` tables out of the binary's data,
`extract_split_targets.py` parses the recompiler's split markers,
`extract_asm_dispatch_targets.py` harvests `glabel D_<addr>` from the
decomp, and `extract_overlay_func_pointers.py` folds `lui+addiu` pairs
that land in an overlay. None of them sees a landing pad whose address is
never materialized whole, such as the `+8` and `+16` cases above.

Promoting blocks changes the function partition and can expose further
orphans, so callers run this to a fixed point.

Usage:
    extract_orphan_blocks.py <generated-full.c> <out-file>
"""
import argparse
import re
from pathlib import Path

BLOCK_RE = re.compile(r'^block_([0-9A-Fa-f]{8}):', re.M)
GOTO_RE  = re.compile(r'goto block_([0-9A-Fa-f]{8})')
FALL_RE  = re.compile(r'fall through to block_([0-9A-Fa-f]{8})')
FUNC_RE  = re.compile(r'^void (\w+)\(CPUState\* cpu\)\n\{', re.M)
FUNC_ADDR_RE = re.compile(r'_([0-9A-Fa-f]{8})$')
# An unresolved register jump: the transfer whose landing pads this finds.
REG_JR_RE = re.compile(r'call_by_address\(cpu, cpu->\w+\);\s*/\* jr cpu->')
# A word psxrecomp could not decode. Filler and data read as code produce
# these, and a block harvested out of a data run splits a function at an
# address psxrecomp will not accept as an entry, so the loop never settles.
UNDECODED_RE = re.compile(r'/\* TODO: opcode=')


def harvest(text: str) -> list[int]:
    reached = {int(m.group(1), 16) for m in GOTO_RE.finditer(text)}
    reached |= {int(m.group(1), 16) for m in FALL_RE.finditer(text)}

    # Walk function by function: a block only counts when the function it
    # sits in actually contains a register jump. Data decoded as code
    # produces unreferenced blocks too, and promoting one of those splits a
    # function at an address psxrecomp will not accept as an entry, so the
    # convergence loop never terminates.
    starts = [(m.start(), m.group(1)) for m in FUNC_RE.finditer(text)]
    orphans: set[int] = set()
    for i, (pos, fname) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else len(text)
        body = text[pos:end]
        m = FUNC_ADDR_RE.search(fname)
        if m:
            reached.add(int(m.group(1), 16))
        if not REG_JR_RE.search(body) or UNDECODED_RE.search(body):
            continue
        orphans |= {int(b.group(1), 16) for b in BLOCK_RE.finditer(body)}
    return sorted(orphans - reached)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('generated_c', type=Path)
    p.add_argument('out_file', type=Path)
    args = p.parse_args()

    targets = harvest(args.generated_c.read_text())
    with args.out_file.open('w') as f:
        f.write(
            f"# {args.out_file.name} - auto-generated by\n"
            f"# tools/extract_orphan_blocks.py from {args.generated_c.name}.\n"
            f"# Do not hand-edit. {len(targets)} block(s) with no incoming edge.\n"
        )
        for a in targets:
            f.write(f'0x{a:08X}\n')
    print(f'{len(targets)} orphan block(s) -> {args.out_file}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
