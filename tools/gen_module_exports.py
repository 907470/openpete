#!/usr/bin/env python3
"""gen_module_exports.py — the exe's export surface for the shared-linkage
recomp module.

The dynamically-loaded recomp module imports two families from the exe:

  * psyq_<name> for every PSYQ symbol in manifest/psyq.toml (the strong
    thunks + weak abort stubs both live exe-side), and
  * the psx_runtime ABI surface it calls directly, maintained by hand in
    games/spyro-1/manifest/module_abi_exports.txt (lines: `symbol` or
    `symbol DATA`; '#' comments). Self-enforcing: a module import missing
    here fails the module link with an undefined symbol.

Emits:
  --def       PE .def exporting exactly this surface (linked into the exe
              AND fed to dlltool for the module's import library).
  --keepalive C TU referencing every non-psyq symbol so the exe link pulls
              their archive members even though no exe code references
              them.
"""
import argparse
import re
import sys

ap = argparse.ArgumentParser()
ap.add_argument("--psyq", required=True)
ap.add_argument("--extras", required=True)
ap.add_argument("--image", required=True, help="exe image name for LIBRARY")
ap.add_argument("--def-out")
ap.add_argument("--keepalive-out")
args = ap.parse_args()

psyq_names = re.findall(r'^name\s*=\s*"([^"]+)"', open(args.psyq).read(), re.M)
if not psyq_names:
    sys.exit("no [[symbols]] names parsed from " + args.psyq)

extras = []  # (symbol, is_data)
for raw in open(args.extras):
    line = raw.split("#", 1)[0].strip()
    if not line:
        continue
    parts = line.split()
    extras.append((parts[0], len(parts) > 1 and parts[1].upper() == "DATA"))

if args.def_out:
    with open(args.def_out, "w") as f:
        # NAME (not LIBRARY): a LIBRARY statement makes ld set the PE
        # DLL flag on the linked image — an exe linked with it becomes
        # unexecutable. dlltool gets the image name via -D instead.
        f.write(f"NAME {args.image}\nEXPORTS\n")
        for sym, is_data in extras:
            f.write(f"  {sym} DATA\n" if is_data else f"  {sym}\n")
        for name in psyq_names:
            f.write(f"  psyq_{name}\n")
        f.write("  psyq_stub_hit\n")

if args.keepalive_out:
    with open(args.keepalive_out, "w") as f:
        f.write("/* AUTO-GENERATED by tools/gen_module_exports.py — do not edit.\n"
                " * References every non-psyq ABI symbol the shared recomp module\n"
                " * imports, so the exe link pulls their archive members even when\n"
                " * no exe code references them.\n"
                " *\n"
                " * used + retain are load-bearing under LTO: the array has\n"
                " * external linkage but nothing references it, so the\n"
                " * whole-program LTO view would dead-strip it — taking the\n"
                " * out-of-line copies of the ABI functions with it, after which\n"
                " * the .def exports resolve to bad addresses and the dlopen'd\n"
                " * module jumps into hyperspace (DEP fault). used/retain pin the\n"
                " * array and the anchor fn so the whole reference chain stays\n"
                " * live through LTO. */\n"
                "#if defined(__GNUC__)\n"
                "#  define OPENPETE_KEEPALIVE __attribute__((used, retain))\n"
                "#else\n"
                "#  define OPENPETE_KEEPALIVE\n"
                "#endif\n\n")
        for sym, is_data in extras:
            f.write(f"extern unsigned char {sym}[];\n" if is_data
                    else f"extern void {sym}(void);\n")
        f.write("\nOPENPETE_KEEPALIVE\n"
                "const void* const spyro1_recomp_abi_keepalive[] = {\n")
        for sym, is_data in extras:
            f.write(f"    (const void*)&{sym},\n")
        f.write("    0,\n};\n\n")
        # A used, noinline anchor that actually reads the array — LTO cannot
        # prove the array (hence the address-taken ABI symbols) is dead.
        f.write("OPENPETE_KEEPALIVE\n"
                "const void* spyro1_recomp_abi_anchor(unsigned i);\n"
                "const void* spyro1_recomp_abi_anchor(unsigned i) {\n"
                "    return spyro1_recomp_abi_keepalive[i];\n"
                "}\n")

print(f"module exports: {len(extras)} ABI + {len(psyq_names)} psyq", file=sys.stderr)
