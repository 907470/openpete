#!/usr/bin/env python3
"""Write games/spyro-1/corpus/dragon-rescue-corpus.manifest from dragons.tsv.

One presentation-corpus row per dragon rescue (the row form of
tests/harness/presentation-corpus.sh: name | start | interval | freeze |
pins | launch). The row has no movie: --skip-to-level and --player-pose
place Spyro above the statue, the landing triggers the rescue, and the
row's length is its last pin.

  name      <level>-<dragon>-<moby_idx>, lower case (dragon names repeat
            across levels, the moby index does not within one)
  pins      every 60 VBLs from the trigger to the end, the camera cuts,
            and the end VBL
  start     end - 1, interval 2: the harness grid steps from start to one
            point past the last pin, so it adds canon end-1 and end+1 and
            intermediate end+2, and the frame-limit is end + 3
  launch    the route (if any), --skip-to-level <level> and --player-pose
            with the pose written without spaces, since the launch field
            splits on whitespace (the pose parser reads only the integers)

Usage: tools/gen_dragon_corpus.py [--check]
  --check   exit 1 when the committed manifest differs from the generated one
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORPUS = os.path.join(ROOT, "games", "spyro-1", "corpus")
TABLE = os.path.join(CORPUS, "dragons.tsv")
MANIFEST = os.path.join(CORPUS, "dragon-rescue-corpus.manifest")

GRID = 60             # sampling step inside the cutscene, VBLs
MAX_PINS = 64         # the binary's --screenshot list cap per process

HEADER = """\
# Spyro 1 dragon-rescue corpus: one row per dragon rescue (80).
# GENERATED by tools/gen_dragon_corpus.py from dragons.tsv; edit the table
# and rerun the tool, never this file.
#
# Row form of tests/harness/presentation-corpus.sh (name | start | interval |
# freeze | pins | launch). No row has a movie: the launch places Spyro above
# the statue, the landing triggers the rescue cutscene, and the row's length
# is its last pin (the end VBL). Pins: every 60 VBLs from the trigger to the
# end, the camera cuts, the end. start = end - 1 with interval 2 keeps the
# harness grid within 3 VBLs of the end.
#
# Captured by tests/harness/check_dragon_golden.sh at stock LOD only; golden
# tests/golden/spyro-1/dragons/.
#
# name | start | int. | freeze | pins | launch
"""


def read_table(path):
    rows = []
    with open(path) as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            cols = line.rstrip("\n").split("\t")
            if cols[0] == "level":
                continue
            if len(cols) != 10:
                sys.exit("FAIL: %s: expected 10 columns, got %d: %r" % (TABLE, len(cols), line))
            rows.append(dict(zip(("level", "dragon", "moby_idx", "name_index", "statue_pos",
                                  "pose", "trigger", "cuts", "end", "route"), cols)))
    return rows


def row_line(r):
    trig, end = int(r["trigger"]), int(r["end"])
    cuts = [] if r["cuts"] == "-" else [int(c) for c in r["cuts"].split(",")]
    if end <= trig or any(c < trig or c > end for c in cuts):
        sys.exit("FAIL: %s-%s: cuts %s outside [trigger %d, end %d]" % (r["level"], r["moby_idx"], cuts, trig, end))
    pins = sorted(set(range(trig, end + 1, GRID)) | set(cuts) | {end})
    if len(pins) + 2 > MAX_PINS:
        sys.exit("FAIL: %s-%s: %d pins exceed the %d-frame screenshot cap" % (r["level"], r["moby_idx"], len(pins), MAX_PINS))
    name = "%s-%s-%s" % (r["level"], r["dragon"].lower(), r["moby_idx"])
    if not re.fullmatch(r"[a-z0-9_]+-[a-z]+-\d+", name):
        sys.exit("FAIL: bad row name %r" % name)
    pose = r["pose"].replace(" ", "")
    launch = [] if r["route"] == "-" else r["route"].split()
    if "--skip-to-level" not in launch:
        launch += ["--skip-to-level", r["level"]]
    launch += ["--player-pose", pose]
    return name, "%s | %d | 2 | | %s | %s" % (name, end - 1, ",".join(map(str, pins)), " ".join(launch))


def generate():
    rows = read_table(TABLE)
    seen = set()
    out = [HEADER]
    for r in rows:
        name, line = row_line(r)
        if name in seen:
            sys.exit("FAIL: duplicate row name %s" % name)
        seen.add(name)
        out.append(line + "\n")
    return "".join(out), len(rows)


def main():
    text, n = generate()
    if "--check" in sys.argv[1:]:
        cur = open(MANIFEST).read() if os.path.isfile(MANIFEST) else ""
        if cur != text:
            print("FAIL: %s is stale; run tools/gen_dragon_corpus.py" % os.path.relpath(MANIFEST, ROOT))
            return 1
        print("OK: %s matches dragons.tsv (%d rows)" % (os.path.relpath(MANIFEST, ROOT), n))
        return 0
    with open(MANIFEST, "w") as f:
        f.write(text)
    print("wrote %s (%d rows)" % (os.path.relpath(MANIFEST, ROOT), n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
