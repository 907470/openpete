#!/usr/bin/env python3
"""gen_proto_db.py - harvest function prototypes from the decomp headers
into a committed manifest (the framework's "prototype database").

Natural-signature
marshalling wrappers are generated from prototypes, decoupled from
whether a function body is decompiled/matched - so the DB is dev-side
metadata, committed like the forced-entry lists, and builds never need
the (private) decomp checkout.

Run (dev machine, whenever decomp headers advance):
  tools/gen_proto_db.py --headers games/spyro-1/spyro-1/include \
      --out games/spyro-1/manifest/prototypes.toml

Parses the decomp's uniform single-line declaration style:
  int  Atan2(int pY, int pX, int output16Bit);
  void CollectItem(Moby *pMoby);
Skips (recorded in the header comment): function pointers, varargs,
struct-by-value params, >4 register-word args - those stay raw-tier
until the generator grows the sp-scratch-frame path.
"""

import argparse
import re
import sys
from pathlib import Path

DECL_RE = re.compile(
    r"^\s*([A-Za-z_][A-Za-z0-9_ ]*?)\s*(\*{0,2})\s*"
    r"([A-Za-z_]\w*)\s*\(([^)]*)\)\s*;\s*$")

INT_TYPES = {
    "int", "unsigned", "unsigned int", "u_int", "uint", "long", "u_long",
    "short", "u_short", "unsigned short", "char", "u_char",
    "unsigned char", "signed char",
    "s8", "u8", "s16", "u16", "s32", "u32", "bool",
}


def classify(type_str, stars):
    """-> ('void'|'int'|'ptr:<T>'|None). None = unsupported."""
    t = " ".join(type_str.split())
    if stars:
        base = t
        if base.startswith("const "):
            base = base[6:]
        if len(stars) != 1:
            return None  # ** unsupported in v0
        return f"ptr:{base}"
    if t == "void":
        return "void"
    if t in INT_TYPES:
        return "int"
    return None


def parse_param(p, idx):
    """-> (kind, name) or (None, None) if unsupported."""
    p = p.strip()
    if not p or p == "void":
        return "void", None
    if "..." in p or "(" in p or "[" in p:
        return None, None
    m = re.match(r"^(.*?)\s*(\*{0,2})\s*([A-Za-z_]\w*)$", p)
    if m and m.group(1).strip():
        kind = classify(m.group(1), m.group(2))
        if kind:
            return kind, m.group(3)
    # Unnamed param ("int", "Vector3D *") - synthesize a name.
    m2 = re.match(r"^(.*?)\s*(\*{0,2})$", p)
    if m2:
        kind = classify(m2.group(1), m2.group(2))
        if kind and kind != "void":
            return kind, f"arg{idx}"
    return None, None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--headers", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    protos = {}
    skipped = []
    for h in sorted(args.headers.rglob("*.h")):
        for line in h.read_text(encoding="utf-8",
                                errors="replace").splitlines():
            if "(*" in line or "..." in line:
                continue
            m = DECL_RE.match(line)
            if not m:
                continue
            rtype, rstars, name, params = m.groups()
            first = rtype.split()[0] if rtype.split() else ""
            if first in ("typedef", "extern", "static", "return", "else"):
                continue
            ret = classify(rtype, rstars)
            if ret is None:
                skipped.append((name, f"ret {rtype}{rstars}"))
                continue
            plist = []
            bad = None
            if params.strip() not in ("", "void"):
                for pi, p in enumerate(params.split(",")):
                    kind, pname = parse_param(p, pi)
                    if kind is None or kind == "void":
                        bad = f"param {p.strip()!r}"
                        break
                    if any(n == pname for _, n in plist):
                        pname = f"{pname}{pi}"
                    plist.append((kind, pname))
            if bad:
                skipped.append((name, bad))
                continue
            if len(plist) > 4:
                skipped.append((name, f"{len(plist)} args > 4"))
                continue
            if name not in protos:  # first declaration wins
                protos[name] = (ret, plist, h.name)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8") as f:
        f.write(
            "# prototypes.toml - the modding-framework prototype database.\n"
            "# GENERATED by tools/gen_proto_db.py from the decomp headers;\n"
            "# committed (like the forced-entry lists) so builds never need\n"
            "# the decomp checkout. Regenerate when decomp headers advance:\n"
            "#   tools/gen_proto_db.py --headers <decomp>/include \\\n"
            "#       --out games/spyro-1/manifest/prototypes.toml\n"
            "# Types: 'void' | 'int' (any <=32-bit integer scalar) |\n"
            "# 'ptr:<T>' (pointer to T, marshalled guest<->host, T opaque).\n"
            f"# Skipped {len(skipped)} declarations (fn-ptr/varargs/by-value/"
            ">4 args) - raw tier.\n\n")
        for name in sorted(protos):
            ret, plist, hdr = protos[name]
            f.write("[[proto]]\n")
            f.write(f'name = "{name}"\n')
            f.write(f'ret = "{ret}"\n')
            if plist:
                pl = ", ".join(
                    f'{{ type = "{k}", name = "{n}" }}' for k, n in plist)
                f.write(f"params = [ {pl} ]\n")
            f.write(f'header = "{hdr}"\n\n')

    print(f"gen_proto_db: {len(protos)} prototypes "
          f"({len(skipped)} skipped) -> {args.out}")
    for name, why in skipped[:12]:
        print(f"  skipped {name}: {why}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
