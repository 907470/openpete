#!/usr/bin/env python3
"""Generate native_renames.h — the force-included symbol redirector.

Every natively-compiled spyro-1/src/*.c TU pulls this header in via
`-include` (added to SPYRO_DECOMP_BASE_FLAGS). It #defines symbol
names so the matching-decomp source can stay byte-identical to the
upstream tree while the host link resolves to the right thunk or
renamed body.

Three classes of rename:

  1. PSYQ wrappers — `[[outbound_psyq]]` entries.
     `#define CdControl openpete_CdControl`
     ...so calls in cd.c/initialization.c reach the Spyro-enhanced
     wrapper instead of PsyCross's raw entry.

  2. Recomp callees with explicit c_name — `[[outbound_recomp]]`
     entries that carry a c_name override (today: every func_<ADDR>
     name, since those collide with PSX.EXE_full.c's recompiled body
     of the same name).
     `#define func_80017F24 openpete_func_80017F24`

  3. Native bodies that share a name with the recompiled body —
     functions in symbols.toml whose source_file is in [[native_source]]
     AND whose name starts with `func_`. The native body and the
     recomp body cannot share a symbol; we rename the native to
     `spyro_native_<name>` so it gets its own slot, and add a
     [[dispatch]] entry to redirect the addr to the renamed symbol
     (still TODO — without it, recomp callers see the recomp body).
     `#define func_80012604 spyro_native_func_80012604`

`main` gets the same treatment as #3 (special-cased — its decl lives
in src/main.c, not a header).

Usage:
    gen_renames.py <manifest_dir> <out_h_path>
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _manifest_lib import load_manifest, fail


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print("usage: gen_renames.py <manifest_dir> <out_h>", file=sys.stderr)
        return 2
    manifest_dir = Path(argv[1])
    out_path = Path(argv[2])

    native, sym_idx, _ = load_manifest(manifest_dir)
    native_sources = {ns["file"] for ns in native.get("native_source", [])}

    lines = [
        "/* Auto-generated by tools/gen_renames.py — do not edit.",
        " *",
        " * Force-included into every natively-compiled spyro-1/src/*.c so",
        " * matching-decomp source can stay byte-identical to upstream while",
        " * the host link resolves the right thunk / renamed body. See the",
        " * gen_renames.py docstring for the three rename classes.",
        " */",
        "#ifndef SPYRO_NATIVE_RENAMES_H",
        "#define SPYRO_NATIVE_RENAMES_H",
        "",
    ]

    # --- Class 1: PSYQ wrappers ---------------------------------------------
    psyq = native.get("outbound_psyq", [])
    if psyq:
        lines.append("/* [[outbound_psyq]] — route to psyq_<NAME>(cpu) wrappers. */")
        for p in sorted(psyq, key=lambda x: x["psyq_name"]):
            lines.append(f"#define {p['psyq_name']} {p['c_name']}")
        lines.append("")

    # --- Class 2: outbound_recomp with explicit c_name ----------------------
    recomp = native.get("outbound_recomp", [])
    explicit = [r for r in recomp if "c_name" in r and r["c_name"] != r["name"]]
    if explicit:
        lines.append("/* [[outbound_recomp]] entries with c_name overrides — */")
        lines.append("/* call sites get redirected to the renamed thunk. */")
        for r in sorted(explicit, key=lambda x: x["name"]):
            lines.append(f"#define {r['name']} {r['c_name']}")
        lines.append("")

    # --- Class 3: native func_<ADDR> bodies ---------------------------------
    # Walk symbols.toml, pick decomp functions whose source is native AND
    # whose name starts with `func_`. Those names clash with PSX.EXE_full.c
    # so the native definition gets a `spyro_native_` prefix.
    by_name = sym_idx["by_name"]
    native_func_renames: list[str] = []
    for name, info in by_name.items():
        if info.get("source_file") not in native_sources:
            continue
        if not name.startswith("func_"):
            continue
        native_func_renames.append(name)
    native_func_renames.sort()
    if native_func_renames:
        lines.append("/* Native func_<ADDR> bodies — rename to dodge the */")
        lines.append("/* recompiled body of the same name in PSX.EXE_full.c. */")
        for name in native_func_renames:
            lines.append(f"#define {name} spyro_native_{name}")
        lines.append("")

    # --- Special case: main() ----------------------------------------------
    # `main` is declared inside src/main.c (not a header). It clashes with
    # the host C runtime entry, so always rename when src/main.c is native.
    if "src/main.c" in native_sources:
        lines.append("/* main() — clashes with host CRT entry. */")
        lines.append("#define main spyro_native_main")
        lines.append("")

    lines.append("#endif  /* SPYRO_NATIVE_RENAMES_H */")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n")
    counts = (
        f"{len(psyq)} psyq + "
        f"{len(explicit)} recomp-override + "
        f"{len(native_func_renames)} native func_*"
    )
    print(f"emitted {counts} renames → {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
