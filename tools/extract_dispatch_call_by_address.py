#!/usr/bin/env python3
"""Harvest jumptable-case targets that psxrecomp left as stub dispatches.

When psxrecomp's static jumptable analysis can't resolve a `case` to a
known function, it emits `case N: call_by_address(cpu, 0xADDRu); return;`
The runtime then has to dispatch ADDR via the global table; if ADDR is
not a forced-entry, the dispatch stub-misses.

This tool greps a recompiled `_full.c` for that exact pattern and
writes the unique address set in `--extra-funcs=` format. Re-feed the
file as a forced-entry source to the next recomp of the same binary
to turn each stub into a direct call.

Also harvests the bare `call_by_address(cpu, 0xADDRu); return;  /* jal
cont: split */` form that the recompiler emits when a function is
split mid-jal-continuation — same root issue, same fix.

Usage:
    extract_dispatch_call_by_address.py <full.c> <out>
"""
import argparse
import re
from pathlib import Path
import sys


SWITCH_RE = re.compile(
    r'case\s+\d+u:\s*call_by_address\(cpu,\s*0x([0-9A-Fa-f]+)u\)'
)
SPLIT_RE = re.compile(
    r'call_by_address\(cpu,\s*0x([0-9A-Fa-f]+)u\)\s*;\s*return;\s*'
    r'/\*\s*jal cont: split\s*\*/'
)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('generated_c', type=Path)
    p.add_argument('out', type=Path)
    args = p.parse_args()

    text = args.generated_c.read_text()
    targets = set()
    for m in SWITCH_RE.finditer(text):
        targets.add(int(m.group(1), 16))
    for m in SPLIT_RE.finditer(text):
        targets.add(int(m.group(1), 16))

    with args.out.open('w') as f:
        f.write(
            f"# {args.out.name} — auto-generated by\n"
            f"# tools/extract_dispatch_call_by_address.py from {args.generated_c.name}.\n"
            f"# Do not hand-edit. {len(targets)} unique stub-dispatch targets.\n"
        )
        for a in sorted(targets):
            f.write(f'0x{a:08X}\n')
    print(f'wrote {len(targets)} stub-dispatch targets to {args.out}',
          file=sys.stderr)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
