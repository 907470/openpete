#!/usr/bin/env python3
"""Generate the outbound-thunk file (native C → recompiled MIPS / PSYQ).

Two outbound shapes, distinguished by manifest table:

    [[outbound_recomp]]   native C call  →  psx_dispatch_compiled(addr)
                          (e.g. Initialize, GamestateUpdate, SoundsUpdate)

    [[outbound_psyq]]     native C call  →  psyq_<NAME>(cpu)
                          (e.g. openpete_CdControl, …; preserves Spyro-
                           specific enhancements layered on top of
                           PsyCross's PSYQ shims)

Both shapes share marshalling: pack args from the host-ABI parameters
into cpu->a0..a3 (and stack slots), set ra to a sentinel, dispatch,
extract the return from cpu->v0, restore the scratch slots so the
caller's CPU state survives.

Argument types come from the C headers — spyro-1/include/ for the
recomp callees and PsyCross/include/psx/ for the PSYQ wrappers.

Usage:
    gen_thunks.py <manifest_dir> <out_cpp> <spyro_include> <psyq_include>
                  [<rewritten_dir>]

If ``rewritten_dir`` is given, per-TU ``*.discovered.toml`` files under it
are merged into the outbound_{recomp,psyq} sets; hand entries in
native.toml override auto-discovered ones with the same name.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _manifest_lib import load_manifest, fail
from parse_headers import load_signatures, Signature, type_to_marshal_token


REG_FOR_INDEX = ["a0", "a1", "a2", "a3"]


def render_param_decl(idx: int, ty: str, name: str) -> str:
    if not name:
        name = f"arg{idx}"
    # Spaces around `*` are uglier than `T*` but the parsed return-type
    # often comes back as `u_char *` with the space. Don't fight it.
    return f"{ty} {name}".strip()


def pack_arg_to_cpu(idx: int, ty: str, c_name: str) -> str:
    """Emit the line that copies host-side arg `c_name` into cpu->aN
    (or pushes onto the stack at sp+offset)."""
    tok = type_to_marshal_token(ty)
    if idx < 4:
        reg = REG_FOR_INDEX[idx]
        if tok == "ptr":
            return f"    cpu->{reg} = host_to_psx({c_name});"
        if tok == "u8":
            return f"    cpu->{reg} = (uint32_t)({c_name}) & 0xFFu;"
        return f"    cpu->{reg} = (uint32_t)({c_name});"
    # Stack — 5th arg lands at sp+16, 6th at sp+20, …
    offset = 16 + (idx - 4) * 4
    if tok == "ptr":
        return f"    cpu->write_word(cpu->sp + {offset}, host_to_psx({c_name}));"
    return f"    cpu->write_word(cpu->sp + {offset}, (uint32_t)({c_name}));"


def render_return(ret_type: str) -> tuple[str, str]:
    """Returns (capture_line_or_empty, return_line_or_empty)."""
    rt = ret_type.strip()
    if rt == "void" or rt == "":
        return ("", "")
    tok = type_to_marshal_token(rt)
    if tok == "ptr":
        return (
            "    void* _rc = openpete_psx_to_host_ptr(cpu->v0);",
            f"    return ({rt})_rc;",
        )
    return (
        "    uint32_t _rc = (uint32_t)cpu->v0;",
        f"    return ({rt})_rc;",
    )


def render_thunk(name: str, c_name: str, sig: Signature, dispatch_call: str,
                 trace_label: str) -> list[str]:
    """One thunk. `dispatch_call` is the line(s) that actually do the
    out-call (psyq_NAME(cpu) or psx_dispatch_compiled(cpu, ADDR))."""
    lines: list[str] = []
    # Function signature.
    if not sig.params:
        param_str = "void"
    else:
        param_str = ", ".join(
            render_param_decl(i, ty, nm) for i, (ty, nm) in enumerate(sig.params)
        )
    lines.append(f"extern \"C\" {sig.return_type} {c_name}({param_str}) {{")
    lines.append("    CPUState* cpu = spyro_native_get_cpu();")
    lines.append("    cpu_scratch_t s; cpu_save(cpu, &s);")
    for i, (ty, nm) in enumerate(sig.params):
        if not nm:
            nm = f"arg{i}"
        lines.append(pack_arg_to_cpu(i, ty, nm))
    lines.append("    cpu->ra = 0xDEADBEEFu;")
    lines.append(f"    {dispatch_call}")
    capture, ret_line = render_return(sig.return_type)
    if capture:
        lines.append(capture)
    lines.append("    cpu_restore(cpu, &s);")
    if ret_line:
        lines.append(ret_line)
    lines.append("}")
    lines.append("")
    return lines


PROLOGUE_HEAD = """\
/* Auto-generated by tools/gen_thunks.py — do not edit.
 *
 * Outbound thunks: native C/C++ code in this binary calling into the
 * recompiled MIPS world (psx_dispatch_compiled) or into the PSYQ
 * compatibility layer (psyq_thunks.cpp). Each thunk packs host-ABI
 * args into cpu->aN, dispatches, and extracts cpu->v0 — saving and
 * restoring the scratch CPU slots so the caller's state survives.
 *
 * `s_active_cpu` is a single-fiber stash set by spyro_native_set_cpu
 * (called from the inbound dispatch hook in native_dispatch.c). Lift
 * to TLS if a second native entry-point fiber lands.
 */
#include "openpete_psx.h"

#include <sys/types.h>
#include <psx/libcd.h>  /* CdlLOC, CdlFILTER for PSYQ thunk types */

#include <stdint.h>

"""

PROLOGUE_TAIL = """\
extern "C" {
    int psx_dispatch_compiled(CPUState* cpu, uint32_t addr);
    /* PSYQ wrappers — defined in psyq_thunks.cpp. */
"""

CPU_HELPERS = """\
}

/* Single-fiber stash. spyro_native_set_cpu fires on every inbound
 * dispatch override so this always reflects the active CPUState*.
 * NULL (not nullptr) — Spyro's common.h #defines nullptr to ((void*)0),
 * which doesn't implicitly convert to CPUState* in C++. */
static CPUState* s_active_cpu = NULL;

extern "C" void spyro_native_set_cpu(CPUState* cpu) { s_active_cpu = cpu; }
extern "C" CPUState* spyro_native_get_cpu(void) { return s_active_cpu; }

/* PSYQ crt0 entry — runs once at the top of native main() to reproduce
 * the C-runtime init that GCC emits on the PSYQ target. */
extern "C" void spyro_native_run_psyq_main(void) {
    extern void psyq___main(CPUState* cpu);
    psyq___main(s_active_cpu);
}

/* Translate host pointer → PSX vaddr. Pointers passed in from native
 * decomp code always sit inside g_ram (link-aliased globals or chained
 * from one) or are NULL; anything outside is a bug. */
static uint32_t host_to_psx(const void* p) {
    if (!p) return 0u;
    uint8_t* base = openpete_psx_get_ram();
    intptr_t off = (const uint8_t*)p - base;
    if (off < 0 || off >= 2 * 1024 * 1024) return 0u;
    return 0x80000000u | (uint32_t)off;
}

/* Save / restore the eight PSYQ-ABI scratch slots around an outbound
 * call. The recompiled callee owns s0..s7/fp/gp; we don't touch those. */
typedef struct {
    uint32_t a0, a1, a2, a3, v0, v1, ra;
} cpu_scratch_t;

static void cpu_save(CPUState* cpu, cpu_scratch_t* s) {
    s->a0 = cpu->a0; s->a1 = cpu->a1; s->a2 = cpu->a2; s->a3 = cpu->a3;
    s->v0 = cpu->v0; s->v1 = cpu->v1; s->ra = cpu->ra;
}
static void cpu_restore(CPUState* cpu, const cpu_scratch_t* s) {
    cpu->a0 = s->a0; cpu->a1 = s->a1; cpu->a2 = s->a2; cpu->a3 = s->a3;
    cpu->v0 = s->v0; cpu->v1 = s->v1; cpu->ra = s->ra;
}

"""


def build_psyq_externs(psyq_entries: list[dict]) -> list[str]:
    out = []
    for e in psyq_entries:
        out.append(f"    void psyq_{e['psyq_name']}(CPUState* cpu);")
    return out


def main(argv: list[str]) -> int:
    if len(argv) not in (5, 6):
        print("usage: gen_thunks.py <manifest_dir> <out_cpp> "
              "<spyro_include> <psyq_include> [<rewritten_dir>]",
              file=sys.stderr)
        return 2
    manifest_dir = Path(argv[1])
    out_path = Path(argv[2])
    spyro_inc = Path(argv[3])
    psyq_inc = Path(argv[4])
    rewritten_dir = Path(argv[5]) if len(argv) == 6 else None

    native, sym_idx, _ = load_manifest(manifest_dir, rewritten_dir)
    recomp = native.get("outbound_recomp", [])
    psyq = native.get("outbound_psyq", [])
    if not recomp and not psyq:
        fail("native.toml has no [[outbound_recomp]] or [[outbound_psyq]]")

    spyro_sigs = load_signatures(spyro_inc)
    psyq_sigs = load_signatures(psyq_inc)

    # Resolve recomp addresses from symbols.toml when missing, validate
    # otherwise. Names without a header signature default to a void/void
    # fallback (handwritten-asm callees like Memset/Memcpy that aren't
    # declared in include/).
    by_addr = sym_idx["by_addr"]
    by_name = sym_idx["by_name"]
    for r in recomp:
        if "addr" not in r:
            sym = by_name.get(r["name"])
            if sym is None:
                fail(f"[[outbound_recomp]] {r['name']}: not in symbols.toml")
            r["addr"] = sym["addr"]
        else:
            sym = by_addr.get(r["addr"])
            if sym is None:
                fail(f"[[outbound_recomp]] {r['name']} @ 0x{r['addr']:08X} "
                     "not in symbols.toml")
            if sym["name"] != r["name"]:
                fail(f"[[outbound_recomp]] addr 0x{r['addr']:08X} maps to "
                     f"{sym['name']!r}, not {r['name']!r}")
        if r["name"] not in spyro_sigs:
            # Allow the header miss with a synthesized void(void) signature.
            spyro_sigs[r["name"]] = Signature(
                name=r["name"], return_type="void", params=[],
                source_file="<synthesized: no header>")

    for p in psyq:
        if p["psyq_name"] not in psyq_sigs:
            fail(f"[[outbound_psyq]] {p['psyq_name']}: no signature in "
                 f"{psyq_inc}")

    # Collect the set of spyro-1/include/ headers that declare the
    # thunked recomp callees — we need to #include them so the type
    # references in our extern "C" forward decls (Gamepad, etc.) resolve.
    spyro_inc_str = str(spyro_inc).rstrip("/")
    used_headers: list[str] = []
    seen = set()
    for r in recomp:
        sig = spyro_sigs.get(r["name"])
        if sig is None:
            continue
        src = sig.source_file
        # Strip the spyro_inc prefix to get a path relative to the
        # include dir (so `#include "gamepad.h"` works).
        if src.startswith(spyro_inc_str + "/"):
            rel = src[len(spyro_inc_str) + 1:]
        else:
            rel = src
        if rel not in seen and rel.endswith(".h"):
            seen.add(rel)
            used_headers.append(rel)
    used_headers.sort()

    parts: list[str] = [PROLOGUE_HEAD]
    if used_headers:
        # psyq_compat.h aliases RECT → RECT16 etc. Headers like hud.h
        # use the PSYQ name; without the alias, the compile breaks.
        parts.append('#include "decomp/psyq_compat.h"\n\n')
        parts.append("/* Spyro-internal type defs needed by the thunked signatures. */\n")
        parts.append("extern \"C\" {\n")
        for h in used_headers:
            parts.append(f'#include "{h}"\n')
        parts.append("}\n\n")
    parts.append(PROLOGUE_TAIL)
    parts.extend(line + "\n" for line in build_psyq_externs(psyq))
    parts.append(CPU_HELPERS)

    if recomp:
        parts.append("/* --- Outbound recomp callees ---------------------------- */\n\n")
        for r in recomp:
            sig = spyro_sigs[r["name"]]
            c_name = r.get("c_name", r["name"])
            call = f"psx_dispatch_compiled(cpu, 0x{r['addr']:08X}u);"
            parts.append("\n".join(render_thunk(
                r["name"], c_name, sig, call, r["name"])))

    if psyq:
        parts.append("/* --- Outbound PSYQ wrappers ----------------------------- */\n\n")
        for p in psyq:
            sig = psyq_sigs[p["psyq_name"]]
            c_name = p["c_name"]
            call = f"psyq_{p['psyq_name']}(cpu);"
            parts.append("\n".join(render_thunk(
                p["psyq_name"], c_name, sig, call, p["psyq_name"])))

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("".join(parts))
    print(f"emitted {len(recomp)} recomp + {len(psyq)} PSYQ thunks → {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
