#!/usr/bin/env python3
"""gen_code_docs.py — generate the codebase reference pages (markdown).

Writes docs/src/developer/reference/ for the documentation site
(docs/mkdocs.yml) from the function corpus of the documentation ratchet
(scripts/fences/doc_ratchet.py): the same libclang parse over the
linux-release compile database, the same scope (core/ and games/, outside
generated/, third_party/, build/ and the nested decomp checkouts), the
same canonical-site rule for which comment documents a function.

  index.md               the tree by directory, one line per file (the
                         first sentence of the file's leading comment)
  <dir>/index.md         one page per directory: its files, subdirectories
                         and function counts
  <dir>/<file>.md        one page per in-scope file: the leading comment,
                         then one entry per function whose canonical site
                         is the file (signature, brief, detail, parameter
                         table, return, source location, linkage), then the
                         functions defined in the file and documented at a
                         header declaration
  symbols/index.md       A-Z symbol index, one page per initial
  symbols/<letter>.md
  parse-failures.md      every corpus function with no rendered entry, and
                         every TU that parsed with errors

Every corpus key is either an entry or a parse-failure row; the run
refuses (exit 1) when the two counts do not sum to the corpus. The output
directory is deleted before the run. Output is deterministic: no
timestamps, sorted walks.

Usage: python3 tools/gen_code_docs.py [--out DIR]
The compile database is build/linux-release/compile_commands.json, or
OPENPETE_DOCS_DB. A missing database exits 1.
"""
