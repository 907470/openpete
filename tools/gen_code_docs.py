GEN_NOTE = ("<!-- GENERATED by tools/gen_code_docs.py from the source "
            "comments; edit the source, not this file. -->\n\n")

# --------------------------------------------------------------------------
# Comment text -> sections
# --------------------------------------------------------------------------
BLOCK_CMD = re.compile(r"^[@\\]([a-zA-Z]+)(\[[a-z, ]*\])?(?:\s+|$)(.*)$")
BRIEF = ("brief", "short")
RETURN = ("return", "returns", "result")
LIST_ITEM = re.compile(r"^(\s*)([-*+]|\d+[.)])\s+(.*)$")
CODE_SPAN = re.compile(r"`[^`\n]*`")
INLINE_CODE_CMD = re.compile(
    r"(?<![\w`])[@\\][pca]\s+([A-Za-z_][\w:]*(?:(?:\.|->)[A-Za-z_]\w*)*(?:\[\])?)")
MD_ESCAPE = re.compile(r"([\\*_\[\]#|])")


def comment_body(raw):
    """The comment's lines without the `/*` `*/` delimiters and the leading
    `*` or `//` prefix; relative indentation is kept."""
    lines = raw.split("\n")
    out = []
    if raw.lstrip().startswith("/*"):
        for i, ln in enumerate(lines):
            if i == 0:
                ln = re.sub(r"^\s*/\*+[!<]?", "", ln)
            if i == len(lines) - 1:
                ln = re.sub(r"\*+/.*$", "", ln)
            if i > 0:
                ln = re.sub(r"^\s*\*(?!/) ?", "", ln, count=1)
            out.append(ln.rstrip())
    else:
        for ln in lines:
            out.append(re.sub(r"^\s*//+[!<]? ?", "", ln).rstrip())
    while out and not out[0].strip():
        out.pop(0)
    while out and not out[-1].strip():
        out.pop()
    base = min((len(ln) - len(ln.lstrip()) for ln in out if ln.strip()),
               default=0)
    return [ln[base:] for ln in out]


def split_sections(body):
    """-> dict(brief, detail [lines], params [(name, dir, [lines])],
    returns [lines], others [(cmd, [lines])]). Text before any command
    joins the detail. A command's paragraph ends at a blank line or the next
    command; later text joins the detail."""
    sec = dict(brief=[], detail=[], params=[], returns=[], others=[])
    cur = sec["detail"]
    for ln in body:
        m = BLOCK_CMD.match(ln.strip())
        if m and m.group(1) not in ("p", "c", "a", "ref", "code", "endcode",
                                    "verbatim", "endverbatim"):
            cmd, arg, rest = m.group(1), m.group(2), m.group(3)
            if cmd in BRIEF:
                cur = sec["brief"]
                cur.append(rest)
            elif cmd == "param":
                pm = re.match(r"(\S+)\s*(.*)$", rest)
                name, text = (pm.group(1), pm.group(2)) if pm else ("", rest)
                entry = (name, (arg or "").strip("[] "), [text] if text else [])
                sec["params"].append(entry)
                cur = entry[2]
            elif cmd in RETURN:
                if sec["returns"]:
                    sec["returns"].append("")
                cur = sec["returns"]
                if rest:
                    cur.append(rest)
            else:
                entry = (cmd, [rest] if rest else [])
                sec["others"].append(entry)
                cur = entry[1]
            continue
        if not ln.strip():
            if cur is not sec["detail"]:
                cur = sec["detail"]
                if sec["detail"]:
                    cur.append("")
                continue
        cur.append(ln)
    return sec


def inline(text, table=False):
    """Markdown for comment text: backtick spans kept, `@p x` / `@c x` /
    `@a x` as code, `<` `>` `&` as entities, markdown metacharacters
    escaped so the words render as written."""
    text = INLINE_CODE_CMD.sub(lambda m: "`%s`" % m.group(1), text)
    out, pos = [], 0
    for m in CODE_SPAN.finditer(text):
        out.append(escape(text[pos:m.start()], table))
        span = m.group(0)
        out.append(span.replace("|", "\\|") if table else span)
        pos = m.end()
    out.append(escape(text[pos:], table))
    return "".join(out)


def escape(s, table):
    s = MD_ESCAPE.sub(r"\\\1", s)
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return s


def paragraphs(lines):
    """Split on blank lines, keeping @code/@verbatim regions whole."""
    paras, cur, fence = [], [], None
    for ln in lines:
        s = ln.strip()
        if fence:
            cur.append(ln)
            if re.match(r"^[@\\]end%s\b" % fence, s):
                fence = None
            continue
        m = re.match(r"^[@\\](code|verbatim)\b", s)
        if m:
            if cur:
                paras.append(cur)
            cur, fence = [ln], m.group(1)
            continue
        if not s:
            if cur:
                paras.append(cur)
            cur = []
            continue
        cur.append(ln)
    if cur:
        paras.append(cur)
    return paras


def render_block(lines):
    """Markdown for a run of comment lines: paragraphs, lists, and
    preformatted text (a @code/@verbatim region, or a paragraph whose every
    line is indented) as a fenced text block."""
    out = []
    for para in paragraphs(lines):
        first = para[0].strip()
        if re.match(r"^[@\\](code|verbatim)\b", first):
            inner = [ln for ln in para[1:]
                     if not re.match(r"^\s*[@\\]end(code|verbatim)\b", ln)]
            out.append(fenced("text", inner))
            continue
        if all(ln.startswith("  ") for ln in para):
            out.append(fenced("text", para))
            continue
        text, items = [], []
        for ln in para:
            m = LIST_ITEM.match(ln)
            if m:
                depth = len(m.group(1)) // 2
                marker = m.group(2) if m.group(2)[0].isdigit() else "-"
                items.append([depth, marker, m.group(3)])
            elif items:
                items[-1][2] += " " + ln.strip()
            else:
                text.append(ln.strip())
        if text:
            out.append("\n".join(inline(t) for t in text))
        if items:
            out.append("\n".join("%s%s %s" % ("    " * d, mk, inline(t))
                                 for d, mk, t in items))
    return "\n\n".join(out)


def fenced(lang, lines):
    base = min((len(ln) - len(ln.lstrip()) for ln in lines if ln.strip()),
               default=0)
    body = "\n".join(ln[base:] for ln in lines).strip("\n")
    fence = "```"
    while fence in body:
        fence += "`"
    return "%s%s\n%s\n%s" % (fence, lang, body, fence)


def first_sentence(lines):
    text = " ".join(ln.strip() for ln in lines if ln.strip())
    text = re.sub(r"^[@\\](file|brief)\b\S*\s*", "", text)
    bare = dr.ABBREVIATIONS.sub(lambda m: m.group(0).replace(".", "\0"), text)
    bare = dr.CODE_SPAN.sub(lambda m: m.group(0).replace(".", "\0"), bare)
    m = dr.TERMINATOR.search(bare)
    return text[:m.end()] if m else text


# --------------------------------------------------------------------------
# Source reads
# --------------------------------------------------------------------------
class Sources:
    def __init__(self, root):
        self.root = root
        self.cache = {}

    def get(self, rel):
        if rel not in self.cache:
            self.cache[rel] = dr.Source(os.path.join(self.root, rel))
        return self.cache[rel]


def leading_comment(src):
    """The body of the first comment block when only blank lines, `#pragma
    once` or an include guard precede it; else None."""
    n = 1
    while n <= len(src.lines):
        s = src.line(n).strip()
        if not s or re.match(r"#\s*(pragma\s+once|ifndef|define)\b", s):
            n += 1
            continue
        blk = src.blocks.get(n)
        if blk and blk[0] == n:
            return comment_body(src.text(blk[0], blk[1]))
        return None
    return None


def signature(src, first, last, is_def):
    """The declaration text: a definition up to its body's `{` at paren
    depth 0, a declaration up to its `;`."""
    text = src.text(first, last)
    depth, cut = 0, len(text)
    for i, ch in enumerate(text):
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif depth == 0 and ((is_def and ch == "{") or (not is_def and ch == ";")):
            cut = i + (0 if is_def else 1)
            break
    lines = text[:cut].rstrip().split("\n")
    base = min((len(ln) - len(ln.lstrip()) for ln in lines if ln.strip()),
               default=0)
    return "\n".join(ln[base:].rstrip() for ln in lines).strip()


# --------------------------------------------------------------------------
# Anchors: the toc extension's slugify and unique(), so each function's
# heading id is known when a link to it is written.
# --------------------------------------------------------------------------
def slugify(value):
    value = re.sub(r"[^\w\s-]", "", value).strip().lower()
    return re.sub(r"[-\s]+", "-", value)


class Slugs:
    def __init__(self):
        self.used = set()

    def take(self, text):
        base = slug = slugify(text)
        n = 0
        while slug in self.used:
            n += 1
            slug = "%s_%d" % (base, n)
        self.used.add(slug)
        return slug


# --------------------------------------------------------------------------
# Model
# --------------------------------------------------------------------------
class Entry:
    """One rendered function. page: the canonical file (where its comment
    lives); defined: the definition file."""

    def __init__(self, key, fx, sec, sig, page):
        self.key, self.fx, self.sec, self.sig, self.page = key, fx, sec, sig, page
        self.name = fx["name"]
        self.label = key.rsplit(":", 1)[1]
        self.slug = None

    def linkage(self):
        if self.fx["linkage"] == "EXTERNAL":
            return None
        if lib.is_header(self.fx["file"]):
            return "static inline" if re.search(r"\binline\b", self.sig) else "static"
        if re.search(r"\bstatic\b", self.sig):
            return "static"
        return "internal linkage (%s)" % self.fx["linkage"].lower()


def build_model(root, corpus):
    srcs = Sources(root)
    entries, failures = [], []
    for key in sorted(corpus.facts):
        fx = corpus.facts[key]
        form = fx["form"]
        if form == "MACRO":
            failures.append((key, fx, "defined by a macro expansion; no "
                             "declaration text to document"))
            continue
        if not fx.get("comment") or len(fx.get("ranges", [])) != 1:
            failures.append((key, fx, "form `%s`: no single doxygen comment "
                             "at the canonical site" % form))
            continue
        cfile, cfirst, clast = fx["comment"]
        sec = split_sections(comment_body(srcs.get(cfile).text(cfirst, clast)))
        if not "".join(sec["brief"]).strip():
            failures.append((key, fx, "form `%s`: the comment carries no "
                             "`@brief` text" % form))
            continue
        canon_file, canon_start = fx["canonical"]
        if fx["canonical_is_header"]:
            ext = next(e for e in fx["extents"][1:] if e[0] == canon_file)
            sig = signature(srcs.get(canon_file), ext[1], ext[2], False)
        else:
            sig = signature(srcs.get(fx["file"]), fx["start"], fx["end"], True)
        e = Entry(key, fx, sec, sig, canon_file)
        e.form = form
        entries.append(e)
    return srcs, entries, failures


def scope_files(root):
    fence = dr.FENCE
    out = git_ls(root, fence.root_dirs())
    return sorted(f for f in out if fence.in_scope(f))


def git_ls(root, dirs):
    return [f for f in lib.git(root, "ls-files", "--", *dirs).stdout.split("\n") if f]


# --------------------------------------------------------------------------
# Pages
# --------------------------------------------------------------------------
def page_of(path):
    return path + ".md"


def rel_link(from_page, to_page):
    return os.path.relpath(to_page, os.path.dirname(from_page) or ".")


def render_entry(e, cur_page, lang):
    fx = e.fx
    out = ["### %s" % e.label.replace("#", " ")]
    out.append("```%s\n%s\n```" % (lang, e.sig))
    out.append(render_block(e.sec["brief"]))
    if any(ln.strip() for ln in e.sec["detail"]):
        out.append(render_block(e.sec["detail"]))
    if e.sec["params"]:
        rows = ["| Parameter | Description |", "| --- | --- |"]
        for name, direction, text in e.sec["params"]:
            label = "`%s`" % name + (" [%s]" % direction if direction else "")
            rows.append("| %s | %s |" % (label, inline(
                " ".join(t.strip() for t in text if t.strip()), table=True)))
        out.append("\n".join(rows))
    if any(ln.strip() for ln in e.sec["returns"]):
        out.append("Returns: " + render_block(e.sec["returns"]))
    for cmd, text in e.sec["others"]:
        out.append("`@%s` %s" % (cmd, render_block(text)))
    loc = ["Source: `%s:%d` (definition)" % (fx["file"], fx["start"])]
    if fx["canonical_is_header"]:
        loc.append("`%s:%d` (declaration)" % (fx["canonical"][0],
                                              fx["canonical_line"]))
    line = ", ".join(loc)
    link = e.linkage()
    if link:
        line += ". Linkage: %s" % link
    out.append(line + ".")
    if e.form != "meets":
        out.append("Ratchet form: `%s`." % e.form)
    return "\n\n".join(out)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(GEN_NOTE + text.rstrip("\n") + "\n")


def lang_of(path):
    return "cpp" if path.endswith((".cpp", ".cc", ".cxx", ".hpp", ".hh")) else "c"


def generate(root, out_dir, corpus):
    srcs, entries, failures = build_model(root, corpus)
    files = set(scope_files(root))
    by_page = defaultdict(list)
    defined_elsewhere = defaultdict(list)
    entries_by_def = defaultdict(list)
    for e in entries:
        entries_by_def[e.fx["file"]].append(e)
        by_page[e.page].append(e)
        files.add(e.page)
        if e.fx["file"] != e.page:
            defined_elsewhere[e.fx["file"]].append(e)
            files.add(e.fx["file"])
    files = sorted(files)
    for page in by_page:
        by_page[page].sort(key=lambda e: (e.fx["canonical_line"]
                                          if e.fx["canonical_is_header"]
                                          else e.fx["start"], e.key))
    summary = {}
    pages = 0
    pending_pages = {}

    # File pages.
    for f in files:
        src = srcs.get(f)
        lead = leading_comment(src)
        summary[f] = first_sentence(lead) if lead else ""
        page = page_of(f)
        parts = ["# %s" % f]
        if lead:
            parts.append(render_block(lead))
        slugs = Slugs()
        slugs.take(f)
        own = by_page.get(f, [])
        if own:
            parts.append("## Functions")
            slugs.take("Functions")
            for e in own:
                e.slug = slugs.take(e.label.replace("#", " "))
        else:
            parts.append("No function has its documenting comment in this file.")
        if defined_elsewhere.get(f):
            slugs.take("Defined here, documented at the declaration")
        for e in own:
            parts.append(render_entry(e, page, lang_of(f)))
        ndef = sum(1 for e in entries_by_def.get(f, ()))
        summary[f] = (summary[f], len(own), ndef)
        e_list = defined_elsewhere.get(f)
        if e_list:
            rows = ["## Defined here, documented at the declaration", "",
                    "| Function | Line | Declaration |", "| --- | --- | --- |"]
            for e in sorted(e_list, key=lambda e: e.fx["start"]):
                rows.append("| [`%s`](%s#%s) | %d | `%s:%d` |" % (
                    e.name, rel_link(page, page_of(e.page)), "{slug:%s}" % e.key,
                    e.fx["start"], e.page, e.fx["canonical_line"]))
            parts.append("\n".join(rows))
        pending_pages[page] = "\n\n".join(parts)
        pages += 1
    slug_of = {e.key: e.slug for e in entries}
    for page, text in pending_pages.items():
        text = re.sub(r"\{slug:([^}]+)\}", lambda m: slug_of[m.group(1)], text)
        write(os.path.join(out_dir, page), text)

    # Directory pages.
    dirs = defaultdict(lambda: ([], set()))
    for f in files:
        d = os.path.dirname(f)
        dirs[d][0].append(f)
        while d:
            parent = os.path.dirname(d)
            dirs[parent][1].add(d)
            d = parent
    count_under = defaultdict(int)
    for f in files:
        d = os.path.dirname(f)
        while True:
            count_under[d] += summary[f][2]
            if not d:
                break
            d = os.path.dirname(d)
    for d in sorted(dirs):
        if not d:
            continue
        page = os.path.join(d, "index.md")
        own_files, subdirs = dirs[d]
        parts = ["# %s/" % d,
                 "%d functions defined under this directory. Documented: entries "
                 "whose comment is in the file; defined: definitions in the "
                 "file." % count_under[d]]
        if subdirs:
            rows = ["## Directories", "", "| Directory | Functions |", "| --- | --- |"]
            for s in sorted(subdirs):
                rows.append("| [%s/](%s) | %d |" % (
                    os.path.basename(s), rel_link(page, os.path.join(s, "index.md")),
                    count_under[s]))
            parts.append("\n".join(rows))
        if own_files:
            rows = ["## Files", "", "| File | Documented | Defined | Summary |",
                    "| --- | --- | --- | --- |"]
            for f in sorted(own_files):
                rows.append("| [%s](%s) | %d | %d | %s |" % (
                    os.path.basename(f), rel_link(page, page_of(f)),
                    summary[f][1], summary[f][2],
                    inline(summary[f][0], table=True)))
            parts.append("\n".join(rows))
        write(os.path.join(out_dir, page), "\n\n".join(parts))
        pages += 1

    # Symbol index.
    buckets = defaultdict(list)
    for e in entries:
        c = e.name[0].lower()
        buckets[c if "a" <= c <= "z" else "other"].append(e)
    letters = sorted(buckets, key=lambda c: (c == "other", c))
    sym_rows = []
    for c in letters:
        page = "symbols/%s.md" % c
        rows = ["# Symbols: %s" % (c.upper() if c != "other" else "other initials"),
                "", "| Function | File | Summary |", "| --- | --- | --- |"]
        for e in sorted(buckets[c], key=lambda e: (e.name.lower(), e.name, e.key)):
            rows.append("| [`%s`](%s#%s) | `%s` | %s |" % (
                e.name, rel_link(page, page_of(e.page)), e.slug, e.page,
                inline(" ".join(e.sec["brief"]).strip(), table=True)))
        write(os.path.join(out_dir, page), "\n".join(rows))
        pages += 1
        sym_rows.append("| [%s](%s.md) | %d |" % (
            c.upper() if c != "other" else "other", c, len(buckets[c])))
    write(os.path.join(out_dir, "symbols/index.md"), "\n".join(
        ["# Symbols", "", "Functions by the initial of their name.", "",
         "| Initial | Functions |", "| --- | --- |"] + sym_rows))
    pages += 1

    # Parse failures.
    parts = ["# Parse failures",
             "Corpus functions with no rendered entry: %d. TUs parsed with "
             "errors: %d." % (len(failures), len(corpus.errors))]
    if failures:
        rows = ["## Functions", "", "| Function | Definition | Reason |",
                "| --- | --- | --- |"]
        for key, fx, why in failures:
            rows.append("| `%s` | `%s:%d` | %s |" % (
                key.rsplit(":", 1)[1], fx["file"], fx["start"], why))
        parts.append("\n".join(rows))
    if corpus.errors:
        rows = ["## TUs parsed with errors",
                "",
                "A missing generated header (a build step not yet run) or a "
                "compile error; functions of these TUs are still parsed.",
                "", "| TU | First error |", "| --- | --- |"]
        for tu in sorted(corpus.errors):
            f, ln, msg = corpus.errors[tu][0]
            rows.append("| `%s` | `%s:%s`: %s |" % (tu, f, ln,
                                                    inline(msg, table=True)))
        parts.append("\n".join(rows))
    parts.append("## Outside the corpus\n\nDefinitions the linux-release parse "
                 "does not see (`WINDOWS_ONLY` in "
                 "`scripts/fences/doc_ratchet.py`):\n\n" +
                 "\n".join("- `%s`" % k for k in dr.WINDOWS_ONLY))
    write(os.path.join(out_dir, "parse-failures.md"), "\n\n".join(parts))
    pages += 1

    # Index.
    top = defaultdict(int)
    for e in entries:
        top[e.fx["file"].split("/")[0]] += 1
    parts = ["# Codebase reference",
             "Every function of `core/` and `games/` (outside `generated/`, "
             "`third_party/` and the decomp checkouts) with its doxygen "
             "comment, as the linux-release compile database parses it. "
             "An entry sits on the page of the file that holds its comment: "
             "the project-header declaration when one exists, else the "
             "definition.",
             "The count after each file is documented/defined: entries whose "
             "comment is in the file, and definitions in the file.",
             "%d functions in %d files. [Symbol index](symbols/index.md). "
             "[Parse failures](parse-failures.md): %d." % (
                 len(entries), len(files), len(failures))]
    for d in sorted(dirs):
        own_files = dirs[d][0]
        if not d or not own_files:
            continue
        lines = ["## [%s/](%s)" % (d, os.path.join(d, "index.md")), ""]
        for f in sorted(own_files):
            s = summary[f][0]
            lines.append("- [%s](%s) (%d/%d)%s" % (
                os.path.basename(f), page_of(f), summary[f][1], summary[f][2],
                ": " + inline(s) if s else ""))
        parts.append("\n".join(lines))
    write(os.path.join(out_dir, "index.md"), "\n\n".join(parts))
    pages += 1
    return entries, failures, files, pages, top



def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=OUT_DEFAULT,
                    help="output directory, relative to the repo root")
    args = ap.parse_args()
    root = REPO
    out_dir = os.path.join(root, args.out)
    t0 = time.time()
    db_path, db = lib.load_db(root, dr.FENCE)
    if db is None:
        sys.stderr.write("gen_code_docs: no compile database at %s; configure "
                         "linux-release first\n" % db_path)
        return 1
    try:
        _, _, _, corpus, _, _, _ = dr.corpus_inputs(root)
    except lib.Refusal as exc:
        sys.stderr.write("gen_code_docs: %s\n" % exc)
        return 1
    shutil.rmtree(out_dir, ignore_errors=True)
    entries, failures, files, pages, top = generate(root, out_dir, corpus)
    total = len(corpus.facts)
    sys.stderr.write(
        "gen_code_docs: %d corpus functions = %d entries + %d parse failures; "
        "%d files, %d pages (%s); %.1f s -> %s\n" % (
            total, len(entries), len(failures), len(files), pages,
            ", ".join("%s %d" % kv for kv in sorted(top.items())),
            time.time() - t0, args.out))
    if len(entries) + len(failures) != total:
        sys.stderr.write("gen_code_docs: REFUSED: entries + failures != corpus\n")
        return 1
    if not entries:
        sys.stderr.write("gen_code_docs: VACUOUS: zero entries\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
