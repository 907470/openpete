#!/usr/bin/env python3
"""Generate the OpenPete icon (original art, authored here - no game bytes).

Emits a C file defining the mark as an openpete_game_icon_t (named by
--c-name; the window icon before a game is picked and whenever the disc's
save header cannot be read, core/include/openpete_save_icon.h), a Windows
.ico (16, 32, 48 and 256 px entries scaled nearest-neighbour from the mark;
the executable's Win32 resource), and/or a PNG for the Linux .desktop /
AppImage icon.

The design is a 16x16 pixel mark: dark-purple rounded tile, two orange
"horn" triangles and eyes - abstract, geometric, original.
"""

import argparse
import struct
import sys
import zlib
from pathlib import Path

# 16x16 grid. Legend: . transparent, P purple tile, D darker purple edge,
# O orange, W warm highlight.
GRID = [
    "..DD........DD..",
    ".DOOD......DOOD.",
    ".DOOOD....DOOOD.",
    "..DOOODDDDOOOD..",
    "..DPPPPPPPPPPD..",
    ".DPPPPPPPPPPPPD.",
    ".DPPWPPPPPPWPPD.",
    "DPPPWWPPPPWWPPPD",
    "DPPPWWPPPPWWPPPD",
    "DPPPPPPPPPPPPPPD",
    "DPPPPPPPPPPPPPPD",
    ".DPPPOPPPPOPPPD.",
    ".DPPPOOOOOOPPPD.",
    "..DPPPPPPPPPPD..",
    "...DDPPPPPPDD...",
    ".....DDDDDD.....",
]

PALETTE = {
    ".": (0, 0, 0, 0),
    "P": (94, 60, 158, 255),     # purple tile
    "D": (54, 32, 96, 255),      # dark edge
    "O": (240, 138, 30, 255),    # orange
    "W": (255, 214, 120, 255),   # warm highlight (eyes)
}

W = H = 16


def pixels(grid):
    out = []
    for row in grid:
        assert len(row) == W
        for ch in row:
            out.append(PALETTE[ch])
    assert len(out) == W * H
    return out


def write_c(path: Path, px, name: str):
    with open(path, "w") as f:
        f.write("/* AUTO-GENERATED by tools/gen_dist_icon.py - original\n"
                " * distribution icon (no game bytes). Do not edit. */\n"
                "#include \"openpete_game_runtime.h\"\n\n"
                f"static const uint8_t k_rgba[{W*H*4}] = {{\n")
        vals = []
        for (r, g, b, a) in px:
            vals += [r, g, b, a]
        for i in range(0, len(vals), 16):
            f.write("    " + ", ".join(str(v) for v in vals[i:i+16]) + ",\n")
        f.write("};\n\n"
                f"const openpete_game_icon_t {name} = {{ k_rgba, {W}, {H} }};\n")


ICO_SIZES = (16, 32, 48, 256)


def scaled(px, size: int):
    """The mark scaled nearest-neighbour to size x size (an integer multiple
    of the 16px grid), as a row-major RGBA list."""
    k = size // W
    return [px[(y // k) * W + (x // k)] for y in range(size) for x in range(size)]


def bmp_entry(px, size: int) -> bytes:
    """One 32-bit BMP-format .ico image: the header, the bottom-up BGRA rows
    and an all-zero AND mask (the alpha channel governs)."""
    xor_rows = bytearray()
    for y in range(size - 1, -1, -1):
        for x in range(size):
            r, g, b, a = px[y * size + x]
            xor_rows += struct.pack("<BBBB", b, g, r, a)
    and_rows = b"\x00" * (((size + 31) // 32) * 4 * size)
    bmp = struct.pack("<IiiHHIIiiII", 40, size, size * 2, 1, 32, 0,
                      len(xor_rows) + len(and_rows), 0, 0, 0, 0)
    return bmp + bytes(xor_rows) + and_rows


def write_ico(path: Path, px):
    # 16-48 px as BMP entries; 256 px as a PNG entry, the form Windows
    # (Vista and later) reads for that size.
    images = []
    for size in ICO_SIZES:
        big = scaled(px, size)
        images.append(png_bytes(big, size, size) if size == 256
                      else bmp_entry(big, size))
    hdr = struct.pack("<HHH", 0, 1, len(images))
    offset = 6 + 16 * len(images)
    entries = b""
    for size, img in zip(ICO_SIZES, images):
        dim = 0 if size == 256 else size    # 0 encodes 256
        entries += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32,
                               len(img), offset)
        offset += len(img)
    path.write_bytes(hdr + entries + b"".join(images))


def png_bytes(px, w: int, h: int) -> bytes:
    """An 8-bit RGBA PNG of the row-major w x h image px."""
    raw = bytearray()
    for y in range(h):
        raw.append(0)                        # filter type 0 (None)
        for x in range(w):
            raw += bytes(px[y * w + x])
    def chunk(tag, data):
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)   # 8-bit RGBA
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", ihdr)
            + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
            + chunk(b"IEND", b""))


def write_png(path: Path, px, scale: int):
    """Nearest-neighbour upscale of the 16x16 mark to a real icon size.

    Freedesktop icon lookup wants 256x256 and AppImage thumbnailers scale
    whatever they find, so shipping the 16x16 grid directly would be
    resampled to mush by someone else's filter. Integer nearest-neighbour
    keeps the pixel mark crisp at any size the desktop asks for.
    """
    size = W * scale
    path.write_bytes(png_bytes(scaled(px, size), size, size))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--c", type=Path)
    ap.add_argument("--c-name",
                    help="the openpete_game_icon_t the --c file defines")
    ap.add_argument("--ico", type=Path)
    ap.add_argument("--png", type=Path)
    ap.add_argument("--png-size", type=int, default=256,
                    help="PNG edge in pixels; rounded down to a whole "
                         "multiple of the 16px mark")
    args = ap.parse_args()
    px = pixels(GRID)
    if args.c and not args.c_name:
        ap.error("--c needs --c-name")
    if args.c:
        write_c(args.c, px, args.c_name)
    if args.ico:
        write_ico(args.ico, px)
    if args.png:
        scale = max(1, args.png_size // W)
        write_png(args.png, px, scale)
    if not args.c and not args.ico and not args.png:
        print("nothing to do (--c/--ico/--png)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
