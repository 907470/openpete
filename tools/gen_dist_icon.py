#!/usr/bin/env python3
"""Generate the ROM-free distribution icon (original art, authored here —
no game bytes; distribution D3). Emits the same artifacts as
mcs_icon_to_ico.py: a C file with openpete_spyro1_icon_{w,h,rgba} for
SDL_SetWindowIcon and/or a Windows .ico (32-bit BMP-format entry).

The design is a 16x16 pixel mark: dark-purple rounded tile, two orange
"horn" triangles and eyes — abstract, geometric, original.
"""

import argparse
import struct
import sys
from pathlib import Path

# 16x16 grid. Legend: . transparent, P purple tile, D darker purple edge,
# O orange, W warm highlight.
GRID = [
    "..DD........DD..",
    ".DOOD......DOOD.",
    ".DOOOD....DOOOD.",
    "..DOOODDDDOOOD..",
    "..DPPPPPPPPPPD..",
    ".DPPPPPPPPPPPPD.",
    ".DPPWPPPPPPWPPD.",
    "DPPPWWPPPPWWPPPD",
    "DPPPWWPPPPWWPPPD",
    "DPPPPPPPPPPPPPPD",
    "DPPPPPPPPPPPPPPD",
    ".DPPPOPPPPOPPPD.",
    ".DPPPOOOOOOPPPD.",
    "..DPPPPPPPPPPD..",
    "...DDPPPPPPDD...",
    ".....DDDDDD.....",
]

PALETTE = {
    ".": (0, 0, 0, 0),
    "P": (94, 60, 158, 255),     # purple tile
    "D": (54, 32, 96, 255),      # dark edge
    "O": (240, 138, 30, 255),    # orange
    "W": (255, 214, 120, 255),   # warm highlight (eyes)
}

W = H = 16


def pixels():
    out = []
    for row in GRID:
        assert len(row) == W
        for ch in row:
            out.append(PALETTE[ch])
    assert len(out) == W * H
    return out


def write_c(path: Path, px):
    with open(path, "w") as f:
        f.write("/* AUTO-GENERATED by tools/gen_dist_icon.py — original\n"
                " * distribution icon (no game bytes). Do not edit. */\n"
                "#include <stdint.h>\n\n"
                f"const int openpete_spyro1_icon_w = {W};\n"
                f"const int openpete_spyro1_icon_h = {H};\n"
                f"const uint8_t openpete_spyro1_icon_rgba[{W*H*4}] = {{\n")
        vals = []
        for (r, g, b, a) in px:
            vals += [r, g, b, a]
        for i in range(0, len(vals), 16):
            f.write("    " + ", ".join(str(v) for v in vals[i:i+16]) + ",\n")
        f.write("};\n")


def write_ico(path: Path, px):
    # Single 16x16 32-bit BMP-format entry.
    xor_rows = b""
    for y in range(H - 1, -1, -1):          # bottom-up
        for x in range(W):
            r, g, b, a = px[y * W + x]
            xor_rows += struct.pack("<BBBB", b, g, r, a)
    and_stride = ((W + 31) // 32) * 4
    and_rows = b"\x00" * (and_stride * H)   # alpha channel governs
    bmp = struct.pack("<IiiHHIIiiII", 40, W, H * 2, 1, 32, 0,
                      len(xor_rows) + len(and_rows), 0, 0, 0, 0)
    img = bmp + xor_rows + and_rows
    hdr = struct.pack("<HHH", 0, 1, 1)
    entry = struct.pack("<BBBBHHII", W, H, 0, 0, 1, 32, len(img), 22)
    path.write_bytes(hdr + entry + img)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--c", type=Path)
    ap.add_argument("--ico", type=Path)
    args = ap.parse_args()
    px = pixels()
    if args.c:
        write_c(args.c, px)
    if args.ico:
        write_ico(args.ico, px)
    if not args.c and not args.ico:
        print("nothing to do (--c/--ico)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
