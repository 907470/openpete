#!/usr/bin/env python3
"""Generate the ROM-free distribution icon (original art, authored here —
no game bytes; distribution D3). Emits the same artifacts as
mcs_icon_to_ico.py: a C file with openpete_game_icon_{w,h,rgba} for
SDL_SetWindowIcon, a Windows .ico (32-bit BMP-format entry), and/or a PNG
for the Linux .desktop / AppImage icon.

The design is a 16x16 pixel mark: dark-purple rounded tile, two orange
"horn" triangles and eyes — abstract, geometric, original.
"""

import argparse
import struct
import sys
import zlib
from pathlib import Path

# 16x16 grid. Legend: . transparent, P purple tile, D darker purple edge,
# O orange, W warm highlight.
GRID = [
    "..DD........DD..",
    ".DOOD......DOOD.",
    ".DOOOD....DOOOD.",
    "..DOOODDDDOOOD..",
    "..DPPPPPPPPPPD..",
    ".DPPPPPPPPPPPPD.",
    ".DPPWPPPPPPWPPD.",
    "DPPPWWPPPPWWPPPD",
    "DPPPWWPPPPWWPPPD",
    "DPPPPPPPPPPPPPPD",
    "DPPPPPPPPPPPPPPD",
    ".DPPPOPPPPOPPPD.",
    ".DPPPOOOOOOPPPD.",
    "..DPPPPPPPPPPD..",
    "...DDPPPPPPDD...",
    ".....DDDDDD.....",
]

PALETTE = {
    ".": (0, 0, 0, 0),
    "P": (94, 60, 158, 255),     # purple tile
    "D": (54, 32, 96, 255),      # dark edge
    "O": (240, 138, 30, 255),    # orange
    "W": (255, 214, 120, 255),   # warm highlight (eyes)
}

W = H = 16

# The mark per game. Every game currently ships the one mark above; a game
# gains its own by naming a different grid here.
GAME_GRIDS = {
    "spyro-1": GRID,
    "spyro-2": GRID,
    "spyro-3": GRID,
}


def pixels(grid):
    out = []
    for row in grid:
        assert len(row) == W
        for ch in row:
            out.append(PALETTE[ch])
    assert len(out) == W * H
    return out


def write_c(path: Path, px):
    with open(path, "w") as f:
        f.write("/* AUTO-GENERATED by tools/gen_dist_icon.py — original\n"
                " * distribution icon (no game bytes). Do not edit. */\n"
                "#include <stdint.h>\n\n"
                f"const int openpete_game_icon_w = {W};\n"
                f"const int openpete_game_icon_h = {H};\n"
                f"const uint8_t openpete_game_icon_rgba[{W*H*4}] = {{\n")
        vals = []
        for (r, g, b, a) in px:
            vals += [r, g, b, a]
        for i in range(0, len(vals), 16):
            f.write("    " + ", ".join(str(v) for v in vals[i:i+16]) + ",\n")
        f.write("};\n")


def write_ico(path: Path, px):
    # Single 16x16 32-bit BMP-format entry.
    xor_rows = b""
    for y in range(H - 1, -1, -1):          # bottom-up
        for x in range(W):
            r, g, b, a = px[y * W + x]
            xor_rows += struct.pack("<BBBB", b, g, r, a)
    and_stride = ((W + 31) // 32) * 4
    and_rows = b"\x00" * (and_stride * H)   # alpha channel governs
    bmp = struct.pack("<IiiHHIIiiII", 40, W, H * 2, 1, 32, 0,
                      len(xor_rows) + len(and_rows), 0, 0, 0, 0)
    img = bmp + xor_rows + and_rows
    hdr = struct.pack("<HHH", 0, 1, 1)
    entry = struct.pack("<BBBBHHII", W, H, 0, 0, 1, 32, len(img), 22)
    path.write_bytes(hdr + entry + img)


def write_png(path: Path, px, scale: int):
    """Nearest-neighbour upscale of the 16x16 mark to a real icon size.

    Freedesktop icon lookup wants 256x256 and AppImage thumbnailers scale
    whatever they find, so shipping the 16x16 grid directly would be
    resampled to mush by someone else's filter. Integer nearest-neighbour
    keeps the pixel mark crisp at any size the desktop asks for.
    """
    w, h = W * scale, H * scale
    raw = bytearray()
    for y in range(h):
        raw.append(0)                        # filter type 0 (None)
        row = px[(y // scale) * W:(y // scale) * W + W]
        for x in range(w):
            raw += bytes(row[x // scale])
    def chunk(tag, data):
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)   # 8-bit RGBA
    path.write_bytes(b"\x89PNG\r\n\x1a\n"
                     + chunk(b"IHDR", ihdr)
                     + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
                     + chunk(b"IEND", b""))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--c", type=Path)
    ap.add_argument("--ico", type=Path)
    ap.add_argument("--png", type=Path)
    ap.add_argument("--game", choices=sorted(GAME_GRIDS), default="spyro-1",
                    help="which game's mark to emit")
    ap.add_argument("--png-size", type=int, default=256,
                    help="PNG edge in pixels; rounded down to a whole "
                         "multiple of the 16px mark")
    args = ap.parse_args()
    px = pixels(GAME_GRIDS[args.game])
    if args.c:
        write_c(args.c, px)
    if args.ico:
        write_ico(args.ico, px)
    if args.png:
        scale = max(1, args.png_size // W)
        write_png(args.png, px, scale)
    if not args.c and not args.ico and not args.png:
        print("nothing to do (--c/--ico/--png)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
