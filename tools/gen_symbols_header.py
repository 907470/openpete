#!/usr/bin/env python3
"""gen_symbols_header.py — emit <tag>_symbols.gen.h from a game's curated symbol
alias manifest, validated against the authoritative address manifest.

Inputs:
  --symbols   manifest/<tag>_symbols.toml    (curated ALIAS -> addr, hand-maintained)
  --globals   manifest/globals.toml          (authoritative, auto-gen from psx.map)
  --functions manifest/symbols.toml          (authoritative functions, from psx.map)
Output:
  --out       <gen>/<tag>_symbols.gen.h

Each curated entry is one of:
  * direct global   { name, addr, note }              -> addr must be a globals.toml start
  * function        { name, addr, kind="function" }   -> addr must be a symbols.toml [[function]] start
  * struct interior { name, base, offset, note }      -> base must be a globals.toml start; addr = base + offset

The build FAILS if any addr/base is not a symbol start in the manifest, so a
psx.map rebuild that moves a symbol surfaces here instead of silently going
stale. (Addresses don't shift in a byte-identical decomp; names/kinds do —
hence the drift check + the upstream-rename WARNING below.)
"""
import argparse
import sys
from pathlib import Path

try:
    import tomllib  # py 3.11+
except ImportError:
    import tomli as tomllib  # type: ignore


def coerce_int(v: object) -> int:
    return v if isinstance(v, int) else int(v, 0)  # type: ignore[arg-type]


def load_addr_names(path: Path, table: str) -> dict:
    """addr -> name for every [[<table>]] entry (e.g. table='global')."""
    with open(path, "rb") as f:
        data = tomllib.load(f)
    out = {}
    for e in data.get(table, []):
        out[coerce_int(e["addr"])] = e["name"]
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--symbols", required=True)
    ap.add_argument("--globals", required=True)
    ap.add_argument("--functions", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    with open(args.symbols, "rb") as f:
        syms = tomllib.load(f).get("symbol", [])
    if not syms:
        print(f"error: no [[symbol]] entries in {args.symbols}", file=sys.stderr)
        return 1

    g_names = load_addr_names(Path(args.globals), "global")
    f_names = load_addr_names(Path(args.functions), "function")

    errors: list[str] = []
    warnings: list[str] = []
    seen_names: set[str] = set()
    rows: list[tuple[int, str, str]] = []  # (addr, name, comment)

    for s in syms:
        name = s.get("name")
        if not name:
            errors.append(f"entry missing 'name': {s}")
            continue
        if name in seen_names:
            errors.append(f"{name}: duplicate alias")
            continue
        seen_names.add(name)
        note = s.get("note", "")
        kind = s.get("kind", "global")

        if "base" in s:  # struct interior
            base = coerce_int(s["base"])
            offset = coerce_int(s.get("offset", 0))
            if base not in g_names:
                errors.append(f"{name}: base 0x{base:08X} is not a globals.toml symbol start")
                continue
            addr = base + offset
            mname = f"{g_names[base]}+0x{offset:X}"
        elif kind == "function":
            addr = coerce_int(s["addr"])
            if addr not in f_names:
                errors.append(f"{name}: addr 0x{addr:08X} is not a symbols.toml function start")
                continue
            mname = f_names[addr]
        else:  # direct global
            addr = coerce_int(s["addr"])
            if addr not in g_names:
                errors.append(f"{name}: addr 0x{addr:08X} is not a globals.toml symbol start")
                continue
            mname = g_names[addr]
            # Upstream-rename nudge: a recomp D_<addr> that has since gained a
            # real decomp name upstream should eventually adopt it. Non-fatal.
            if not mname.startswith("D_") and name.startswith("D_"):
                warnings.append(f"{name} (0x{addr:08X}): manifest now names this '{mname}' "
                                f"— consider adopting it")

        comment = f"{mname}" + (f" — {note}" if note else "")
        rows.append((addr, name, comment))

    if errors:
        for e in errors:
            print(f"gen_symbols_header: ERROR: {e}", file=sys.stderr)
        return 1
    for w in warnings:
        print(f"gen_symbols_header: warning: {w}", file=sys.stderr)

    rows.sort(key=lambda r: r[0])
    width = max(len(n) for _, n, _ in rows)

    lines: list[str] = []
    lines.append("/* Auto-generated by tools/gen_symbols_header.py — do not edit. */")
    lines.append(f"/* Source: {args.symbols} (validated vs globals.toml / symbols.toml). */")
    lines.append("#pragma once")
    lines.append("")
    lines.append("/* PSX vaddr constants for the native-renderer feeders. These are raw")
    lines.append(" * integers fed to cpu->read_word(); they are deliberately NOT the linked")
    lines.append(" * decomp symbols (g_Camera etc.), which a #define would clobber. */")
    lines.append("")
    for addr, name, comment in rows:
        lines.append(f"#define {name:<{width}} 0x{addr:08X}u  /* {comment} */")
    lines.append("")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"gen_symbols_header: wrote {len(rows)} symbols -> {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
