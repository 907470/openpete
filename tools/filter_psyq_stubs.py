#!/usr/bin/env python3
"""Emit the PSYQ abort-on-call stubs that no thunk source defines.

Usage:
    filter_psyq_stubs.py STUBS_C OUTPUT_C SOURCE...

STUBS_C is the generated psyq_stubs.c (tools/gen_psyq_stubs.py): one
`OPENPETE_WEAK void psyq_NAME(CPUState* cpu) { ... }` line per manifest
symbol. SOURCE... are the executable's C/C++ translation units. A stub
whose name a source defines as `void psyq_NAME(CPUState* ...) {` is
dropped; every other stub is written without the weak attribute.

Every surviving stub is a strong definition, so a thunk this scan misses
is a multiple-definition error at link time on every platform, and a
name the scan matches that no translation unit compiles is an undefined
reference. The executable therefore links with no
--allow-multiple-definition and resolves each symbol the same way on ELF
and PE.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

STUB_RE = re.compile(r"^OPENPETE_WEAK (void (psyq_\w+)\(CPUState\* cpu\) \{.*\})\s*$")
DEF_RE = re.compile(r"\bvoid\s+(psyq_\w+)\s*\(\s*CPUState\s*\*\s*\w*\s*\)\s*\{")

HEADER = """\
/* Generated by tools/filter_psyq_stubs.py from {stubs} -- do not edit.
 *
 * The abort-on-call stubs for the PSYQ symbols no thunk defines, as strong
 * definitions. The {n_drop} stubs a thunk defines are omitted. The real
 * fprintf+abort body lives in psyq_stub_runtime.c; no libc header is
 * included, since PSYQ exports stdlib names (printf, strlen, rand, ...)
 * whose stubs would collide with libc's prototypes.
 */

#include "psx_runtime_internal.h"

extern void psyq_stub_hit(const char* name, uint32_t addr, CPUState* cpu);

"""


def defined_names(sources: list[Path]) -> set[str]:
    """Return the psyq_ names the sources define with the thunk signature."""
    names: set[str] = set()
    for src in sources:
        names.update(DEF_RE.findall(src.read_text(errors="replace")))
    return names


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    stubs, output = Path(sys.argv[1]), Path(sys.argv[2])
    sources = [Path(s) for s in sys.argv[3:]
               if s.endswith((".c", ".cpp")) and Path(s).is_file()]
    thunked = defined_names(sources)
    body: list[str] = []
    n_stub = n_drop = 0
    for line in stubs.read_text().splitlines(keepends=True):
        m = STUB_RE.match(line)
        if not m:
            continue
        n_stub += 1
        if m.group(2) in thunked:
            n_drop += 1
            continue
        body.append(m.group(1) + "\n")
    if n_stub == 0:
        print(f"filter_psyq_stubs: no stub lines in {stubs}", file=sys.stderr)
        return 1
    text = HEADER.format(stubs=stubs.name, n_drop=n_drop) + "".join(body)
    if not output.exists() or output.read_text() != text:
        output.write_text(text)
    print(f"filter_psyq_stubs: {n_stub - n_drop} stubs kept, {n_drop} "
          f"defined by thunks ({len(sources)} sources scanned)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
