#!/usr/bin/env python3
"""Generate the func-trace symtab TU (OPENPETE_FUNC_TRACE builds).

Parses a recompiler dispatch file's case table (`case 0xADDRu: func_ADDR(cpu);`)
for the set of instrumented functions, joins manifest/symbols.toml for human
names, and emits a C file defining op_func_symtab[] / op_func_symtab_count —
the pointer→name table func_trace.c resolves the -finstrument-functions hooks
against.

Usage:
  gen_func_trace_symtab.py --dispatch PSX.EXE_dispatch.c --symbols symbols.toml
                           --out func_trace_symtab.c
"""
import argparse
import re
import sys

CASE_RE = re.compile(r"case\s+0x([0-9a-fA-F]+)u?\s*:\s*(func_[0-9a-fA-F]+)\s*\(")


def parse_dispatch(path):
    """Return ordered list of (addr:int, funcname:str), de-duplicated."""
    seen = set()
    out = []
    with open(path, errors="replace") as f:
        for line in f:
            m = CASE_RE.search(line)
            if not m:
                continue
            addr = int(m.group(1), 16)
            fn = m.group(2)
            if fn in seen:
                continue
            seen.add(fn)
            out.append((addr, fn))
    return out


def parse_symbols(path):
    """addr:int -> name:str from the [[function]] blocks of symbols.toml."""
    names = {}
    cur_addr = None
    with open(path, errors="replace") as f:
        for line in f:
            s = line.strip()
            if s.startswith("[[function]]"):
                cur_addr = None
            elif s.startswith("addr"):
                m = re.search(r"0x([0-9a-fA-F]+)", s)
                if m:
                    cur_addr = int(m.group(1), 16)
            elif s.startswith("name") and cur_addr is not None:
                m = re.search(r'name\s*=\s*"([^"]*)"', s)
                if m:
                    names[cur_addr] = m.group(1)
    return names


def c_ident_ok(name):
    return re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", name) is not None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dispatch", required=True)
    ap.add_argument("--symbols", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    funcs = parse_dispatch(args.dispatch)
    names = parse_symbols(args.symbols)

    lines = [
        "/* Auto-generated by tools/gen_func_trace_symtab.py — do not edit. */",
        '#include "openpete_func_trace.h"',
        "",
        "/* Forward declarations (unspecified params: only the address is used). */",
    ]
    for _addr, fn in funcs:
        lines.append("extern void %s();" % fn)
    lines.append("")
    lines.append("static const op_func_sym_t k_symtab[] = {")
    for addr, fn in funcs:
        nm = names.get(addr, fn)
        nm = nm.replace("\\", "\\\\").replace('"', '\\"')
        lines.append('    { (const void*)&%s, 0x%08xu, "%s" },' % (fn, addr, nm))
    lines.append("};")
    lines.append("")
    lines.append("/* Register at startup (portable across ELF/PE — no weak symbols). */")
    lines.append("__attribute__((constructor)) static void op_functrace_symtab_register(void) {")
    lines.append("    op_functrace_register_symtab(k_symtab, %d);" % len(funcs))
    lines.append("}")
    lines.append("")

    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print("gen_func_trace_symtab: %d functions -> %s" % (len(funcs), args.out),
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
