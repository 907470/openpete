#!/usr/bin/env python3
"""Write the X-macro list of the Vulkan entry points an object references through volk's function pointers.

usage: gen_vk_list.py <nm> <object.o> <vk_list.h>

Each undefined symbol of the object named vk* becomes one X(vkName) line,
sorted, so the fake device defines exactly the pointers the RHI uses and a
newly referenced entry point gets a trap without a source change.
"""

import subprocess
import sys


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    nm, obj, out = sys.argv[1:]
    text = subprocess.run([nm, "-u", obj], check=True, capture_output=True, text=True).stdout
    names = sorted({line.split()[-1] for line in text.splitlines()
                    if line.split() and line.split()[-1].startswith("vk")})
    if not names:
        raise SystemExit("gen_vk_list: %s references no vk* symbol" % obj)
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* Generated by tests/sched/present/gen_vk_list.py from %s; do not edit. */\n" % obj)
        f.write("".join("X(%s)\n" % n for n in names))


if __name__ == "__main__":
    main()
